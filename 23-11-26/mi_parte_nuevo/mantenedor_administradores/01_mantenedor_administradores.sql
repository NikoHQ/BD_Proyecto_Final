CREATE OR REPLACE PROCEDURE SGCD_CREAR_ADMINISTRADOR (
    ID_USUARIO_P SGCD_ADMINISTRADORES.ID_USUARIO%TYPE,
    NOMBRE_ADMINISTRADOR_P SGCD_ADMINISTRADORES.NOMBRE_ADMINISTRADOR%TYPE,
    ESTADO_ADMINISTRADOR_P SGCD_ADMINISTRADORES.ESTADO_ADMINISTRADOR%TYPE,
    ID_ADMINISTRADOR_P OUT SGCD_ADMINISTRADORES.ID_ADMINISTRADOR%TYPE
)
IS

    ROL_V SGCD_USUARIOS.ROL%TYPE;

BEGIN

    IF TRIM(NOMBRE_ADMINISTRADOR_P) IS NULL OR ESTADO_ADMINISTRADOR_P IS NULL
       OR ESTADO_ADMINISTRADOR_P NOT IN ('ACTIVO', 'INACTIVO') THEN
        RAISE_APPLICATION_ERROR(-20860, 'Revise el nombre y el estado');

    END IF;

    SELECT ROL INTO ROL_V FROM SGCD_USUARIOS
    WHERE ID_USUARIO = ID_USUARIO_P FOR UPDATE;

    IF ROL_V IS NULL OR ROL_V <> 'ADMINISTRADOR' THEN
        RAISE_APPLICATION_ERROR(-20861, 'La cuenta debe tener rol de administrador');
    END IF;

    INSERT INTO SGCD_ADMINISTRADORES (ID_USUARIO, NOMBRE_ADMINISTRADOR, ESTADO_ADMINISTRADOR)
    VALUES (ID_USUARIO_P, TRIM(NOMBRE_ADMINISTRADOR_P), ESTADO_ADMINISTRADOR_P)
    RETURNING ID_ADMINISTRADOR INTO ID_ADMINISTRADOR_P;


EXCEPTION


    WHEN DUP_VAL_ON_INDEX THEN
        RAISE_APPLICATION_ERROR(-20863, 'El registro ya existe');
    WHEN NO_DATA_FOUND THEN
        RAISE_APPLICATION_ERROR(-20861, 'La cuenta no existe');
END;
/

CREATE OR REPLACE PROCEDURE SGCD_LISTAR_ADMINISTRADORES (
    RESULTADO_P OUT SYS_REFCURSOR
) IS

BEGIN

    OPEN RESULTADO_P FOR
        SELECT ID_ADMINISTRADOR, ID_USUARIO, NOMBRE_ADMINISTRADOR, ESTADO_ADMINISTRADOR
        FROM SGCD_ADMINISTRADORES
        ORDER BY NOMBRE_ADMINISTRADOR, ID_ADMINISTRADOR;
END;
/

CREATE OR REPLACE PROCEDURE SGCD_ACTUALIZAR_ADMINISTRADOR (
    ID_ADMINISTRADOR_P SGCD_ADMINISTRADORES.ID_ADMINISTRADOR%TYPE,
    NOMBRE_ADMINISTRADOR_P SGCD_ADMINISTRADORES.NOMBRE_ADMINISTRADOR%TYPE,
    ESTADO_ADMINISTRADOR_P SGCD_ADMINISTRADORES.ESTADO_ADMINISTRADOR%TYPE
)
IS

BEGIN

    IF TRIM(NOMBRE_ADMINISTRADOR_P) IS NULL OR ESTADO_ADMINISTRADOR_P IS NULL
       OR ESTADO_ADMINISTRADOR_P NOT IN ('ACTIVO', 'INACTIVO') THEN
        RAISE_APPLICATION_ERROR(-20860, 'Revise el nombre y el estado');
    END IF;

    UPDATE SGCD_ADMINISTRADORES
    SET NOMBRE_ADMINISTRADOR = TRIM(NOMBRE_ADMINISTRADOR_P),
        ESTADO_ADMINISTRADOR = ESTADO_ADMINISTRADOR_P
    WHERE ID_ADMINISTRADOR = ID_ADMINISTRADOR_P;

    IF SQL%ROWCOUNT = 0 THEN
        RAISE_APPLICATION_ERROR(-20862, 'El registro no existe');
    END IF;

EXCEPTION


    WHEN DUP_VAL_ON_INDEX THEN
        RAISE_APPLICATION_ERROR(-20863, 'El registro ya existe');
END;
/

CREATE OR REPLACE PROCEDURE SGCD_BORRAR_ADMINISTRADOR (
    ID_ADMINISTRADOR_P SGCD_ADMINISTRADORES.ID_ADMINISTRADOR%TYPE
)
IS

BEGIN

    DELETE FROM SGCD_ADMINISTRADORES WHERE ID_ADMINISTRADOR = ID_ADMINISTRADOR_P;

    IF SQL%ROWCOUNT = 0 THEN
        RAISE_APPLICATION_ERROR(-20862, 'El registro no existe');
    END IF;
    

EXCEPTION


    WHEN OTHERS THEN
        IF SQLCODE = -2292 THEN
            RAISE_APPLICATION_ERROR(-20864, 'El registro está en uso');
        END IF;
        RAISE;
END;
/

