-- La asociación se identifica con la cancha y la modalidad.
CREATE OR REPLACE PROCEDURE SGCD_CREAR_CANCHA_MODALIDAD (
    ID_CANCHA_P SGCD_CANCHAS_MODALIDADES.ID_CANCHA%TYPE,
    ID_MODALIDAD_P SGCD_CANCHAS_MODALIDADES.ID_MODALIDAD%TYPE
)
IS

BEGIN

    INSERT INTO SGCD_CANCHAS_MODALIDADES (ID_CANCHA, ID_MODALIDAD)
    VALUES (ID_CANCHA_P, ID_MODALIDAD_P);

EXCEPTION

    WHEN DUP_VAL_ON_INDEX THEN
        RAISE_APPLICATION_ERROR(-20850, 'La cancha ya admite esa modalidad');
END;
/

CREATE OR REPLACE PROCEDURE SGCD_LISTAR_CANCHA_MODALIDAD (
    ID_CANCHA_P SGCD_CANCHAS_MODALIDADES.ID_CANCHA%TYPE,
    MODALIDADES_P OUT SYS_REFCURSOR
)
IS

BEGIN

    OPEN MODALIDADES_P FOR
        SELECT CM.ID_CANCHA, CM.ID_MODALIDAD, M.NOMBRE_MODALIDAD
        FROM SGCD_CANCHAS_MODALIDADES CM
        JOIN SGCD_MODALIDADES M ON M.ID_MODALIDAD = CM.ID_MODALIDAD
        WHERE CM.ID_CANCHA = ID_CANCHA_P
        ORDER BY M.NOMBRE_MODALIDAD, CM.ID_MODALIDAD;
END;
/

CREATE OR REPLACE PROCEDURE SGCD_ACTUALIZAR_CANCHA_MODALIDAD (
    ID_CANCHA_P SGCD_CANCHAS_MODALIDADES.ID_CANCHA%TYPE,
    ID_MODALIDAD_P SGCD_CANCHAS_MODALIDADES.ID_MODALIDAD%TYPE,
    ID_MODALIDAD_NUEVA_P SGCD_CANCHAS_MODALIDADES.ID_MODALIDAD%TYPE
)
IS

BEGIN

    UPDATE SGCD_CANCHAS_MODALIDADES
    SET ID_MODALIDAD = ID_MODALIDAD_NUEVA_P
    WHERE ID_CANCHA = ID_CANCHA_P
      AND ID_MODALIDAD = ID_MODALIDAD_P;

    IF SQL%ROWCOUNT = 0 THEN
        RAISE_APPLICATION_ERROR(-20851, 'La asociación no existe');
    END IF;

EXCEPTION

    WHEN DUP_VAL_ON_INDEX THEN
        RAISE_APPLICATION_ERROR(-20850, 'La cancha ya admite esa modalidad');
END;
/

CREATE OR REPLACE PROCEDURE SGCD_BORRAR_CANCHA_MODALIDAD (
    ID_CANCHA_P SGCD_CANCHAS_MODALIDADES.ID_CANCHA%TYPE,
    ID_MODALIDAD_P SGCD_CANCHAS_MODALIDADES.ID_MODALIDAD%TYPE
)
IS

BEGIN

    DELETE FROM SGCD_CANCHAS_MODALIDADES
    WHERE ID_CANCHA = ID_CANCHA_P
      AND ID_MODALIDAD = ID_MODALIDAD_P;

    IF SQL%ROWCOUNT = 0 THEN
        RAISE_APPLICATION_ERROR(-20851, 'La asociación no existe');
    END IF;
END;
/

