-- El esquema genera el ID. La aplicación controla la transacción.

CREATE OR REPLACE PROCEDURE SGCD_CREAR_MODALIDAD (
    ID_DEPORTE_P SGCD_MODALIDADES.ID_DEPORTE%TYPE,
    MAX_JUGADORES_POR_EQUIPO_P SGCD_MODALIDADES.MAX_JUGADORES_POR_EQUIPO%TYPE,
    NOMBRE_MODALIDAD_P SGCD_MODALIDADES.NOMBRE_MODALIDAD%TYPE,
    ID_MODALIDAD_P OUT SGCD_MODALIDADES.ID_MODALIDAD%TYPE
)
IS

BEGIN

    IF TRIM(NOMBRE_MODALIDAD_P) IS NULL THEN
        RAISE_APPLICATION_ERROR(-20830, 'Ingrese un nombre');
    END IF;

    IF MAX_JUGADORES_POR_EQUIPO_P IS NULL
       OR MAX_JUGADORES_POR_EQUIPO_P < 1
       OR MAX_JUGADORES_POR_EQUIPO_P <> TRUNC(MAX_JUGADORES_POR_EQUIPO_P) THEN
        RAISE_APPLICATION_ERROR(-20831, 'Ingrese una cantidad entera mayor que cero');
    END IF;

    INSERT INTO SGCD_MODALIDADES (ID_DEPORTE, MAX_JUGADORES_POR_EQUIPO, NOMBRE_MODALIDAD, ESTADO_MODALIDAD)
    VALUES (ID_DEPORTE_P, MAX_JUGADORES_POR_EQUIPO_P, TRIM(NOMBRE_MODALIDAD_P), 'ACTIVO')
    RETURNING ID_MODALIDAD INTO ID_MODALIDAD_P;

EXCEPTION

    WHEN DUP_VAL_ON_INDEX THEN
        RAISE_APPLICATION_ERROR(-20833, 'Ya existe un registro con ese nombre');
END;
/

CREATE OR REPLACE PROCEDURE SGCD_LISTAR_MODALIDADES (
    RESULTADO_P OUT SYS_REFCURSOR
)
IS

BEGIN

    OPEN RESULTADO_P FOR
        SELECT ID_MODALIDAD, ID_DEPORTE, MAX_JUGADORES_POR_EQUIPO, NOMBRE_MODALIDAD, ESTADO_MODALIDAD
        FROM SGCD_MODALIDADES
        ORDER BY NOMBRE_MODALIDAD, ID_MODALIDAD;
END;
/

CREATE OR REPLACE PROCEDURE SGCD_ACTUALIZAR_MODALIDAD (
    ID_MODALIDAD_P SGCD_MODALIDADES.ID_MODALIDAD%TYPE,
    ID_DEPORTE_P SGCD_MODALIDADES.ID_DEPORTE%TYPE,
    MAX_JUGADORES_POR_EQUIPO_P SGCD_MODALIDADES.MAX_JUGADORES_POR_EQUIPO%TYPE,
    NOMBRE_MODALIDAD_P SGCD_MODALIDADES.NOMBRE_MODALIDAD%TYPE,
    ESTADO_MODALIDAD_P SGCD_MODALIDADES.ESTADO_MODALIDAD%TYPE
)
IS

BEGIN

    IF TRIM(NOMBRE_MODALIDAD_P) IS NULL THEN
        RAISE_APPLICATION_ERROR(-20830, 'Ingrese un nombre');
    END IF;

    IF MAX_JUGADORES_POR_EQUIPO_P IS NULL
       OR MAX_JUGADORES_POR_EQUIPO_P < 1
       OR MAX_JUGADORES_POR_EQUIPO_P <> TRUNC(MAX_JUGADORES_POR_EQUIPO_P) THEN
        RAISE_APPLICATION_ERROR(-20831, 'Ingrese una cantidad entera mayor que cero');
    END IF;

    IF ESTADO_MODALIDAD_P IS NULL OR ESTADO_MODALIDAD_P NOT IN ('ACTIVO', 'INACTIVO') THEN
        RAISE_APPLICATION_ERROR(-20834, 'El estado debe ser ACTIVO o INACTIVO');
    END IF;

    UPDATE SGCD_MODALIDADES
    SET ID_DEPORTE = ID_DEPORTE_P,
        MAX_JUGADORES_POR_EQUIPO = MAX_JUGADORES_POR_EQUIPO_P,
        NOMBRE_MODALIDAD = TRIM(NOMBRE_MODALIDAD_P),
        ESTADO_MODALIDAD = ESTADO_MODALIDAD_P
    WHERE ID_MODALIDAD = ID_MODALIDAD_P;

    IF SQL%ROWCOUNT = 0 THEN
        RAISE_APPLICATION_ERROR(-20832, 'El registro no existe');
    END IF;

EXCEPTION

    WHEN DUP_VAL_ON_INDEX THEN
        RAISE_APPLICATION_ERROR(-20833, 'Ya existe un registro con ese nombre');
END;
/

CREATE OR REPLACE PROCEDURE SGCD_BORRAR_MODALIDAD (
    ID_MODALIDAD_P SGCD_MODALIDADES.ID_MODALIDAD%TYPE
)
IS

BEGIN

    DELETE FROM SGCD_MODALIDADES WHERE ID_MODALIDAD = ID_MODALIDAD_P;

    IF SQL%ROWCOUNT = 0 THEN
        RAISE_APPLICATION_ERROR(-20832, 'El registro no existe');
    END IF;

EXCEPTION

    WHEN OTHERS THEN
        IF SQLCODE = -2292 THEN
            RAISE_APPLICATION_ERROR(-20835, 'El registro está en uso. Puede desactivarlo');
        END IF;
        RAISE;
END;
/

