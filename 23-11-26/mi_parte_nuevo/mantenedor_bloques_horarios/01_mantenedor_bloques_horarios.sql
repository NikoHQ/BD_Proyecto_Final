-- Validación compartida para crear y editar bloques de la plantilla semanal.
CREATE OR REPLACE PROCEDURE SGCD_VALIDAR_BLOQUE_HORARIO (
    ID_HORARIO_P NUMBER,
    HORA_INICIO_P VARCHAR2,
    HORA_TERMINO_P VARCHAR2,
    ID_BLOQUE_P NUMBER
) 
IS

    APERTURA_V SGCD_HORARIOS.HORA_APERTURA_HORARIO%TYPE;
    CIERRE_V SGCD_HORARIOS.HORA_CIERRE_HORARIO%TYPE;
    COINCIDENCIAS_V NUMBER;

BEGIN

    IF HORA_INICIO_P IS NULL OR HORA_TERMINO_P IS NULL
       OR NOT REGEXP_LIKE(HORA_INICIO_P, '^([01][0-9]|2[0-3]):[0-5][0-9]$')
       OR NOT REGEXP_LIKE(HORA_TERMINO_P, '^([01][0-9]|2[0-3]):[0-5][0-9]$') THEN
        RAISE_APPLICATION_ERROR(-20821, 'Ingrese las horas en formato HH:MI');
    END IF;

    IF (TO_NUMBER(SUBSTR(HORA_TERMINO_P, 1, 2)) -
        TO_NUMBER(SUBSTR(HORA_INICIO_P, 1, 2))) * 60 +
        TO_NUMBER(SUBSTR(HORA_TERMINO_P, 4, 2)) -
        TO_NUMBER(SUBSTR(HORA_INICIO_P, 4, 2)) <> 60 THEN
        RAISE_APPLICATION_ERROR(-20822, 'El bloque debe durar una hora');
    END IF;

    -- Se bloquea el horario para que dos altas simultáneas no se solapen.
    SELECT HORA_APERTURA_HORARIO, HORA_CIERRE_HORARIO
    INTO APERTURA_V, CIERRE_V FROM SGCD_HORARIOS
    WHERE ID_HORARIO = ID_HORARIO_P
    FOR UPDATE;

    IF HORA_INICIO_P < APERTURA_V OR HORA_TERMINO_P > CIERRE_V THEN
        RAISE_APPLICATION_ERROR(-20823, 'El bloque queda fuera del horario del recinto');
    END IF;

    SELECT COUNT(*) INTO COINCIDENCIAS_V FROM SGCD_BLOQUES_HORARIOS
    WHERE ID_HORARIO = ID_HORARIO_P
      AND (ID_BLOQUE_P IS NULL OR ID_BLOQUE_HORARIO <> ID_BLOQUE_P)
      AND HORA_INICIO < HORA_TERMINO_P
      AND HORA_TERMINO > HORA_INICIO_P;

    IF COINCIDENCIAS_V > 0 THEN
        RAISE_APPLICATION_ERROR(-20824, 'El bloque se solapa con otro del mismo horario');
    END IF;

EXCEPTION

    WHEN NO_DATA_FOUND THEN
        RAISE_APPLICATION_ERROR(-20820, 'El horario no existe');
END;
/

CREATE OR REPLACE PROCEDURE SGCD_CREAR_BLOQUE_HORARIO (
    ID_HORARIO_P NUMBER,
    HORA_INICIO_P VARCHAR2,
    HORA_TERMINO_P VARCHAR2,
    ID_BLOQUE_P OUT NUMBER
) 

IS

BEGIN
    SGCD_VALIDAR_BLOQUE_HORARIO(ID_HORARIO_P, HORA_INICIO_P, HORA_TERMINO_P, NULL);

    INSERT INTO SGCD_BLOQUES_HORARIOS (ID_HORARIO, HORA_INICIO, HORA_TERMINO)
    VALUES (ID_HORARIO_P, HORA_INICIO_P, HORA_TERMINO_P)
    RETURNING ID_BLOQUE_HORARIO INTO ID_BLOQUE_P;
END;
/

CREATE OR REPLACE PROCEDURE SGCD_LISTAR_BLOQUES_HORARIOS (
    ID_HORARIO_P NUMBER,
    BLOQUES_P OUT SYS_REFCURSOR
) IS

BEGIN
    OPEN BLOQUES_P FOR
        SELECT ID_BLOQUE_HORARIO, HORA_INICIO, HORA_TERMINO
        FROM SGCD_BLOQUES_HORARIOS
        WHERE ID_HORARIO = ID_HORARIO_P
        ORDER BY HORA_INICIO, ID_BLOQUE_HORARIO;
END;
/

CREATE OR REPLACE PROCEDURE SGCD_ACTUALIZAR_BLOQUE_HORARIO (
    ID_BLOQUE_P NUMBER,
    HORA_INICIO_P VARCHAR2,
    HORA_TERMINO_P VARCHAR2
) IS
    ID_HORARIO_V SGCD_BLOQUES_HORARIOS.ID_HORARIO%TYPE;
BEGIN
    SELECT ID_HORARIO INTO ID_HORARIO_V FROM SGCD_BLOQUES_HORARIOS
    WHERE ID_BLOQUE_HORARIO = ID_BLOQUE_P;

    SGCD_VALIDAR_BLOQUE_HORARIO(ID_HORARIO_V, HORA_INICIO_P, HORA_TERMINO_P, ID_BLOQUE_P);

    UPDATE SGCD_BLOQUES_HORARIOS
    SET HORA_INICIO = HORA_INICIO_P, HORA_TERMINO = HORA_TERMINO_P
    WHERE ID_BLOQUE_HORARIO = ID_BLOQUE_P AND ID_HORARIO = ID_HORARIO_V;

    IF SQL%ROWCOUNT = 0 THEN
        RAISE_APPLICATION_ERROR(-20825, 'El bloque no existe');
    END IF;

EXCEPTION

    WHEN NO_DATA_FOUND THEN
        RAISE_APPLICATION_ERROR(-20825, 'El bloque no existe');
END;
/

CREATE OR REPLACE PROCEDURE SGCD_BORRAR_BLOQUE_HORARIO (
    ID_BLOQUE_P NUMBER
) 
IS

BEGIN

    DELETE FROM SGCD_BLOQUES_HORARIOS
    WHERE ID_BLOQUE_HORARIO = ID_BLOQUE_P;

    IF SQL%ROWCOUNT = 0 THEN
        RAISE_APPLICATION_ERROR(-20825, 'El bloque no existe');
    END IF;
END;
/
