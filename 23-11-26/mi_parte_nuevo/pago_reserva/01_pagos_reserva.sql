-- Calcular el saldo y registrar pagos de una reserva.
-- Nico confirma o revierte la transaccion desde PHP.

CREATE OR REPLACE FUNCTION SGCD_SALDO_RESERVA (
    ID_RESERVA_F RESERVA.ID_RESERVA%TYPE
)
RETURN NUMBER

IS
    IMPORTE_RESERVA_V RESERVA.IMPORTE_ACORDADO%TYPE;
    TOTAL_PAGADO_V PAGO.IMPORTE_PAGO%TYPE;
    SALDO_V NUMBER;

BEGIN

    IF ID_RESERVA_F IS NULL
       OR ID_RESERVA_F <= 0
       OR ID_RESERVA_F <> TRUNC(ID_RESERVA_F) THEN
        RAISE_APPLICATION_ERROR(
            -20201,
            'EL ID DE LA RESERVA DEBE SER UN ENTERO MAYOR QUE CERO'
        );
    END IF;

    SELECT IMPORTE_ACORDADO INTO IMPORTE_RESERVA_V FROM RESERVA
    WHERE ID_RESERVA = ID_RESERVA_F;

    SELECT NVL(SUM(IMPORTE_PAGO), 0) INTO TOTAL_PAGADO_V FROM PAGO
    WHERE ID_RESERVA = ID_RESERVA_F;

    SALDO_V := IMPORTE_RESERVA_V - TOTAL_PAGADO_V;

    RETURN SALDO_V;

EXCEPTION
    WHEN NO_DATA_FOUND THEN
        RAISE_APPLICATION_ERROR(
            -20202,
            'LA RESERVA NO EXISTE'
        );

END;
/


CREATE OR REPLACE PROCEDURE SGCD_REGISTRAR_PAGO_RESERVA (
    ID_RESERVA_P RESERVA.ID_RESERVA%TYPE,
    IMPORTE_PAGO_P PAGO.IMPORTE_PAGO%TYPE,
    MEDIO_PAGO_P PAGO.MEDIO_PAGO%TYPE
)

IS
    ESTADO_RESERVA_V RESERVA.ESTADO_RESERVA%TYPE;
    MEDIO_PAGO_V PAGO.MEDIO_PAGO%TYPE;
    IMPORTE_ACORDADO_V RESERVA.IMPORTE_ACORDADO%TYPE;
    PAGOS_EXISTENTES_V NUMBER;

BEGIN

    IF ID_RESERVA_P IS NULL
       OR ID_RESERVA_P <= 0
       OR ID_RESERVA_P <> TRUNC(ID_RESERVA_P) THEN
        RAISE_APPLICATION_ERROR(
            -20201,
            'EL ID DE LA RESERVA DEBE SER UN ENTERO MAYOR QUE CERO'
        );
    END IF;

    IF IMPORTE_PAGO_P IS NULL OR IMPORTE_PAGO_P <= 0 THEN
        RAISE_APPLICATION_ERROR(
            -20204,
            'EL IMPORTE DEL PAGO DEBE SER MAYOR QUE CERO'
        );
    END IF;

    MEDIO_PAGO_V := UPPER(TRIM(MEDIO_PAGO_P));

    IF MEDIO_PAGO_V IS NULL
       OR MEDIO_PAGO_V NOT IN (
           'EFECTIVO',
           'DEBITO',
           'CREDITO',
           'TRANSFERENCIA'
       ) THEN
        RAISE_APPLICATION_ERROR(
            -20205,
            'EL MEDIO DE PAGO NO ES VALIDO'
        );
    END IF;

    -- Bloquear la reserva evita que dos pagos usen el mismo saldo.
    SELECT ESTADO_RESERVA, IMPORTE_ACORDADO
    INTO ESTADO_RESERVA_V, IMPORTE_ACORDADO_V
    FROM RESERVA
    WHERE ID_RESERVA = ID_RESERVA_P
    FOR UPDATE;

    IF ESTADO_RESERVA_V = 'CANCELADA' THEN
        RAISE_APPLICATION_ERROR(
            -20203,
            'NO SE PUEDE PAGAR UNA RESERVA CANCELADA'
        );
    END IF;

    SELECT COUNT(*) INTO PAGOS_EXISTENTES_V FROM PAGO
    WHERE ID_RESERVA = ID_RESERVA_P;

    IF PAGOS_EXISTENTES_V > 0 THEN
        RAISE_APPLICATION_ERROR(-20207, 'LA RESERVA YA TIENE UN PAGO');
    END IF;

    IF IMPORTE_ACORDADO_V IS NULL OR IMPORTE_PAGO_P <> IMPORTE_ACORDADO_V THEN
        RAISE_APPLICATION_ERROR(
            -20206,
            'EL IMPORTE DEBE COINCIDIR CON EL TOTAL DE LA RESERVA'
        );
    END IF;

    INSERT INTO PAGO (
        ID_RESERVA,
        IMPORTE_PAGO,
        MEDIO_PAGO,
        FECHA_PAGO,
        ESTADO_PAGO
    ) VALUES (
        ID_RESERVA_P,
        IMPORTE_PAGO_P,
        MEDIO_PAGO_V,
        SYSDATE,
        'PAGADO'
    );

EXCEPTION
    WHEN NO_DATA_FOUND THEN
        RAISE_APPLICATION_ERROR(
            -20202,
            'LA RESERVA NO EXISTE'
        );

END;
/

