-- Comparar los resultados:
-- 1: una fila EFECTIVO, CANTIDAD_PAGOS=2 y TOTAL_COBRADO=200. No incluye el pago futuro.
-- 2: CANCHA PRUEBA con CANTIDAD_RESERVAS=2; no aparece CANCHA SIN RESERVAS.
-- 3: CLIENTE REPORTE con CANTIDAD_RESERVAS=2; no aparece CLIENTE SIN RESERVAS.
ROLLBACK;

-- Despues del ROLLBACK, los tres reportes deben quedar vacios.
