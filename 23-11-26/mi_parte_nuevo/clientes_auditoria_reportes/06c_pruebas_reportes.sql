-- Preparar datos para probar los tres reportes.
-- Usar una conexion de pruebas, sin otros cambios pendientes.
-- Ejecutar con F5 desde esta carpeta. Al final se revierten los datos.
-- Para comparar resultados, los ultimos 30 dias deben estar sin operaciones.

SET SERVEROUTPUT ON
WHENEVER SQLERROR EXIT FAILURE ROLLBACK

DECLARE
    RUT_V NUMBER;
    CLIENTE_V NUMBER;
    RECINTO_V NUMBER;
    DEPORTE_V NUMBER;
    MODALIDAD_V NUMBER;
    CANCHA_V NUMBER;
    RESERVA_V NUMBER;
    CANTIDAD_V NUMBER;
    FECHA_V DATE := SYSDATE - 1;

BEGIN

    SELECT COUNT(*) INTO CANTIDAD_V FROM SGCD_PAGOS
    WHERE FECHA_PAGO >= SYSDATE - 30 AND FECHA_PAGO < SYSDATE;

    IF CANTIDAD_V <> 0 THEN
        RAISE_APPLICATION_ERROR(
            -20995,
            'REPORTE REQUIERE RANGO SIN PAGOS PREVIOS'
        );
    END IF;

    SELECT COUNT(*) INTO CANTIDAD_V FROM SGCD_RESERVAS
    WHERE INICIO_RESERVA >= SYSDATE - 30 AND INICIO_RESERVA < SYSDATE;

    IF CANTIDAD_V <> 0 THEN
        RAISE_APPLICATION_ERROR(
            -20995,
            'REPORTE REQUIERE RANGO SIN RESERVAS PREVIAS'
        );
    END IF;

    SELECT NVL(MAX(RUT_CLIENTE), 0) + 1
    INTO RUT_V
    FROM SGCD_CLIENTES;

    IF RUT_V + 1 > 99999999 THEN
        RAISE_APPLICATION_ERROR(
            -20990,
            'REVISAR RUT DE PRUEBA'
        );
    END IF;
    INSERT INTO SGCD_CLIENTES (RUT_CLIENTE, DV_CLIENTE, NOMBRE_CLIENTE)
    VALUES (RUT_V, '0', 'CLIENTE REPORTE ' || RUT_V);

    SELECT ID_CLIENTE INTO CLIENTE_V FROM SGCD_CLIENTES
    WHERE RUT_CLIENTE = RUT_V AND DV_CLIENTE = '0';

    INSERT INTO SGCD_CLIENTES (RUT_CLIENTE, DV_CLIENTE, NOMBRE_CLIENTE)
    VALUES (RUT_V + 1, '0', 'CLIENTE SIN RESERVAS ' || RUT_V);

    INSERT INTO SGCD_RECINTOS (NOMBRE_RECINTO, DIRECCION_RECINTO, COMUNA_RECINTO)
    VALUES ('RECINTO PRUEBA ' || RUT_V, 'DIRECCION PRUEBA', 'PRUEBA');

    SELECT ID_RECINTO INTO RECINTO_V FROM SGCD_RECINTOS
    WHERE NOMBRE_RECINTO = 'RECINTO PRUEBA ' || RUT_V AND COMUNA_RECINTO = 'PRUEBA';

    INSERT INTO SGCD_DEPORTES (NOMBRE_DEPORTE) 
    VALUES ('DEPORTE PRUEBA ' || RUT_V);

    SELECT ID_DEPORTE INTO DEPORTE_V FROM SGCD_DEPORTES
    WHERE NOMBRE_DEPORTE = 'DEPORTE PRUEBA ' || RUT_V;

    INSERT INTO SGCD_MODALIDADES (ID_DEPORTE, NOMBRE_MODALIDAD) 
    VALUES (DEPORTE_V, 'MODALIDAD PRUEBA');

    SELECT ID_MODALIDAD INTO MODALIDAD_V FROM SGCD_MODALIDADES
    WHERE ID_DEPORTE = DEPORTE_V AND NOMBRE_MODALIDAD = 'MODALIDAD PRUEBA';
    INSERT INTO SGCD_CANCHAS (ID_RECINTO, NOMBRE_CANCHA, TIPO_CANCHA) VALUES (RECINTO_V, 'CANCHA PRUEBA', 'CANCHA');

    SELECT ID_CANCHA INTO CANCHA_V FROM SGCD_CANCHAS
    WHERE ID_RECINTO = RECINTO_V AND NOMBRE_CANCHA = 'CANCHA PRUEBA';
    INSERT INTO SGCD_CANCHAS (ID_RECINTO, NOMBRE_CANCHA, TIPO_CANCHA) VALUES (RECINTO_V, 'CANCHA SIN RESERVAS', 'CANCHA');
    INSERT INTO SGCD_CANCHAS_MODALIDADES (ID_CANCHA, ID_MODALIDAD) VALUES (CANCHA_V, MODALIDAD_V);

    -- Agregar reservas y pagos para comparar los resultados.
    INSERT INTO SGCD_RESERVAS (ID_CLIENTE, ID_CANCHA, ID_MODALIDAD, ORIGEN_RESERVA,
        INICIO_RESERVA, TERMINO_RESERVA, IMPORTE_ACORDADO_RESERVA, ESTADO_RESERVA)
    VALUES (CLIENTE_V, CANCHA_V, MODALIDAD_V, 'WEB', FECHA_V, FECHA_V + 1/24, 1000, 'CONFIRMADA');

    SELECT ID_RESERVA INTO RESERVA_V FROM SGCD_RESERVAS
    WHERE ID_CLIENTE = CLIENTE_V AND ESTADO_RESERVA = 'CONFIRMADA';

    INSERT INTO SGCD_PAGOS (ID_RESERVA, FECHA_PAGO, IMPORTE_PAGO, MEDIO_PAGO)
    VALUES (RESERVA_V, FECHA_V, 100, 'EFECTIVO');

    INSERT INTO SGCD_PAGOS (ID_RESERVA, FECHA_PAGO, IMPORTE_PAGO, MEDIO_PAGO)
    VALUES (RESERVA_V, FECHA_V, 100, 'EFECTIVO');

    INSERT INTO SGCD_PAGOS (ID_RESERVA, FECHA_PAGO, IMPORTE_PAGO, MEDIO_PAGO)
    VALUES (RESERVA_V, FECHA_V + 2, 900, 'EFECTIVO');

    INSERT INTO SGCD_RESERVAS (ID_CLIENTE, ID_CANCHA, ID_MODALIDAD, ORIGEN_RESERVA,
        INICIO_RESERVA, TERMINO_RESERVA, IMPORTE_ACORDADO_RESERVA, ESTADO_RESERVA)
    VALUES (CLIENTE_V, CANCHA_V, MODALIDAD_V, 'WEB', FECHA_V + 2/24, FECHA_V + 3/24, 1000, 'COMPLETADA');
    
    INSERT INTO SGCD_RESERVAS (ID_CLIENTE, ID_CANCHA, ID_MODALIDAD, ORIGEN_RESERVA,
        INICIO_RESERVA, TERMINO_RESERVA, IMPORTE_ACORDADO_RESERVA, ESTADO_RESERVA)
    VALUES (CLIENTE_V, CANCHA_V, MODALIDAD_V, 'WEB', FECHA_V + 4/24, FECHA_V + 5/24, 1000, 'CANCELADA');
    
    INSERT INTO SGCD_RESERVAS (ID_CLIENTE, ID_CANCHA, ID_MODALIDAD, ORIGEN_RESERVA,
        INICIO_RESERVA, TERMINO_RESERVA, IMPORTE_ACORDADO_RESERVA, ESTADO_RESERVA)
    VALUES (CLIENTE_V, CANCHA_V, MODALIDAD_V, 'WEB', FECHA_V + 2, FECHA_V + 2 + 1/24, 1000, 'CONFIRMADA');

    -- Estos datos antiguos deben quedar fuera del reporte.
    INSERT INTO SGCD_PAGOS (ID_RESERVA, FECHA_PAGO, IMPORTE_PAGO, MEDIO_PAGO)
    VALUES (RESERVA_V, FECHA_V - 31, 800, 'EFECTIVO');
    
    INSERT INTO SGCD_RESERVAS (ID_CLIENTE, ID_CANCHA, ID_MODALIDAD, ORIGEN_RESERVA,
        INICIO_RESERVA, TERMINO_RESERVA, IMPORTE_ACORDADO_RESERVA, ESTADO_RESERVA)
    VALUES (CLIENTE_V, CANCHA_V, MODALIDAD_V, 'WEB', FECHA_V - 31, FECHA_V - 31 + 1/24, 1000, 'CONFIRMADA');
    DBMS_OUTPUT.PUT_LINE('DATOS PREPARADOS. Comparar los tres resultados que siguen con la guia.');

EXCEPTION
    WHEN OTHERS THEN
        ROLLBACK;
        RAISE;

END;
/

