-- Guardar los cambios y borrados de clientes.
-- Crear esta tabla y su secuencia una sola vez.

CREATE TABLE SGCD_AUDITORIA_CLIENTES (
    ID_AUDITORIA NUMBER(10),
    ID_CLIENTE NUMBER(10) NOT NULL,
    ACCION VARCHAR2(10) NOT NULL,
    FECHA_EVENTO DATE NOT NULL,
    NOMBRE_ANTERIOR VARCHAR2(4000),
    NOMBRE_NUEVO VARCHAR2(4000),
    TELEFONO_ANTERIOR VARCHAR2(4000),
    TELEFONO_NUEVO VARCHAR2(4000),
    CORREO_ANTERIOR VARCHAR2(4000),
    CORREO_NUEVO VARCHAR2(4000),
    CONSTRAINT PK_SGCD_AUDITORIA_CLIENTES PRIMARY KEY (ID_AUDITORIA)
);

-- Secuencia para el ID del registro.
CREATE SEQUENCE SGCD_SEQ_AUDITORIA_CLIENTES
START WITH 1
INCREMENT BY 1
MINVALUE 1
MAXVALUE 9999999999
NOCYCLE;

-- Asignar el ID.
CREATE OR REPLACE TRIGGER TRG_SGCD_AUD_CLIENTES_BI
BEFORE INSERT
ON SGCD_AUDITORIA_CLIENTES
FOR EACH ROW

BEGIN

    IF :NEW.ID_AUDITORIA IS NULL THEN
        :NEW.ID_AUDITORIA := SGCD_SEQ_AUDITORIA_CLIENTES.NEXTVAL;
    END IF;

END;
/

-- Registrar los datos que cambiaron.
CREATE OR REPLACE TRIGGER TRG_SGCD_CLIENTES_AU
AFTER UPDATE
ON SGCD_CLIENTES
FOR EACH ROW

BEGIN

    -- Revisar tambien cuando un dato se completa o se deja vacio.
    IF :OLD.NOMBRE_CLIENTE <> :NEW.NOMBRE_CLIENTE
       OR (:OLD.NOMBRE_CLIENTE IS NULL AND :NEW.NOMBRE_CLIENTE IS NOT NULL)
       OR (:OLD.NOMBRE_CLIENTE IS NOT NULL AND :NEW.NOMBRE_CLIENTE IS NULL)
       OR :OLD.TELEFONO_CLIENTE <> :NEW.TELEFONO_CLIENTE
       OR (:OLD.TELEFONO_CLIENTE IS NULL AND :NEW.TELEFONO_CLIENTE IS NOT NULL)
       OR (:OLD.TELEFONO_CLIENTE IS NOT NULL AND :NEW.TELEFONO_CLIENTE IS NULL)
       OR :OLD.CORREO_CLIENTE <> :NEW.CORREO_CLIENTE
       OR (:OLD.CORREO_CLIENTE IS NULL AND :NEW.CORREO_CLIENTE IS NOT NULL)
       OR (:OLD.CORREO_CLIENTE IS NOT NULL AND :NEW.CORREO_CLIENTE IS NULL) THEN
        INSERT INTO SGCD_AUDITORIA_CLIENTES (
            ID_CLIENTE, ACCION, FECHA_EVENTO, NOMBRE_ANTERIOR, NOMBRE_NUEVO,
            TELEFONO_ANTERIOR, TELEFONO_NUEVO, CORREO_ANTERIOR, CORREO_NUEVO)
        VALUES (:OLD.ID_CLIENTE, 'UPDATE', SYSDATE, :OLD.NOMBRE_CLIENTE, :NEW.NOMBRE_CLIENTE,
            :OLD.TELEFONO_CLIENTE, :NEW.TELEFONO_CLIENTE, :OLD.CORREO_CLIENTE, :NEW.CORREO_CLIENTE);
    END IF;

END;
/

-- Registrar el borrado de una ficha.
CREATE OR REPLACE TRIGGER TRG_SGCD_CLIENTES_AD
AFTER DELETE
ON SGCD_CLIENTES
FOR EACH ROW

BEGIN
    INSERT INTO SGCD_AUDITORIA_CLIENTES (
        ID_CLIENTE, ACCION, FECHA_EVENTO, NOMBRE_ANTERIOR, TELEFONO_ANTERIOR, CORREO_ANTERIOR)
    VALUES (:OLD.ID_CLIENTE, 'DELETE', SYSDATE, :OLD.NOMBRE_CLIENTE,
        :OLD.TELEFONO_CLIENTE, :OLD.CORREO_CLIENTE);

END;
/

