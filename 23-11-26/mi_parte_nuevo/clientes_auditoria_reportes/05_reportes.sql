-- Reportes de los ultimos 30 dias.
-- Nico debe ajustar las fechas al conectarlos con las pantallas.

-- 1. Total cobrado por dia y medio de pago.
SELECT TO_CHAR(FECHA_PAGO, 'YYYY-MM-DD') AS DIA,
       MEDIO_PAGO,
       COUNT(*) AS CANTIDAD_PAGOS,
       SUM(IMPORTE_PAGO) AS TOTAL_COBRADO
FROM SGCD_PAGOS
WHERE FECHA_PAGO >= SYSDATE - 30 AND FECHA_PAGO < SYSDATE
GROUP BY TO_CHAR(FECHA_PAGO, 'YYYY-MM-DD'), MEDIO_PAGO
ORDER BY DIA, MEDIO_PAGO;

-- 2. Reservas por cancha, sin contar las canceladas.
-- Solo aparecen las canchas que tienen reservas en el periodo.
SELECT c.ID_CANCHA, c.NOMBRE_CANCHA, COUNT(r.ID_RESERVA) AS CANTIDAD_RESERVAS
FROM SGCD_CANCHAS c JOIN SGCD_RESERVAS r ON (r.ID_CANCHA = c.ID_CANCHA)
WHERE r.INICIO_RESERVA >= SYSDATE - 30 AND r.INICIO_RESERVA < SYSDATE
  AND r.ESTADO_RESERVA <> 'CANCELADA'
GROUP BY c.ID_CANCHA, c.NOMBRE_CANCHA
ORDER BY CANTIDAD_RESERVAS DESC, c.ID_CANCHA;

-- 3. Clientes con mas reservas, sin contar las canceladas.
SELECT c.ID_CLIENTE, c.NOMBRE_CLIENTE, COUNT(r.ID_RESERVA) AS CANTIDAD_RESERVAS
FROM SGCD_CLIENTES c JOIN SGCD_RESERVAS r ON (r.ID_CLIENTE = c.ID_CLIENTE)
WHERE r.INICIO_RESERVA >= SYSDATE - 30 AND r.INICIO_RESERVA < SYSDATE
  AND r.ESTADO_RESERVA <> 'CANCELADA'
GROUP BY c.ID_CLIENTE, c.NOMBRE_CLIENTE
ORDER BY CANTIDAD_RESERVAS DESC, c.ID_CLIENTE;
