-- Actualizar los datos del cliente.

CREATE OR REPLACE PROCEDURE SGCD_ACTUALIZAR_FICHA_CLIENTE (
    ID_CLIENTE_P SGCD_CLIENTES.ID_CLIENTE%TYPE,
    NOMBRE_CLIENTE_P SGCD_CLIENTES.NOMBRE_CLIENTE%TYPE,
    TELEFONO_CLIENTE_P SGCD_CLIENTES.TELEFONO_CLIENTE%TYPE,
    CORREO_CLIENTE_P SGCD_CLIENTES.CORREO_CLIENTE%TYPE
)

IS
    CANTIDAD_V NUMBER;

BEGIN

    IF ID_CLIENTE_P IS NULL OR ID_CLIENTE_P <= 0 OR ID_CLIENTE_P <> TRUNC(ID_CLIENTE_P) THEN
        RAISE_APPLICATION_ERROR(
            -20101,
            'EL ID DEBE SER UN ENTERO MAYOR QUE CERO'
        );
    END IF;

    IF TRIM(NOMBRE_CLIENTE_P) IS NULL THEN
        RAISE_APPLICATION_ERROR(
            -20102,
            'EL NOMBRE DEL CLIENTE ES OBLIGATORIO'
        );
    END IF;

    SELECT COUNT(*)
    INTO CANTIDAD_V
    FROM SGCD_CLIENTES
    WHERE ID_CLIENTE = ID_CLIENTE_P;

    IF CANTIDAD_V = 0 THEN
        RAISE_APPLICATION_ERROR(
            -20103,
            'EL CLIENTE NO EXISTE'
        );
    END IF;

    -- Revisar si el correo pertenece a otro cliente.
    SELECT COUNT(*) INTO CANTIDAD_V
    FROM SGCD_CLIENTES
    WHERE CORREO_CLIENTE = LOWER(TRIM(CORREO_CLIENTE_P))
      AND ID_CLIENTE <> ID_CLIENTE_P;

    IF CANTIDAD_V > 0 THEN
        RAISE_APPLICATION_ERROR(
            -20104,
            'EL CORREO YA ESTA REGISTRADO EN OTRO CLIENTE'
        );
    END IF;

    -- Guardar los cambios.
    UPDATE SGCD_CLIENTES
    SET NOMBRE_CLIENTE = TRIM(NOMBRE_CLIENTE_P),
        TELEFONO_CLIENTE = TELEFONO_CLIENTE_P,
        CORREO_CLIENTE = LOWER(TRIM(CORREO_CLIENTE_P))
    WHERE ID_CLIENTE = ID_CLIENTE_P;

    -- Revisar si se actualizo la ficha.
    IF SQL%ROWCOUNT = 0 THEN
        RAISE_APPLICATION_ERROR(
            -20103,
            'EL CLIENTE NO EXISTE'
        );
    END IF;

END;
/

