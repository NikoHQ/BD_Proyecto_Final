-- Probar la actualizacion, el borrado y la auditoria.
-- Usar una conexion de pruebas, sin otros cambios pendientes.
-- Al terminar se revierten los datos. La secuencia puede dejar saltos.

SET SERVEROUTPUT ON

DECLARE
    ID_V SGCD_CLIENTES.ID_CLIENTE%TYPE;
    RUT_V NUMBER;
    CORREO_V SGCD_CLIENTES.CORREO_CLIENTE%TYPE;
    CANTIDAD_V NUMBER;

BEGIN

    SELECT NVL(MAX(RUT_CLIENTE), 0) + 1
    INTO RUT_V
    FROM SGCD_CLIENTES;

    IF RUT_V > 99999999 THEN
        RAISE_APPLICATION_ERROR(
            -20990,
            'NO HAY RUT SINTETICO DISPONIBLE PARA ESTA PRUEBA'
        );
    END IF;

    CORREO_V := 'prueba_' || RUT_V || '@prueba.cl';

    SELECT COUNT(*)
    INTO CANTIDAD_V
    FROM SGCD_CLIENTES
    WHERE CORREO_CLIENTE = CORREO_V;

    IF CANTIDAD_V > 0 THEN
        RAISE_APPLICATION_ERROR(
            -20990,
            'CORREO DE PRUEBA OCUPADO; REVISAR EL ESQUEMA DE PRUEBAS'
        );
    END IF;

    INSERT INTO SGCD_CLIENTES (RUT_CLIENTE, DV_CLIENTE, NOMBRE_CLIENTE)
    VALUES (RUT_V, '0', 'NOMBRE ORIGINAL');

    SELECT ID_CLIENTE
    INTO ID_V
    FROM SGCD_CLIENTES
    WHERE RUT_CLIENTE = RUT_V AND DV_CLIENTE = '0';
    SGCD_ACTUALIZAR_FICHA_CLIENTE(ID_V, '  NOMBRE NUEVO  ', '123', UPPER(CORREO_V));

    SELECT COUNT(*) INTO CANTIDAD_V FROM SGCD_CLIENTES
    WHERE ID_CLIENTE = ID_V AND RUT_CLIENTE = RUT_V AND DV_CLIENTE = '0'
      AND NOMBRE_CLIENTE = 'NOMBRE NUEVO' AND TELEFONO_CLIENTE = '123' AND CORREO_CLIENTE = CORREO_V;

    IF CANTIDAD_V <> 1 THEN
        RAISE_APPLICATION_ERROR(
            -20991,
            'FALLO: ACTUALIZACION O CONSERVACION DE ID/RUT/DV'
        );
    END IF;

    DBMS_OUTPUT.PUT_LINE('OK: actualiza, normaliza y conserva ID/RUT/DV');

    SELECT COUNT(*) INTO CANTIDAD_V FROM SGCD_AUDITORIA_CLIENTES
    WHERE ID_CLIENTE = ID_V AND ACCION = 'UPDATE'
      AND NOMBRE_ANTERIOR = 'NOMBRE ORIGINAL' AND NOMBRE_NUEVO = 'NOMBRE NUEVO'
      AND TELEFONO_ANTERIOR IS NULL AND TELEFONO_NUEVO = '123'
      AND CORREO_ANTERIOR IS NULL AND CORREO_NUEVO = CORREO_V;

    IF CANTIDAD_V <> 1 THEN
        RAISE_APPLICATION_ERROR(
            -20992,
            'FALLO: AUDITORIA DE VALORES ANTERIORES/NUEVOS'
        );
    END IF;

    DBMS_OUTPUT.PUT_LINE('OK: auditoria registra cambios desde NULL');
    SGCD_ACTUALIZAR_FICHA_CLIENTE(ID_V, 'NOMBRE NUEVO', '123', CORREO_V);

    SELECT COUNT(*)
    INTO CANTIDAD_V
    FROM SGCD_AUDITORIA_CLIENTES
    WHERE ID_CLIENTE = ID_V;

    IF CANTIDAD_V <> 1 THEN
        RAISE_APPLICATION_ERROR(
            -20992,
            'FALLO: SE REGISTRO UN UPDATE SIN CAMBIOS'
        );
    END IF;

    DBMS_OUTPUT.PUT_LINE('OK: no duplica auditoria sin cambios');
    SGCD_ACTUALIZAR_FICHA_CLIENTE(ID_V, 'NOMBRE NUEVO', NULL, NULL);

    SELECT COUNT(*) INTO CANTIDAD_V FROM SGCD_CLIENTES
    WHERE ID_CLIENTE = ID_V AND TELEFONO_CLIENTE IS NULL AND CORREO_CLIENTE IS NULL;

    IF CANTIDAD_V <> 1 THEN
        RAISE_APPLICATION_ERROR(
            -20991,
            'FALLO: NULL NO VACIO LOS CAMPOS OPCIONALES'
        );
    END IF;

    SELECT COUNT(*) INTO CANTIDAD_V FROM SGCD_AUDITORIA_CLIENTES
    WHERE ID_CLIENTE = ID_V AND ACCION = 'UPDATE' AND TELEFONO_ANTERIOR = '123'
      AND TELEFONO_NUEVO IS NULL AND CORREO_ANTERIOR = CORREO_V AND CORREO_NUEVO IS NULL;

    IF CANTIDAD_V <> 1 THEN
        RAISE_APPLICATION_ERROR(
            -20992,
            'FALLO: AUDITORIA DE CAMBIO HACIA NULL'
        );
    END IF;

    DBMS_OUTPUT.PUT_LINE('OK: vacia campos y audita cambios hacia NULL');
    SGCD_BORRAR_FICHA_CLIENTE(ID_V);

    SELECT COUNT(*)
    INTO CANTIDAD_V
    FROM SGCD_CLIENTES
    WHERE ID_CLIENTE = ID_V;

    IF CANTIDAD_V <> 0 THEN
        RAISE_APPLICATION_ERROR(
            -20993,
            'FALLO: NO SE BORRO LA FICHA SIN DEPENDENCIAS'
        );
    END IF;

    SELECT COUNT(*) INTO CANTIDAD_V FROM SGCD_AUDITORIA_CLIENTES
    WHERE ID_CLIENTE = ID_V AND ACCION = 'DELETE' AND NOMBRE_ANTERIOR = 'NOMBRE NUEVO';

    IF CANTIDAD_V <> 1 THEN
        RAISE_APPLICATION_ERROR(
            -20992,
            'FALLO: NO SE CONSERVO LA AUDITORIA DEL BORRADO'
        );
    END IF;

    DBMS_OUTPUT.PUT_LINE('OK: borra solo la ficha y conserva auditoria');
    ROLLBACK;

    SELECT COUNT(*)
    INTO CANTIDAD_V
    FROM SGCD_AUDITORIA_CLIENTES
    WHERE ID_CLIENTE = ID_V;

    IF CANTIDAD_V <> 0 THEN
        RAISE_APPLICATION_ERROR(
            -20994,
            'FALLO: ROLLBACK NO REVIRTIO LA AUDITORIA'
        );
    END IF;

    SELECT COUNT(*)
    INTO CANTIDAD_V
    FROM SGCD_CLIENTES
    WHERE RUT_CLIENTE = RUT_V AND DV_CLIENTE = '0';

    IF CANTIDAD_V <> 0 THEN
        RAISE_APPLICATION_ERROR(
            -20994,
            'FALLO: LA PRUEBA DEJO SU FICHA INSERTADA'
        );
    END IF;

    DBMS_OUTPUT.PUT_LINE('OK: pruebas positivas terminadas; datos y auditoria revertidos');

EXCEPTION
    WHEN OTHERS THEN
        ROLLBACK;

        -- Mostrar el error despues de revertir la prueba.
        RAISE;

END;
/
