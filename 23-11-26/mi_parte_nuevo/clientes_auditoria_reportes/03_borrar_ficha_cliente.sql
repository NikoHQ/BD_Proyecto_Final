-- Borrar un cliente que no tenga registros relacionados.
-- Las claves foraneas deben seguir activas y sin borrado en cascada.

CREATE OR REPLACE PROCEDURE SGCD_BORRAR_FICHA_CLIENTE (
    ID_CLIENTE_P SGCD_CLIENTES.ID_CLIENTE%TYPE
)

IS
    CANTIDAD_V NUMBER;
    RELACIONES_V NUMBER := 0;

BEGIN

    IF ID_CLIENTE_P IS NULL OR ID_CLIENTE_P <= 0 OR ID_CLIENTE_P <> TRUNC(ID_CLIENTE_P) THEN
        RAISE_APPLICATION_ERROR(
            -20105,
            'EL ID DEBE SER UN ENTERO MAYOR QUE CERO'
        );
    END IF;

    -- Contar los registros relacionados con el cliente.
    SELECT COUNT(*) INTO CANTIDAD_V FROM SGCD_CREDENCIALES
    WHERE ID_CLIENTE = ID_CLIENTE_P;

    RELACIONES_V := RELACIONES_V + CANTIDAD_V;

    SELECT COUNT(*) INTO CANTIDAD_V FROM SGCD_MEMBRESIAS
    WHERE ID_CLIENTE = ID_CLIENTE_P;

    RELACIONES_V := RELACIONES_V + CANTIDAD_V;

    SELECT COUNT(*) INTO CANTIDAD_V FROM SGCD_MOVIMIENTOS_PUNTOS
    WHERE ID_CLIENTE = ID_CLIENTE_P;

    RELACIONES_V := RELACIONES_V + CANTIDAD_V;

    SELECT COUNT(*) INTO CANTIDAD_V FROM SGCD_RESERVAS
    WHERE ID_CLIENTE = ID_CLIENTE_P;

    RELACIONES_V := RELACIONES_V + CANTIDAD_V;

    SELECT COUNT(*) INTO CANTIDAD_V  FROM SGCD_EQUIPOS
    WHERE ID_CLIENTE_RESPONSABLE = ID_CLIENTE_P;

    RELACIONES_V := RELACIONES_V + CANTIDAD_V;

    SELECT COUNT(*) INTO CANTIDAD_V FROM SGCD_JUGADORES
    WHERE ID_CLIENTE = ID_CLIENTE_P;

    RELACIONES_V := RELACIONES_V + CANTIDAD_V;

    SELECT COUNT(*) INTO CANTIDAD_V  FROM SGCD_OPERACIONES_IMPLEMENTOS
    WHERE ID_CLIENTE = ID_CLIENTE_P;

    RELACIONES_V := RELACIONES_V + CANTIDAD_V;

    IF RELACIONES_V > 0 THEN
        RAISE_APPLICATION_ERROR(
            -20107,
            'EL CLIENTE TIENE REGISTROS RELACIONADOS; NO SE PUEDE BORRAR'
        );
    END IF;

    -- Borrar la ficha.
    DELETE FROM SGCD_CLIENTES
    WHERE ID_CLIENTE = ID_CLIENTE_P;

    IF SQL%ROWCOUNT = 0 THEN
        RAISE_APPLICATION_ERROR(
            -20106,
            'EL CLIENTE NO EXISTE'
        );
    END IF;

END;
/

-- Oracle rechaza el borrado si aparecen otros registros relacionados.
