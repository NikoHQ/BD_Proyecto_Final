CREATE OR REPLACE PROCEDURE SGCD_CREAR_CANCHA (
    ID_RECINTO_P SGCD_CANCHAS.ID_RECINTO%TYPE,
    NOMBRE_CANCHA_P SGCD_CANCHAS.NOMBRE_CANCHA%TYPE,
    TIPO_CANCHA_P SGCD_CANCHAS.TIPO_CANCHA%TYPE,
    ESTADO_CANCHA_P SGCD_CANCHAS.ESTADO_CANCHA%TYPE,
    ID_CANCHA_P OUT SGCD_CANCHAS.ID_CANCHA%TYPE
)
IS

BEGIN

    IF TRIM(NOMBRE_CANCHA_P) IS NULL OR ESTADO_CANCHA_P IS NULL
       OR ESTADO_CANCHA_P NOT IN ('DISPONIBLE', 'MANTENCION', 'INACTIVA') THEN
        RAISE_APPLICATION_ERROR(-20860, 'Revise el nombre y el estado');
    END IF;

    IF TIPO_CANCHA_P IS NULL THEN
        RAISE_APPLICATION_ERROR(-20860, 'Ingrese el tipo de cancha');
    END IF;

    INSERT INTO SGCD_CANCHAS (ID_RECINTO, NOMBRE_CANCHA, TIPO_CANCHA, ESTADO_CANCHA)
    VALUES (ID_RECINTO_P, TRIM(NOMBRE_CANCHA_P), TIPO_CANCHA_P, ESTADO_CANCHA_P)
    RETURNING ID_CANCHA INTO ID_CANCHA_P;

EXCEPTION

    WHEN DUP_VAL_ON_INDEX THEN
        RAISE_APPLICATION_ERROR(-20863, 'El registro ya existe');
END;
/

CREATE OR REPLACE PROCEDURE SGCD_LISTAR_CANCHAS (
    RESULTADO_P OUT SYS_REFCURSOR
)
IS

BEGIN

    OPEN RESULTADO_P FOR
        SELECT ID_CANCHA, ID_RECINTO, NOMBRE_CANCHA, TIPO_CANCHA, ESTADO_CANCHA
        FROM SGCD_CANCHAS
        ORDER BY NOMBRE_CANCHA, ID_CANCHA;
END;
/

CREATE OR REPLACE PROCEDURE SGCD_ACTUALIZAR_CANCHA (
    ID_CANCHA_P SGCD_CANCHAS.ID_CANCHA%TYPE,
    NOMBRE_CANCHA_P SGCD_CANCHAS.NOMBRE_CANCHA%TYPE,
    TIPO_CANCHA_P SGCD_CANCHAS.TIPO_CANCHA%TYPE,
    ESTADO_CANCHA_P SGCD_CANCHAS.ESTADO_CANCHA%TYPE
)
IS

BEGIN

    IF TRIM(NOMBRE_CANCHA_P) IS NULL OR ESTADO_CANCHA_P IS NULL
       OR ESTADO_CANCHA_P NOT IN ('DISPONIBLE', 'MANTENCION', 'INACTIVA') THEN
        RAISE_APPLICATION_ERROR(-20860, 'Revise el nombre y el estado');
    END IF;

    IF TIPO_CANCHA_P IS NULL THEN
        RAISE_APPLICATION_ERROR(-20860, 'Ingrese el tipo de cancha');
    END IF;

    UPDATE SGCD_CANCHAS
    SET NOMBRE_CANCHA = TRIM(NOMBRE_CANCHA_P),
        TIPO_CANCHA = TIPO_CANCHA_P,
        ESTADO_CANCHA = ESTADO_CANCHA_P
    WHERE ID_CANCHA = ID_CANCHA_P;

    IF SQL%ROWCOUNT = 0 THEN
        RAISE_APPLICATION_ERROR(-20862, 'El registro no existe');
    END IF;

EXCEPTION

    WHEN DUP_VAL_ON_INDEX THEN
        RAISE_APPLICATION_ERROR(-20863, 'El registro ya existe');
END;
/

CREATE OR REPLACE PROCEDURE SGCD_BORRAR_CANCHA (
    ID_CANCHA_P SGCD_CANCHAS.ID_CANCHA%TYPE
)
IS

BEGIN

    DELETE FROM SGCD_CANCHAS WHERE ID_CANCHA = ID_CANCHA_P;

    IF SQL%ROWCOUNT = 0 THEN
        RAISE_APPLICATION_ERROR(-20862, 'El registro no existe');
    END IF;

EXCEPTION

    WHEN OTHERS THEN
        IF SQLCODE = -2292 THEN
            RAISE_APPLICATION_ERROR(-20864, 'El registro está en uso');
        END IF;
        RAISE;
END;
/

