-- Horarios de apertura y cierre por día. Oracle asigna el ID.
CREATE OR REPLACE PROCEDURE SGCD_CREAR_HORARIO (
    ID_RECINTO_P NUMBER,
    DIA_P NUMBER,
    APERTURA_P VARCHAR2,
    CIERRE_P VARCHAR2,
    ID_HORARIO_P OUT NUMBER
)
IS

BEGIN

    IF DIA_P IS NULL OR DIA_P < 1 OR DIA_P > 7 OR DIA_P <> TRUNC(DIA_P) THEN
        RAISE_APPLICATION_ERROR(-20840, 'Ingrese un día entero entre 1 y 7');
    END IF;

    INSERT INTO SGCD_HORARIOS (
        ID_RECINTO, DIA_SEMANA_HORARIO, HORA_APERTURA_HORARIO, HORA_CIERRE_HORARIO
    ) VALUES (
        ID_RECINTO_P, DIA_P, APERTURA_P, CIERRE_P
    ) RETURNING ID_HORARIO INTO ID_HORARIO_P;

EXCEPTION

    WHEN DUP_VAL_ON_INDEX THEN
        RAISE_APPLICATION_ERROR(-20841, 'Ya existe un horario para ese día y recinto');
END;
/

CREATE OR REPLACE PROCEDURE SGCD_LISTAR_HORARIOS (
    ID_RECINTO_P NUMBER,
    HORARIOS_P OUT SYS_REFCURSOR
)
IS

BEGIN

    OPEN HORARIOS_P FOR
        SELECT ID_HORARIO, DIA_SEMANA_HORARIO,
               HORA_APERTURA_HORARIO, HORA_CIERRE_HORARIO
        FROM SGCD_HORARIOS
        WHERE ID_RECINTO = ID_RECINTO_P
        ORDER BY DIA_SEMANA_HORARIO;
END;
/

CREATE OR REPLACE PROCEDURE SGCD_ACTUALIZAR_HORARIO (
    ID_HORARIO_P NUMBER,
    APERTURA_P VARCHAR2,
    CIERRE_P VARCHAR2
)
IS

    ID_HORARIO_V NUMBER;
    BLOQUES_FUERA_V NUMBER;

BEGIN

    -- El mantenedor de bloques también bloquea esta fila antes de guardar.
    SELECT ID_HORARIO INTO ID_HORARIO_V FROM SGCD_HORARIOS
    WHERE ID_HORARIO = ID_HORARIO_P
    FOR UPDATE;

    SELECT COUNT(*) INTO BLOQUES_FUERA_V FROM SGCD_BLOQUES_HORARIOS
    WHERE ID_HORARIO = ID_HORARIO_V
      AND (HORA_INICIO < APERTURA_P OR HORA_TERMINO > CIERRE_P);

    IF BLOQUES_FUERA_V > 0 THEN
        RAISE_APPLICATION_ERROR(-20842, 'Hay bloques fuera del nuevo horario');
    END IF;

    UPDATE SGCD_HORARIOS
    SET HORA_APERTURA_HORARIO = APERTURA_P,
        HORA_CIERRE_HORARIO = CIERRE_P
    WHERE ID_HORARIO = ID_HORARIO_V;

EXCEPTION

    WHEN NO_DATA_FOUND THEN
        RAISE_APPLICATION_ERROR(-20843, 'El horario no existe');
END;
/

CREATE OR REPLACE PROCEDURE SGCD_BORRAR_HORARIO (
    ID_HORARIO_P NUMBER
)
IS

    ID_HORARIO_V NUMBER;
    BLOQUES_V NUMBER;

BEGIN

    SELECT ID_HORARIO INTO ID_HORARIO_V
    FROM SGCD_HORARIOS
    WHERE ID_HORARIO = ID_HORARIO_P
    FOR UPDATE;

    SELECT COUNT(*) INTO BLOQUES_V
    FROM SGCD_BLOQUES_HORARIOS
    WHERE ID_HORARIO = ID_HORARIO_V;

    IF BLOQUES_V > 0 THEN
        RAISE_APPLICATION_ERROR(-20844, 'Quite los bloques antes de borrar el horario');
    END IF;

    DELETE FROM SGCD_HORARIOS WHERE ID_HORARIO = ID_HORARIO_V;

EXCEPTION

    WHEN NO_DATA_FOUND THEN
        RAISE_APPLICATION_ERROR(-20843, 'El horario no existe');
END;
/

