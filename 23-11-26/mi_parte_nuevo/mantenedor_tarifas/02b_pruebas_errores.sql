-- Casos que debe rechazar el mantenedor de tarifas.

SET SERVEROUTPUT ON

DECLARE
    CANCHA_V NUMBER;
    MODALIDAD_V NUMBER;
    TARIFA_V NUMBER;
    OTRA_TARIFA_V NUMBER;
    TARIFA_HISTORICA_V NUMBER;
    CURSOR_V SYS_REFCURSOR;

BEGIN

    SELECT MIN(ID_CANCHA) INTO CANCHA_V FROM SGCD_CANCHAS_MODALIDADES;

    SELECT MIN(ID_MODALIDAD) INTO MODALIDAD_V FROM SGCD_CANCHAS_MODALIDADES
    WHERE ID_CANCHA = CANCHA_V;

    IF CANCHA_V IS NULL OR MODALIDAD_V IS NULL THEN
        RAISE_APPLICATION_ERROR(-20990, 'FALTA UNA CANCHA CON MODALIDAD');
    END IF;

    SGCD_CREAR_TARIFA(
        CANCHA_V, MODALIDAD_V, 2, '10:00', '12:00',
        TRUNC(SYSDATE) + 4000, NULL, 20000, TARIFA_V
    );

    BEGIN
        SGCD_ACTUALIZAR_TARIFA(0, 2, '10:00', '12:00', SYSDATE + 4000, NULL, 20000);
        RAISE_APPLICATION_ERROR(-20991, 'FALLO: ACEPTO ID CERO');
    EXCEPTION WHEN OTHERS THEN
        IF SQLCODE <> -20801 THEN RAISE; END IF;
        DBMS_OUTPUT.PUT_LINE('OK 1: RECHAZA ID NO VALIDO');
    END;

    BEGIN
        SGCD_CAMBIAR_ESTADO_TARIFA(999999999, 'ACTIVA');
        RAISE_APPLICATION_ERROR(-20992, 'FALLO: ACEPTO TARIFA INEXISTENTE');
    EXCEPTION WHEN OTHERS THEN
        IF SQLCODE <> -20802 THEN RAISE; END IF;
        DBMS_OUTPUT.PUT_LINE('OK 2: RECHAZA TARIFA INEXISTENTE');
    END;

    BEGIN
        SGCD_CREAR_TARIFA(999999999, 999999999, 2, '10:00', '12:00',
            SYSDATE + 4000, NULL, 20000, OTRA_TARIFA_V);
        RAISE_APPLICATION_ERROR(-20993, 'FALLO: ACEPTO COMBINACION INEXISTENTE');
    EXCEPTION WHEN OTHERS THEN
        IF SQLCODE <> -20803 THEN RAISE; END IF;
        DBMS_OUTPUT.PUT_LINE('OK 3: RECHAZA CANCHA Y MODALIDAD INCOMPATIBLES');
    END;

    BEGIN
        SGCD_CREAR_TARIFA(CANCHA_V, MODALIDAD_V, 8, '10:00', '12:00',
            SYSDATE + 4000, NULL, 20000, OTRA_TARIFA_V);
        RAISE_APPLICATION_ERROR(-20994, 'FALLO: ACEPTO DIA OCHO');
    EXCEPTION WHEN OTHERS THEN
        IF SQLCODE <> -20804 THEN RAISE; END IF;
        DBMS_OUTPUT.PUT_LINE('OK 4: RECHAZA DIA NO VALIDO');
    END;

    BEGIN
        SGCD_CREAR_TARIFA(CANCHA_V, MODALIDAD_V, 2, '12:00', '10:00',
            SYSDATE + 4000, NULL, 20000, OTRA_TARIFA_V);
        RAISE_APPLICATION_ERROR(-20995, 'FALLO: ACEPTO HORAS INVERTIDAS');
    EXCEPTION WHEN OTHERS THEN
        IF SQLCODE <> -20805 THEN RAISE; END IF;
        DBMS_OUTPUT.PUT_LINE('OK 5: RECHAZA HORAS NO VALIDAS');
    END;

    BEGIN
        SGCD_CREAR_TARIFA(CANCHA_V, MODALIDAD_V, 2, '13:00', '14:00',
            SYSDATE + 4000, SYSDATE + 3999, 20000, OTRA_TARIFA_V);
        RAISE_APPLICATION_ERROR(-20996, 'FALLO: ACEPTO VIGENCIA INVERTIDA');
    EXCEPTION WHEN OTHERS THEN
        IF SQLCODE <> -20806 THEN RAISE; END IF;
        DBMS_OUTPUT.PUT_LINE('OK 6: RECHAZA VIGENCIA NO VALIDA');
    END;

    BEGIN
        SGCD_CREAR_TARIFA(CANCHA_V, MODALIDAD_V, 2, '13:00', '14:00',
            SYSDATE - 1, NULL, 20000, OTRA_TARIFA_V);
        RAISE_APPLICATION_ERROR(-20987, 'FALLO: ACEPTO ALTA RETROACTIVA');
    EXCEPTION WHEN OTHERS THEN
        IF SQLCODE <> -20806 THEN RAISE; END IF;
        DBMS_OUTPUT.PUT_LINE('OK 6B: RECHAZA ALTA RETROACTIVA');
    END;

    BEGIN
        SGCD_CREAR_TARIFA(CANCHA_V, MODALIDAD_V, 2, '13:00', '14:00',
            SYSDATE + 4000, NULL, 0, OTRA_TARIFA_V);
        RAISE_APPLICATION_ERROR(-20997, 'FALLO: ACEPTO VALOR CERO');
    EXCEPTION WHEN OTHERS THEN
        IF SQLCODE <> -20807 THEN RAISE; END IF;
        DBMS_OUTPUT.PUT_LINE('OK 7: RECHAZA VALOR NO VALIDO');
    END;

    BEGIN
        SGCD_CREAR_TARIFA(CANCHA_V, MODALIDAD_V, 2, '11:00', '13:00',
            TRUNC(SYSDATE) + 4000, NULL, 21000, OTRA_TARIFA_V);
        RAISE_APPLICATION_ERROR(-20998, 'FALLO: ACEPTO BANDA AMBIGUA');
    EXCEPTION WHEN OTHERS THEN
        IF SQLCODE <> -20808 THEN RAISE; END IF;
        DBMS_OUTPUT.PUT_LINE('OK 8: RECHAZA BANDA AMBIGUA');
    END;

    BEGIN
        SGCD_CAMBIAR_ESTADO_TARIFA(TARIFA_V, 'BORRADA');
        RAISE_APPLICATION_ERROR(-20981, 'FALLO: ACEPTO ESTADO NO VALIDO');
    EXCEPTION WHEN OTHERS THEN
        IF SQLCODE <> -20809 THEN RAISE; END IF;
        DBMS_OUTPUT.PUT_LINE('OK 9: RECHAZA ESTADO NO VALIDO');
    END;

    BEGIN
        SGCD_ACTUALIZAR_TARIFA(TARIFA_V, 2, '10:00', '12:00',
            SYSDATE - 1, NULL, 20000);
        RAISE_APPLICATION_ERROR(-20982, 'FALLO: MOVIO TARIFA FUTURA AL PASADO');
    EXCEPTION WHEN OTHERS THEN
        IF SQLCODE <> -20810 THEN RAISE; END IF;
        DBMS_OUTPUT.PUT_LINE('OK 10: RECHAZA MOVER TARIFA FUTURA AL PASADO');
    END;

    SGCD_CREAR_TARIFA(
        CANCHA_V, MODALIDAD_V, 2, '13:00', '14:00',
        TRUNC(SYSDATE) + 4001, NULL, 22000, OTRA_TARIFA_V
    );

    SGCD_CAMBIAR_ESTADO_TARIFA(OTRA_TARIFA_V, 'INACTIVA');

    SGCD_ACTUALIZAR_TARIFA(
        OTRA_TARIFA_V, 2, '11:00', '13:00',
        TRUNC(SYSDATE) + 4000, NULL, 22000
    );

    BEGIN
        SGCD_CAMBIAR_ESTADO_TARIFA(OTRA_TARIFA_V, 'ACTIVA');
        RAISE_APPLICATION_ERROR(-20983, 'FALLO: REACTIVO BANDA AMBIGUA');
    EXCEPTION WHEN OTHERS THEN
        IF SQLCODE <> -20808 THEN RAISE; END IF;
        DBMS_OUTPUT.PUT_LINE('OK 11: RECHAZA REACTIVAR BANDA AMBIGUA');
    END;

    INSERT INTO SGCD_TARIFAS (
        ID_CANCHA, ID_MODALIDAD, DIA_SEMANA_TARIFA,
        HORA_DESDE_TARIFA, HORA_HASTA_TARIFA,
        VIGENTE_DESDE_TARIFA, VIGENTE_HASTA_TARIFA,
        VALOR_HORA_TARIFA
    ) VALUES (
        CANCHA_V, MODALIDAD_V, 4,
        '00:01', '00:02',
        TRUNC(SYSDATE) - 30, TRUNC(SYSDATE) + 30,
        1000
    );

    SELECT ID_TARIFA INTO TARIFA_HISTORICA_V FROM SGCD_TARIFAS
    WHERE ID_CANCHA = CANCHA_V
      AND ID_MODALIDAD = MODALIDAD_V
      AND DIA_SEMANA_TARIFA = 4
      AND HORA_DESDE_TARIFA = '00:01'
      AND VIGENTE_DESDE_TARIFA = TRUNC(SYSDATE) - 30;

    BEGIN
        SGCD_ACTUALIZAR_TARIFA(TARIFA_HISTORICA_V, 4, '00:01', '00:03',
            SYSDATE - 30, SYSDATE + 30, 1200);
        RAISE_APPLICATION_ERROR(-20984, 'FALLO: MODIFICO TARIFA VIGENTE');
    EXCEPTION WHEN OTHERS THEN
        IF SQLCODE <> -20810 THEN RAISE; END IF;
        DBMS_OUTPUT.PUT_LINE('OK 12: RECHAZA MODIFICAR TARIFA INICIADA');
    END;

    BEGIN
        SGCD_BORRAR_TARIFA(TARIFA_HISTORICA_V);
        RAISE_APPLICATION_ERROR(-20985, 'FALLO: BORRO TARIFA INICIADA');
    EXCEPTION WHEN OTHERS THEN
        IF SQLCODE <> -20811 THEN RAISE; END IF;
        DBMS_OUTPUT.PUT_LINE('OK 13: RECHAZA BORRAR TARIFA INICIADA');
    END;

    BEGIN
        SGCD_LISTAR_TARIFAS(NULL, NULL, 'BORRADA', CURSOR_V);
        RAISE_APPLICATION_ERROR(-20986, 'FALLO: ACEPTO FILTRO NO VALIDO');
    EXCEPTION WHEN OTHERS THEN
        IF SQLCODE <> -20812 THEN RAISE; END IF;
        DBMS_OUTPUT.PUT_LINE('OK 14: RECHAZA FILTRO NO VALIDO');
    END;

    ROLLBACK;

EXCEPTION
    WHEN OTHERS THEN
        IF CURSOR_V%ISOPEN THEN CLOSE CURSOR_V; END IF;
        ROLLBACK;
        RAISE;

END;
/
