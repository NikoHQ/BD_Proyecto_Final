-- Probar el mantenedor de tarifas.
-- Al terminar se revierten todos los datos creados.

SET SERVEROUTPUT ON

DECLARE
    CANCHA_V NUMBER;
    MODALIDAD_V NUMBER;
    TARIFA_V NUMBER;
    CANTIDAD_V NUMBER;
    DIA_V NUMBER;
    DESDE_V CHAR(5);
    HASTA_V CHAR(5);
    VIGENTE_DESDE_V DATE;
    VIGENTE_HASTA_V DATE;
    VALOR_V NUMBER;
    ESTADO_V VARCHAR2(10);
    CURSOR_V SYS_REFCURSOR;

BEGIN

    SELECT MIN(ID_CANCHA) INTO CANCHA_V FROM SGCD_CANCHAS_MODALIDADES;

    SELECT MIN(ID_MODALIDAD) INTO MODALIDAD_V FROM SGCD_CANCHAS_MODALIDADES
    WHERE ID_CANCHA = CANCHA_V;

    IF CANCHA_V IS NULL OR MODALIDAD_V IS NULL THEN
        RAISE_APPLICATION_ERROR(-20990, 'FALTA UNA CANCHA CON MODALIDAD');
    END IF;

    SGCD_CREAR_TARIFA(
        CANCHA_V,
        MODALIDAD_V,
        2,
        '06:00',
        '07:00',
        TRUNC(SYSDATE) + 3650,
        NULL,
        15000,
        TARIFA_V
    );

    SGCD_ACTUALIZAR_TARIFA(
        TARIFA_V,
        3,
        '07:00',
        '08:30',
        TRUNC(SYSDATE) + 3650,
        TRUNC(SYSDATE) + 3680,
        16000
    );

    SGCD_CAMBIAR_ESTADO_TARIFA(TARIFA_V, 'inactiva');

    SELECT DIA_SEMANA_TARIFA,
           HORA_DESDE_TARIFA,
           HORA_HASTA_TARIFA,
           VIGENTE_DESDE_TARIFA,
           VIGENTE_HASTA_TARIFA,
           VALOR_HORA_TARIFA,
           ESTADO_TARIFA
    INTO DIA_V,
         DESDE_V,
         HASTA_V,
         VIGENTE_DESDE_V,
         VIGENTE_HASTA_V,
         VALOR_V,
         ESTADO_V
    FROM SGCD_TARIFAS
    WHERE ID_TARIFA = TARIFA_V;

    IF DIA_V <> 3
       OR TRIM(DESDE_V) <> '07:00'
       OR TRIM(HASTA_V) <> '08:30'
       OR VIGENTE_DESDE_V <> TRUNC(SYSDATE) + 3650
       OR VIGENTE_HASTA_V <> TRUNC(SYSDATE) + 3681 - 1/86400
       OR VALOR_V <> 16000
       OR ESTADO_V <> 'INACTIVA' THEN
        RAISE_APPLICATION_ERROR(
            -20991,
            'FALLO: LOS DATOS MODIFICADOS NO SON CORRECTOS'
        );
    END IF;

    DBMS_OUTPUT.PUT_LINE('OK 1: CREA, MODIFICA Y DESACTIVA UNA TARIFA');

    SGCD_LISTAR_TARIFAS(
        CANCHA_V,
        MODALIDAD_V,
        'INACTIVA',
        CURSOR_V
    );

    FETCH CURSOR_V INTO TARIFA_V,
                        CANCHA_V,
                        MODALIDAD_V,
                        DIA_V,
                        DESDE_V,
                        HASTA_V,
                        VIGENTE_DESDE_V,
                        VIGENTE_HASTA_V,
                        VALOR_V,
                        ESTADO_V;

    IF CURSOR_V%NOTFOUND OR VALOR_V <> 16000 THEN
        CLOSE CURSOR_V;
        RAISE_APPLICATION_ERROR(-20992, 'FALLO: EL LISTADO NO ENCONTRO LA TARIFA');
    END IF;

    CLOSE CURSOR_V;

    DBMS_OUTPUT.PUT_LINE('OK 2: LISTA POR CANCHA, MODALIDAD Y ESTADO');

    SGCD_BORRAR_TARIFA(TARIFA_V);

    SELECT COUNT(*) INTO CANTIDAD_V FROM SGCD_TARIFAS
    WHERE ID_TARIFA = TARIFA_V;

    IF CANTIDAD_V <> 0 THEN
        RAISE_APPLICATION_ERROR(-20993, 'FALLO: LA TARIFA FUTURA DEBE BORRARSE');
    END IF;

    DBMS_OUTPUT.PUT_LINE('OK 3: BORRA UNA TARIFA FUTURA');

    ROLLBACK;
    DBMS_OUTPUT.PUT_LINE('OK 4: EL ROLLBACK REVIERTE LA PRUEBA');

EXCEPTION
    WHEN OTHERS THEN
        IF CURSOR_V%ISOPEN THEN
            CLOSE CURSOR_V;
        END IF;
        ROLLBACK;
        RAISE;

END;
