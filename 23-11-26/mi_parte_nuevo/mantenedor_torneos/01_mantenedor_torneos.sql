-- El alta se incorpora en SGCD_PKG_TORNEOS.crear_torneo.
CREATE OR REPLACE PROCEDURE SGCD_LISTAR_TORNEOS (
    TORNEOS_P OUT SYS_REFCURSOR
)
IS

BEGIN

    OPEN TORNEOS_P FOR
        SELECT ID_TORNEO, ID_MODALIDAD, NOMBRE_TORNEO, FECHA_INICIO,
               FECHA_TERMINO, CUPOS_TORNEO, MAX_JUGADORES_POR_EQUIPO, ESTADO_TORNEO
        FROM SGCD_TORNEOS
        ORDER BY FECHA_INICIO, ID_TORNEO;
END;
/

CREATE OR REPLACE PROCEDURE SGCD_ACTUALIZAR_TORNEO (
    ID_TORNEO_P NUMBER,
    NOMBRE_P VARCHAR2,
    INICIO_P DATE,
    TERMINO_P DATE,
    CUPOS_P NUMBER,
    JUGADORES_P NUMBER
)
IS

    TORNEO_V SGCD_TORNEOS%ROWTYPE;
    EQUIPOS_V NUMBER;
    NOMINAS_INVALIDAS_V NUMBER;
    RESERVAS_FUERA_V NUMBER;

BEGIN

    IF TRIM(NOMBRE_P) IS NULL OR INICIO_P IS NULL OR TERMINO_P IS NULL
       OR INICIO_P > TERMINO_P OR CUPOS_P IS NULL OR CUPOS_P < 1
       OR CUPOS_P <> TRUNC(CUPOS_P) OR JUGADORES_P IS NULL OR JUGADORES_P < 1
       OR JUGADORES_P <> TRUNC(JUGADORES_P) THEN
        RAISE_APPLICATION_ERROR(-20865, 'Revise el nombre, las fechas, los cupos y la cantidad de jugadores');
    END IF;

    -- El alta de un equipo debe usar el mismo bloqueo.
    SELECT * INTO TORNEO_V
    FROM SGCD_TORNEOS WHERE ID_TORNEO = ID_TORNEO_P
    FOR UPDATE;

    SELECT COUNT(*) INTO EQUIPOS_V
    FROM SGCD_INSCRIPCIONES_TORNEO
    WHERE ID_TORNEO = ID_TORNEO_P AND ESTADO_INSCRIPCION = 'INSCRITO';

    IF CUPOS_P < EQUIPOS_V THEN
        RAISE_APPLICATION_ERROR(-20866, 'Ya hay más equipos inscritos que cupos solicitados');
    END IF;

    IF JUGADORES_P <> TORNEO_V.MAX_JUGADORES_POR_EQUIPO THEN
        SELECT COUNT(*) INTO NOMINAS_INVALIDAS_V
        FROM SGCD_INSCRIPCIONES_TORNEO I
        WHERE I.ID_TORNEO = ID_TORNEO_P AND I.ESTADO_INSCRIPCION = 'INSCRITO'
          AND JUGADORES_P <> (
              SELECT COUNT(*) FROM SGCD_EQUIPOS_JUGADORES E
              WHERE E.ID_INSCRIPCION = I.ID_INSCRIPCION
          );

        IF NOMINAS_INVALIDAS_V > 0 THEN
            RAISE_APPLICATION_ERROR(-20867, 'Hay equipos que no cumplen la nueva cantidad');
        END IF;
    END IF;

    SELECT COUNT(*) INTO RESERVAS_FUERA_V
    FROM SGCD_RESERVAS
    WHERE ID_TORNEO = ID_TORNEO_P AND ESTADO_RESERVA <> 'CANCELADA'
      AND (INICIO_RESERVA < INICIO_P OR TERMINO_RESERVA > TERMINO_P);

    IF RESERVAS_FUERA_V > 0 THEN
        RAISE_APPLICATION_ERROR(-20868, 'Hay reservas fuera de las nuevas fechas');
    END IF;

    UPDATE SGCD_TORNEOS
    SET NOMBRE_TORNEO = TRIM(NOMBRE_P), FECHA_INICIO = INICIO_P,
        FECHA_TERMINO = TERMINO_P, CUPOS_TORNEO = CUPOS_P,
        MAX_JUGADORES_POR_EQUIPO = JUGADORES_P
    WHERE ID_TORNEO = ID_TORNEO_P;

EXCEPTION

    WHEN NO_DATA_FOUND THEN
        RAISE_APPLICATION_ERROR(-20869, 'El torneo no existe');
END;
/

CREATE OR REPLACE PROCEDURE SGCD_BORRAR_TORNEO (
    ID_TORNEO_P NUMBER
)
IS

BEGIN

    DELETE FROM SGCD_TORNEOS WHERE ID_TORNEO = ID_TORNEO_P;

    IF SQL%ROWCOUNT = 0 THEN
        RAISE_APPLICATION_ERROR(-20869, 'El torneo no existe');
    END IF;

EXCEPTION

    WHEN OTHERS THEN
        IF SQLCODE = -2292 THEN
            RAISE_APPLICATION_ERROR(-20864, 'El torneo tiene reservas o inscripciones asociadas');
        END IF;
        RAISE;
END;
/

