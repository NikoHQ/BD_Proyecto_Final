-- 1. TABLA RECINTO

CREATE TABLE SGCD_RECINTOS (
    ID_RECINTO NUMBER ,
    NOMBRE_RECINTO VARCHAR2(100) ,
    DIRECCION_RECINTO VARCHAR2(150) ,
    ESTADO_RECINTO VARCHAR2(10) ,

    CONSTRAINT PK_SGCD_RECINTO
    PRIMARY KEY (ID_RECINTO)
);



-- 2. TABLA DEPORTE

CREATE TABLE SGCD_DEPORTES (
    ID_DEPORTE NUMBER ,
    NOMBRE_DEPORTE VARCHAR2(50) ,
    ESTADO_DEPORTE VARCHAR2(10) ,

    CONSTRAINT PK_SGCD_DEPORTE
    PRIMARY KEY (ID_DEPORTE),

    CONSTRAINT UQ_SGCD_DEPORTE_NOMBRE
    UNIQUE (NOMBRE_DEPORTE)
);



-- 3. TABLA USUARIO

CREATE TABLE SGCD_USUARIOS (
    ID_USUARIO NUMBER ,
    LOGIN VARCHAR2(50) ,
    CLAVE_HASH VARCHAR2(255) ,
    ROL VARCHAR2(20) ,
    ESTADO_USUARIO VARCHAR2(10) ,

    CONSTRAINT PK_SGCD_USUARIO
    PRIMARY KEY (ID_USUARIO),

    CONSTRAINT UQ_SGCD_USUARIO_LOGIN
    UNIQUE (LOGIN)
);



-- 4. TABLA HORARIO

CREATE TABLE SGCD_HORARIOS (
    ID_HORARIO NUMBER ,
    ID_RECINTO NUMBER ,
    DIA_SEMANA NUMBER ,
    HORA_APERTURA VARCHAR2(5) ,
    HORA_CIERRE VARCHAR2(5) ,

    CONSTRAINT PK_SGCD_HORARIO
    PRIMARY KEY (ID_HORARIO),

    CONSTRAINT UQ_SGCD_HORARIO_DIA
    UNIQUE (ID_RECINTO, DIA_SEMANA),

    CONSTRAINT FK_SGCD_HOR_REC
    FOREIGN KEY (ID_RECINTO)
    REFERENCES SGCD_RECINTOS (ID_RECINTO)
);



-- 5. TABLA CANCHA

CREATE TABLE SGCD_CANCHAS (
    ID_CANCHA NUMBER ,
    ID_RECINTO NUMBER ,
    NOMBRE_CANCHA VARCHAR2(100) ,
    TIPO_CANCHA VARCHAR2(20) ,
    ESTADO_CANCHA VARCHAR2(15) ,

    CONSTRAINT PK_SGCD_CANCHA
    PRIMARY KEY (ID_CANCHA),

    CONSTRAINT UQ_SGCD_CANCHA_NOMBRE
    UNIQUE (ID_RECINTO, NOMBRE_CANCHA),

    CONSTRAINT FK_SGCD_CAN_REC
    FOREIGN KEY (ID_RECINTO)
    REFERENCES SGCD_RECINTOS (ID_RECINTO)
);



-- 6. TABLA MODALIDAD

CREATE TABLE SGCD_MODALIDADES (
    ID_MODALIDAD NUMBER ,
    ID_DEPORTE NUMBER ,
    NOMBRE_MODALIDAD VARCHAR2(80) ,
    MAX_JUGADORES_POR_EQUIPO NUMBER ,
    ESTADO_MODALIDAD VARCHAR2(10) ,

    CONSTRAINT PK_SGCD_MODALIDAD
    PRIMARY KEY (ID_MODALIDAD),

    CONSTRAINT UQ_SGCD_MOD_DEP_NOMBRE
    UNIQUE (ID_DEPORTE, NOMBRE_MODALIDAD),

    CONSTRAINT FK_SGCD_MOD_DEP
    FOREIGN KEY (ID_DEPORTE)
    REFERENCES SGCD_DEPORTES (ID_DEPORTE)
);



-- 7. TABLA CLIENTE

CREATE TABLE SGCD_CLIENTES (
    ID_CLIENTE NUMBER,
    ID_USUARIO NUMBER,
    RUT_CLIENTE NUMBER ,
    DV_CLIENTE VARCHAR2(1) ,
    NOMBRE_CLIENTE VARCHAR2(100) ,
    CORREO_CLIENTE VARCHAR2(150),
    TELEFONO_CLIENTE VARCHAR2(20),
    ESTADO_CLIENTE VARCHAR2(10) ,

    CONSTRAINT PK_SGCD_CLIENTE
    PRIMARY KEY (ID_CLIENTE),

    CONSTRAINT UQ_SGCD_CLIENTE_USUARIO
    UNIQUE (ID_USUARIO),

    CONSTRAINT UQ_SGCD_CLIENTE_RUT
    UNIQUE (RUT_CLIENTE, DV_CLIENTE),

    CONSTRAINT FK_SGCD_CLI_USU
    FOREIGN KEY (ID_USUARIO)
    REFERENCES SGCD_USUARIOS (ID_USUARIO)
);



-- 8. TABLA ADMINISTRADOR

CREATE TABLE SGCD_ADMINISTRADORES (
