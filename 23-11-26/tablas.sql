);



-- 14. TABLA JUGADOR

CREATE TABLE SGCD_JUGADORES (
    ID_JUGADOR NUMBER ,
    RUT_JUGADOR NUMBER,
    DV_JUGADOR CHAR(1) ,
    NOMBRE_JUGADOR VARCHAR2(100) ,
    ID_CLIENTE NUMBER,

    CONSTRAINT PK_SGCD_JUGADOR
    PRIMARY KEY (ID_JUGADOR),

    CONSTRAINT UQ_SGCD_JUGADOR_CLIENTE
    UNIQUE (ID_CLIENTE),

    CONSTRAINT UQ_SGCD_JUGADOR_RUT
    UNIQUE (RUT_JUGADOR, DV_JUGADOR),

    CONSTRAINT FK_SGCD_JUG_CLI
    FOREIGN KEY (ID_CLIENTE)
    REFERENCES SGCD_CLIENTES (ID_CLIENTE)
);



