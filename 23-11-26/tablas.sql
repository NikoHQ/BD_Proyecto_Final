-- 16. TABLA RESERVA

CREATE TABLE SGCD_RESERVAS (
    ID_RESERVA NUMBER ,
    ID_CLIENTE NUMBER,
    ID_ADMINISTRADOR NUMBER,
    ID_CANCHA NUMBER ,
    ID_MODALIDAD NUMBER ,
    ID_TORNEO NUMBER,
    INICIO_RESERVA DATE ,
    TERMINO_RESERVA DATE ,
    IMPORTE_ACORDADO NUMBER ,
    ORIGEN_RESERVA VARCHAR2(10) ,
    ESTADO_RESERVA VARCHAR2(15) ,

    CONSTRAINT PK_SGCD_RESERVA
    PRIMARY KEY (ID_RESERVA),

    CONSTRAINT FK_SGCD_RES_CLI
    FOREIGN KEY (ID_CLIENTE)
    REFERENCES SGCD_CLIENTES (ID_CLIENTE),

    CONSTRAINT FK_SGCD_RES_ADM
    FOREIGN KEY (ID_ADMINISTRADOR)
    REFERENCES SGCD_ADMINISTRADORES (ID_ADMINISTRADOR),

    CONSTRAINT FK_SGCD_RES_TOR
    FOREIGN KEY (ID_TORNEO)
    REFERENCES SGCD_TORNEOS (ID_TORNEO),

    CONSTRAINT FK_SGCD_RES_CM
    FOREIGN KEY (ID_CANCHA, ID_MODALIDAD)
    REFERENCES SGCD_CANCHAS_MODALIDADES (ID_CANCHA, ID_MODALIDAD)
);



