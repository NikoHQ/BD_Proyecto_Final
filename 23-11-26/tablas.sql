-- 13. TABLA TARIFA

CREATE TABLE SGCD_TARIFAS (
    ID_TARIFA NUMBER ,
    ID_CANCHA NUMBER ,
    ID_MODALIDAD NUMBER ,
    DIA_SEMANA NUMBER ,
    HORA_DESDE VARCHAR2(5) ,
    HORA_HASTA VARCHAR2(5) ,
    VIGENTE_DESDE DATE ,
    VIGENTE_HASTA DATE,
