-- ---------------------------------------------------------------------
-- 15. SGCD_TORNEOS - el evento. Sin partidos, sin fixture
--    DESCUENTO_PORCENTAJE_TORNEO se aplica al arriendo de cada bloque
-- ---------------------------------------------------------------------
CREATE TABLE SGCD_TORNEOS (
    ID_TORNEO       NUMBER(10) GENERATED BY DEFAULT ON NULL AS IDENTITY,
    ID_RECINTO      NUMBER(10) NOT NULL,
    ID_MODALIDAD    NUMBER(10) NOT NULL,
    NOMBRE_TORNEO   VARCHAR2(100) NOT NULL,
    FECHA_INICIO_TORNEO DATE NOT NULL,
    FECHA_FIN_TORNEO    DATE NOT NULL,
