);


-- ---------------------------------------------------------------------
-- 7. SGCD_ARTICULOS - implementos que se venden o se arriendan
-- ---------------------------------------------------------------------
CREATE TABLE SGCD_ARTICULOS (
    ID_ARTICULO     NUMBER(10) GENERATED BY DEFAULT ON NULL AS IDENTITY,
    NOMBRE_ARTICULO VARCHAR2(100) NOT NULL,
    EXISTENCIAS_VENTA_ARTICULO NUMBER(10) DEFAULT 0 NOT NULL,
    EXISTENCIAS_ARRIENDO_ARTICULO NUMBER(10) DEFAULT 0 NOT NULL,
    PRECIO_VENTA_ARTICULO NUMBER(12,2),
    PRECIO_ARRIENDO_ARTICULO NUMBER(12,2),
    ESTADO_ARTICULO VARCHAR2(10) DEFAULT 'ACTIVO' NOT NULL,
    CONSTRAINT PK_SGCD_ARTICULOS PRIMARY KEY (ID_ARTICULO),
    CONSTRAINT UQ_SGCD_ARTICULO_NOMBRE UNIQUE (NOMBRE_ARTICULO),
    CONSTRAINT CK_SGCD_ART_STOCK CHECK (EXISTENCIAS_VENTA_ARTICULO >= 0
                                    AND EXISTENCIAS_ARRIENDO_ARTICULO >= 0),
    CONSTRAINT CK_SGCD_ART_PRECIOS CHECK ((PRECIO_VENTA_ARTICULO IS NULL OR PRECIO_VENTA_ARTICULO >= 0)
                                      AND (PRECIO_ARRIENDO_ARTICULO IS NULL OR PRECIO_ARRIENDO_ARTICULO >= 0)),
    CONSTRAINT CK_SGCD_ART_ESTADO CHECK (ESTADO_ARTICULO IN ('ACTIVO', 'INACTIVO'))
);


-- ---------------------------------------------------------------------
-- 8. SGCD_CANCHAS - la instalacion reservable (cancha, gimnasio, sala, piscina)
--    ESTADO_CANCHA = MANTENCION bloquea toda reserva mientras dure, sin fecha
-- ---------------------------------------------------------------------
CREATE TABLE SGCD_CANCHAS (
    ID_CANCHA       NUMBER(10) GENERATED BY DEFAULT ON NULL AS IDENTITY,
    ID_RECINTO      NUMBER(10) NOT NULL,
    NOMBRE_CANCHA   VARCHAR2(100) NOT NULL,
    TIPO_CANCHA     VARCHAR2(20) DEFAULT 'CANCHA' NOT NULL,
    SUPERFICIE_CANCHA NUMBER(8,2),
    ESTADO_CANCHA   VARCHAR2(20) DEFAULT 'DISPONIBLE' NOT NULL,
    CONSTRAINT PK_SGCD_CANCHAS PRIMARY KEY (ID_CANCHA),
    CONSTRAINT FK_SGCD_CANCHA_RECINTO FOREIGN KEY (ID_RECINTO)
        REFERENCES SGCD_RECINTOS (ID_RECINTO),
    CONSTRAINT UQ_SGCD_CANCHA_NOMBRE UNIQUE (ID_RECINTO, NOMBRE_CANCHA),
    CONSTRAINT CK_SGCD_CANCHA_TIPO CHECK (TIPO_CANCHA IN ('CANCHA', 'GIMNASIO', 'SALA', 'PISCINA')),
    CONSTRAINT CK_SGCD_CANCHA_SUPERFICIE CHECK (SUPERFICIE_CANCHA IS NULL OR SUPERFICIE_CANCHA > 0),
    CONSTRAINT CK_SGCD_CANCHA_ESTADO CHECK (ESTADO_CANCHA IN ('DISPONIBLE', 'MANTENCION', 'INACTIVA'))
);


-- ---------------------------------------------------------------------
