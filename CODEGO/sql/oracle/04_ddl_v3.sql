-- =====================================================================
-- SISTEMA DE GESTION DE CENTROS DEPORTIVOS - SGCD
-- DDL Oracle 26ai Free - ESQUEMA v3 - 22 tablas
--
-- Reemplaza a 01_ddl_v2.sql. Cambios estructurales:
--   * CLIENTES gana RUT_CLIENTE + DV_CLIENTE (clave natural) y CORREO unico.
--   * CREDENCIALES (nueva): acceso unico para clientes y personal, con rol,
--     estado y verificacion. ADMINISTRADORES pierde usuario, clave y perfil.
--   * TORNEOS, EQUIPOS, JUGADORES, EQUIPO_JUGADORES (nuevas): torneos sin
--     partidos; el jugador se identifica por RUT sin crearle ficha.
--   * RESERVAS: TIPO_RESERVA, ID_TORNEO y ORIGEN_RESERVA. El bloque de cancha
--     de un torneo ES una reserva: un solo calendario.
--   * El indice unico de bloque deja de incluir ID_MODALIDAD: el conflicto es
--     por cancha. El solape parcial lo detecta SGCD_PKG_RESERVAS.
--
-- Orden de ejecucion: 01..03 (v2) son historico. La v3 es:
--   04_ddl_v3.sql -> 05_paquetes_plsql.sql -> 06_catalogos_v3.sql
--   -> 07_datos_operativos.sql -> 08_pruebas_v3.sql
--
-- Este script es autocontenido y re-ejecutable: borra las tablas SGCD_*
-- existentes (datos incluidos) antes de crearlas. No toca otros esquemas.
--
-- Reglas de escritura: sin lineas en blanco dentro de cada sentencia, porque
-- SQL*Plus con SQLBLANKLINES OFF corta la sentencia en la linea vacia.
-- =====================================================================


SET DEFINE OFF


-- ---------------------------------------------------------------------
-- 0. Limpieza: borra cualquier tabla SGCD_* previa (idempotente)
-- ---------------------------------------------------------------------
BEGIN
    FOR t IN (SELECT TABLE_NAME FROM USER_TABLES WHERE TABLE_NAME LIKE 'SGCD\_%' ESCAPE '\') LOOP
        EXECUTE IMMEDIATE 'DROP TABLE ' || t.TABLE_NAME || ' CASCADE CONSTRAINTS';
    END LOOP;
END;
/


-- ---------------------------------------------------------------------
-- 1. SGCD_RECINTOS - el establecimiento fisico
-- ---------------------------------------------------------------------
CREATE TABLE SGCD_RECINTOS (
    ID_RECINTO        NUMBER(10) GENERATED BY DEFAULT ON NULL AS IDENTITY,
    NOMBRE_RECINTO    VARCHAR2(100) NOT NULL,
    DIRECCION_RECINTO VARCHAR2(200) NOT NULL,
    COMUNA_RECINTO    VARCHAR2(80)  NOT NULL,
    TELEFONO_RECINTO  VARCHAR2(20),
    ESTADO_RECINTO    VARCHAR2(10) DEFAULT 'ACTIVO' NOT NULL,
    CREADO_EN_RECINTO TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
    CONSTRAINT PK_SGCD_RECINTOS PRIMARY KEY (ID_RECINTO),
    CONSTRAINT UQ_SGCD_RECINTO_NOMBRE UNIQUE (NOMBRE_RECINTO, COMUNA_RECINTO),
    CONSTRAINT CK_SGCD_RECINTO_ESTADO CHECK (ESTADO_RECINTO IN ('ACTIVO', 'INACTIVO'))
);


-- ---------------------------------------------------------------------
-- 2. SGCD_DEPORTES - futbol, padel, basquetbol...
-- ---------------------------------------------------------------------
CREATE TABLE SGCD_DEPORTES (
    ID_DEPORTE      NUMBER(10) GENERATED BY DEFAULT ON NULL AS IDENTITY,
    NOMBRE_DEPORTE  VARCHAR2(100) NOT NULL,
    ESTADO_DEPORTE  VARCHAR2(10) DEFAULT 'ACTIVO' NOT NULL,
    CONSTRAINT PK_SGCD_DEPORTES PRIMARY KEY (ID_DEPORTE),
    CONSTRAINT UQ_SGCD_DEPORTE_NOMBRE UNIQUE (NOMBRE_DEPORTE),
    CONSTRAINT CK_SGCD_DEPORTE_ESTADO CHECK (ESTADO_DEPORTE IN ('ACTIVO', 'INACTIVO'))
);


-- ---------------------------------------------------------------------
-- 3. SGCD_CLIENTES - ficha comercial. Existe SIN cuenta: ese es el caso normal
--    El RUT identifica; no autentica (la clave vive en SGCD_CREDENCIALES)
-- ---------------------------------------------------------------------
CREATE TABLE SGCD_CLIENTES (
    ID_CLIENTE        NUMBER(10) GENERATED BY DEFAULT ON NULL AS IDENTITY,
    RUT_CLIENTE       NUMBER(8) NOT NULL,
    DV_CLIENTE        CHAR(1) NOT NULL,
    NOMBRE_CLIENTE    VARCHAR2(100) NOT NULL,
    TELEFONO_CLIENTE  VARCHAR2(20),
    CORREO_CLIENTE    VARCHAR2(150),
    ESTADO_CLIENTE    VARCHAR2(10) DEFAULT 'ACTIVO' NOT NULL,
    CREADO_EN_CLIENTE TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
    CONSTRAINT PK_SGCD_CLIENTES PRIMARY KEY (ID_CLIENTE),
    CONSTRAINT UQ_SGCD_CLIENTE_RUT UNIQUE (RUT_CLIENTE, DV_CLIENTE),
    CONSTRAINT UQ_SGCD_CLIENTE_CORREO UNIQUE (CORREO_CLIENTE),
    CONSTRAINT CK_SGCD_CLIENTE_RUT CHECK (RUT_CLIENTE BETWEEN 1 AND 99999999),
    CONSTRAINT CK_SGCD_CLIENTE_DV CHECK (REGEXP_LIKE(DV_CLIENTE, '^[0-9K]$')),
    CONSTRAINT CK_SGCD_CLIENTE_CORREO CHECK (
        CORREO_CLIENTE IS NULL
        OR (CORREO_CLIENTE = LOWER(CORREO_CLIENTE)
            AND REGEXP_LIKE(CORREO_CLIENTE, '^[^@[:space:]]+@[^@[:space:]]+\.[[:alpha:]]{2,}$'))
    ),
    CONSTRAINT CK_SGCD_CLIENTE_ESTADO CHECK (ESTADO_CLIENTE IN ('ACTIVO', 'INACTIVO'))
);


-- ---------------------------------------------------------------------
-- 4. SGCD_ADMINISTRADORES - personal del recinto. Datos personales solamente:
--    el acceso vive en SGCD_CREDENCIALES (perfil -> ROL_CREDENCIAL)
-- ---------------------------------------------------------------------
CREATE TABLE SGCD_ADMINISTRADORES (
    ID_ADMINISTRADOR        NUMBER(10) GENERATED BY DEFAULT ON NULL AS IDENTITY,
    NOMBRE_ADMINISTRADOR    VARCHAR2(100) NOT NULL,
    ESTADO_ADMINISTRADOR    VARCHAR2(10) DEFAULT 'ACTIVO' NOT NULL,
    CREADO_EN_ADMINISTRADOR TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
    CONSTRAINT PK_SGCD_ADMINISTRADORES PRIMARY KEY (ID_ADMINISTRADOR),
    CONSTRAINT CK_SGCD_ADMIN_ESTADO CHECK (ESTADO_ADMINISTRADOR IN ('ACTIVO', 'INACTIVO'))
);


-- ---------------------------------------------------------------------
-- 5. SGCD_CREDENCIALES - acceso al sistema. Exactamente un dueno:
--    un cliente (cuenta web) o un administrador (personal)
--    NO_VERIFICADA = FECHA_VERIFICACION nula: puede reservar, no ve historial
-- ---------------------------------------------------------------------
CREATE TABLE SGCD_CREDENCIALES (
    ID_CREDENCIAL                 NUMBER(10) GENERATED BY DEFAULT ON NULL AS IDENTITY,
    LOGIN_CREDENCIAL              VARCHAR2(50) NOT NULL,
    CLAVE_HASH_CREDENCIAL         VARCHAR2(255) NOT NULL,
    ROL_CREDENCIAL                VARCHAR2(20) DEFAULT 'CLIENTE' NOT NULL,
    ESTADO_CREDENCIAL             VARCHAR2(10) DEFAULT 'ACTIVA' NOT NULL,
    ID_CLIENTE                    NUMBER(10),
    ID_ADMINISTRADOR              NUMBER(10),
    FECHA_VERIFICACION_CREDENCIAL TIMESTAMP,
    ID_ADMINISTRADOR_VERIFICADOR  NUMBER(10),
    CONSTRAINT PK_SGCD_CREDENCIALES PRIMARY KEY (ID_CREDENCIAL),
    CONSTRAINT UQ_SGCD_CRED_LOGIN UNIQUE (LOGIN_CREDENCIAL),
    CONSTRAINT UQ_SGCD_CRED_CLIENTE UNIQUE (ID_CLIENTE),
    CONSTRAINT UQ_SGCD_CRED_ADMIN UNIQUE (ID_ADMINISTRADOR),
    CONSTRAINT FK_SGCD_CRED_CLIENTE FOREIGN KEY (ID_CLIENTE)
        REFERENCES SGCD_CLIENTES (ID_CLIENTE),
    CONSTRAINT FK_SGCD_CRED_ADMIN FOREIGN KEY (ID_ADMINISTRADOR)
        REFERENCES SGCD_ADMINISTRADORES (ID_ADMINISTRADOR),
    CONSTRAINT FK_SGCD_CRED_VERIF FOREIGN KEY (ID_ADMINISTRADOR_VERIFICADOR)
        REFERENCES SGCD_ADMINISTRADORES (ID_ADMINISTRADOR),
    CONSTRAINT CK_SGCD_CRED_DUENO CHECK (
        CASE WHEN ID_CLIENTE IS NOT NULL THEN 1 ELSE 0 END
      + CASE WHEN ID_ADMINISTRADOR IS NOT NULL THEN 1 ELSE 0 END = 1
    ),
    CONSTRAINT CK_SGCD_CRED_ROL CHECK (ROL_CREDENCIAL IN ('ADMINISTRADOR', 'OPERADOR', 'CLIENTE')),
    CONSTRAINT CK_SGCD_CRED_ROL_DUENO CHECK (
        (ROL_CREDENCIAL = 'CLIENTE' AND ID_CLIENTE IS NOT NULL)
        OR (ROL_CREDENCIAL <> 'CLIENTE' AND ID_ADMINISTRADOR IS NOT NULL)
    ),
    CONSTRAINT CK_SGCD_CRED_ESTADO CHECK (ESTADO_CREDENCIAL IN ('ACTIVA', 'BLOQUEADA', 'INACTIVA')),
    CONSTRAINT CK_SGCD_CRED_VERIF CHECK (
        (FECHA_VERIFICACION_CREDENCIAL IS NULL AND ID_ADMINISTRADOR_VERIFICADOR IS NULL)
        OR (FECHA_VERIFICACION_CREDENCIAL IS NOT NULL AND ID_ADMINISTRADOR_VERIFICADOR IS NOT NULL)
    ),
    CONSTRAINT CK_SGCD_CRED_PERSONAL_VERIF CHECK (
        ROL_CREDENCIAL = 'CLIENTE' OR FECHA_VERIFICACION_CREDENCIAL IS NOT NULL
    )
);


-- ---------------------------------------------------------------------
-- 6. SGCD_PLANES_MEMBRESIA - el producto de membresia
