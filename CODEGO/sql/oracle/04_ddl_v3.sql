    CONSTRAINT CK_SGCD_TORNEO_CUPOS CHECK (CUPOS_EQUIPOS_TORNEO BETWEEN 2 AND 128),
    CONSTRAINT CK_SGCD_TORNEO_DESCUENTO CHECK (DESCUENTO_PORCENTAJE_TORNEO BETWEEN 0 AND 100),
    CONSTRAINT CK_SGCD_TORNEO_ESTADO
        CHECK (ESTADO_TORNEO IN ('PLANIFICADO', 'EN_CURSO', 'FINALIZADO', 'CANCELADO'))
);


-- ---------------------------------------------------------------------
-- 16. SGCD_RESERVAS - EL UNICO CALENDARIO del sistema
--    Reserva de mostrador, reserva web y bloque de torneo son filas de aqui
--    PENDIENTE bloquea el horario igual que CONFIRMADA; CANCELADA lo libera
-- ---------------------------------------------------------------------
CREATE TABLE SGCD_RESERVAS (
    ID_RESERVA      NUMBER(10) GENERATED BY DEFAULT ON NULL AS IDENTITY,
    ID_CLIENTE      NUMBER(10),
    ID_ADMINISTRADOR NUMBER(10),
    ID_CANCHA       NUMBER(10) NOT NULL,
    ID_MODALIDAD    NUMBER(10) NOT NULL,
    ID_TORNEO       NUMBER(10),
    TIPO_RESERVA    VARCHAR2(10) DEFAULT 'NORMAL' NOT NULL,
    ORIGEN_RESERVA  VARCHAR2(10) NOT NULL,
    INICIO_RESERVA  TIMESTAMP NOT NULL,
    TERMINO_RESERVA TIMESTAMP NOT NULL,
    IMPORTE_ACORDADO_RESERVA NUMBER(12,2) NOT NULL,
    ESTADO_RESERVA  VARCHAR2(20) DEFAULT 'PENDIENTE' NOT NULL,
    CREADO_EN_RESERVA TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
    CONSTRAINT PK_SGCD_RESERVAS PRIMARY KEY (ID_RESERVA),
    CONSTRAINT FK_SGCD_RES_CLIENTE FOREIGN KEY (ID_CLIENTE)
        REFERENCES SGCD_CLIENTES (ID_CLIENTE),
    CONSTRAINT FK_SGCD_RES_ADMIN FOREIGN KEY (ID_ADMINISTRADOR)
        REFERENCES SGCD_ADMINISTRADORES (ID_ADMINISTRADOR),
    CONSTRAINT FK_SGCD_RES_CM FOREIGN KEY (ID_CANCHA, ID_MODALIDAD)
        REFERENCES SGCD_CANCHAS_MODALIDADES (ID_CANCHA, ID_MODALIDAD),
    CONSTRAINT FK_SGCD_RES_TORNEO FOREIGN KEY (ID_TORNEO)
        REFERENCES SGCD_TORNEOS (ID_TORNEO),
    CONSTRAINT CK_SGCD_RES_FECHAS CHECK (TERMINO_RESERVA > INICIO_RESERVA),
    CONSTRAINT CK_SGCD_RES_IMPORTE CHECK (IMPORTE_ACORDADO_RESERVA >= 0),
    CONSTRAINT CK_SGCD_RES_ESTADO
        CHECK (ESTADO_RESERVA IN ('PENDIENTE', 'CONFIRMADA', 'CANCELADA', 'COMPLETADA')),
    CONSTRAINT CK_SGCD_RES_TIPO CHECK (TIPO_RESERVA IN ('NORMAL', 'TORNEO')),
    CONSTRAINT CK_SGCD_RES_ORIGEN CHECK (ORIGEN_RESERVA IN ('MOSTRADOR', 'WEB')),
    CONSTRAINT CK_SGCD_RES_TORNEO_ID CHECK (
        (TIPO_RESERVA = 'TORNEO' AND ID_TORNEO IS NOT NULL)
        OR (TIPO_RESERVA = 'NORMAL' AND ID_TORNEO IS NULL)
    ),
    CONSTRAINT CK_SGCD_RES_CLIENTE CHECK (TIPO_RESERVA = 'TORNEO' OR ID_CLIENTE IS NOT NULL),
    CONSTRAINT CK_SGCD_RES_ORIGEN_ADMIN CHECK (
        (ORIGEN_RESERVA = 'MOSTRADOR' AND ID_ADMINISTRADOR IS NOT NULL)
        OR (ORIGEN_RESERVA = 'WEB' AND ID_ADMINISTRADOR IS NULL)
    )
);

-- Un mismo bloque (cancha, inicio) no puede reservarse dos veces mientras no
-- este CANCELADA. Oracle no tiene indices parciales: se emula con funcion + NULL.
-- No incluye ID_MODALIDAD: la cancha ocupada lo esta para cualquier deporte.
CREATE UNIQUE INDEX UX_SGCD_RESERVAS_BLOQUE ON SGCD_RESERVAS (
    CASE WHEN ESTADO_RESERVA <> 'CANCELADA' THEN ID_CANCHA       END,
    CASE WHEN ESTADO_RESERVA <> 'CANCELADA' THEN INICIO_RESERVA  END
);


-- ---------------------------------------------------------------------
-- 17. SGCD_EQUIPOS - la inscripcion al torneo. El capitan es el primer jugador
-- ---------------------------------------------------------------------
CREATE TABLE SGCD_EQUIPOS (
    ID_EQUIPO       NUMBER(10) GENERATED BY DEFAULT ON NULL AS IDENTITY,
    ID_TORNEO       NUMBER(10) NOT NULL,
    NOMBRE_EQUIPO   VARCHAR2(100) NOT NULL,
    ID_CLIENTE_RESPONSABLE NUMBER(10) NOT NULL,
    FECHA_INSCRIPCION_EQUIPO TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
    ESTADO_EQUIPO   VARCHAR2(10) DEFAULT 'INSCRITO' NOT NULL,
    CONSTRAINT PK_SGCD_EQUIPOS PRIMARY KEY (ID_EQUIPO),
    CONSTRAINT FK_SGCD_EQUIPO_TORNEO FOREIGN KEY (ID_TORNEO)
        REFERENCES SGCD_TORNEOS (ID_TORNEO),
    CONSTRAINT FK_SGCD_EQUIPO_CAPITAN FOREIGN KEY (ID_CLIENTE_RESPONSABLE)
        REFERENCES SGCD_CLIENTES (ID_CLIENTE),
    CONSTRAINT UQ_SGCD_EQUIPO_NOMBRE UNIQUE (ID_TORNEO, NOMBRE_EQUIPO),
    CONSTRAINT CK_SGCD_EQUIPO_ESTADO CHECK (ESTADO_EQUIPO IN ('INSCRITO', 'RETIRADO'))
);


-- ---------------------------------------------------------------------
-- 18. SGCD_JUGADORES - identidad liviana del jugador de torneo.
--    NO es una ficha de cliente. ID_CLIENTE se enlaza solo si el RUT ya existe
--    como cliente; en ese caso el nombre se copia de la ficha (lo hace el paquete)
-- ---------------------------------------------------------------------
CREATE TABLE SGCD_JUGADORES (
    ID_JUGADOR      NUMBER(10) GENERATED BY DEFAULT ON NULL AS IDENTITY,
    RUT_JUGADOR     NUMBER(8) NOT NULL,
    DV_JUGADOR      CHAR(1) NOT NULL,
    NOMBRE_JUGADOR  VARCHAR2(100) NOT NULL,
    ID_CLIENTE      NUMBER(10),
    CONSTRAINT PK_SGCD_JUGADORES PRIMARY KEY (ID_JUGADOR),
    CONSTRAINT FK_SGCD_JUGADOR_CLIENTE FOREIGN KEY (ID_CLIENTE)
        REFERENCES SGCD_CLIENTES (ID_CLIENTE),
    CONSTRAINT UQ_SGCD_JUGADOR_RUT UNIQUE (RUT_JUGADOR, DV_JUGADOR),
    CONSTRAINT CK_SGCD_JUGADOR_RUT CHECK (RUT_JUGADOR BETWEEN 1 AND 99999999),
    CONSTRAINT CK_SGCD_JUGADOR_DV CHECK (REGEXP_LIKE(DV_JUGADOR, '^[0-9K]$'))
);


-- ---------------------------------------------------------------------
-- 19. SGCD_EQUIPO_JUGADORES - la plantilla del equipo
-- ---------------------------------------------------------------------
CREATE TABLE SGCD_EQUIPO_JUGADORES (
    ID_EQUIPO       NUMBER(10) NOT NULL,
    ID_JUGADOR      NUMBER(10) NOT NULL,
    CONSTRAINT PK_SGCD_EQUIPO_JUGADORES PRIMARY KEY (ID_EQUIPO, ID_JUGADOR),
    CONSTRAINT FK_SGCD_EQJUG_EQUIPO FOREIGN KEY (ID_EQUIPO)
        REFERENCES SGCD_EQUIPOS (ID_EQUIPO) ON DELETE CASCADE,
    CONSTRAINT FK_SGCD_EQJUG_JUGADOR FOREIGN KEY (ID_JUGADOR)
        REFERENCES SGCD_JUGADORES (ID_JUGADOR)
);


-- ---------------------------------------------------------------------
-- 20. SGCD_OPERACIONES_IMPLEMENTOS - cabecera de venta o arriendo
-- ---------------------------------------------------------------------
CREATE TABLE SGCD_OPERACIONES_IMPLEMENTOS (
    ID_OPERACION    NUMBER(10) GENERATED BY DEFAULT ON NULL AS IDENTITY,
    ID_CLIENTE      NUMBER(10) NOT NULL,
    TIPO_OPERACION  VARCHAR2(10) NOT NULL,
    FECHA_OPERACION TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
    IMPORTE_TOTAL_OPERACION NUMBER(12,2) NOT NULL,
    CONSTRAINT PK_SGCD_OPERACIONES_IMPLEMENTOS PRIMARY KEY (ID_OPERACION),
    CONSTRAINT FK_SGCD_OPER_CLIENTE FOREIGN KEY (ID_CLIENTE)
        REFERENCES SGCD_CLIENTES (ID_CLIENTE),
    CONSTRAINT CK_SGCD_OPER_TIPO CHECK (TIPO_OPERACION IN ('VENTA', 'ARRIENDO')),
    CONSTRAINT CK_SGCD_OPER_IMPORTE CHECK (IMPORTE_TOTAL_OPERACION >= 0)
);


-- ---------------------------------------------------------------------
-- 21. SGCD_DETALLES_IMPLEMENTOS - lineas de la operacion
-- ---------------------------------------------------------------------
CREATE TABLE SGCD_DETALLES_IMPLEMENTOS (
    ID_OPERACION    NUMBER(10) NOT NULL,
    ID_ARTICULO     NUMBER(10) NOT NULL,
    CANTIDAD_DETALLE NUMBER(10) NOT NULL,
    PRECIO_ACORDADO_DETALLE NUMBER(12,2) NOT NULL,
    ENTREGA_DETALLE TIMESTAMP NOT NULL,
    DEVOLUCION_PREVISTA_DETALLE TIMESTAMP,
    DEVOLUCION_REAL_DETALLE TIMESTAMP,
    CONSTRAINT PK_SGCD_DETALLES_IMPLEMENTOS PRIMARY KEY (ID_OPERACION, ID_ARTICULO),
    CONSTRAINT FK_SGCD_DET_OPERACION FOREIGN KEY (ID_OPERACION)
        REFERENCES SGCD_OPERACIONES_IMPLEMENTOS (ID_OPERACION) ON DELETE CASCADE,
    CONSTRAINT FK_SGCD_DET_ARTICULO FOREIGN KEY (ID_ARTICULO)
        REFERENCES SGCD_ARTICULOS (ID_ARTICULO),
    CONSTRAINT CK_SGCD_DET_CANTIDAD CHECK (CANTIDAD_DETALLE > 0),
    CONSTRAINT CK_SGCD_DET_PRECIO CHECK (PRECIO_ACORDADO_DETALLE >= 0),
    CONSTRAINT CK_SGCD_DET_DEVOLUCION CHECK (
        (DEVOLUCION_PREVISTA_DETALLE IS NULL OR DEVOLUCION_PREVISTA_DETALLE >= ENTREGA_DETALLE)
        AND (DEVOLUCION_REAL_DETALLE IS NULL OR DEVOLUCION_REAL_DETALLE >= ENTREGA_DETALLE)
    )
);


-- ---------------------------------------------------------------------
-- 22. SGCD_PAGOS - exactamente un origen: reserva, operacion o membresia
-- ---------------------------------------------------------------------
CREATE TABLE SGCD_PAGOS (
    ID_PAGO         NUMBER(10) GENERATED BY DEFAULT ON NULL AS IDENTITY,
    ID_RESERVA      NUMBER(10),
    ID_OPERACION    NUMBER(10),
    ID_MEMBRESIA    NUMBER(10),
    FECHA_PAGO      TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
    IMPORTE_PAGO    NUMBER(12,2) NOT NULL,
    MEDIO_PAGO      VARCHAR2(30) NOT NULL,
    CONSTRAINT PK_SGCD_PAGOS PRIMARY KEY (ID_PAGO),
    CONSTRAINT FK_SGCD_PAGO_RESERVA FOREIGN KEY (ID_RESERVA)
        REFERENCES SGCD_RESERVAS (ID_RESERVA),
    CONSTRAINT FK_SGCD_PAGO_OPERACION FOREIGN KEY (ID_OPERACION)
        REFERENCES SGCD_OPERACIONES_IMPLEMENTOS (ID_OPERACION),
    CONSTRAINT FK_SGCD_PAGO_MEMBRESIA FOREIGN KEY (ID_MEMBRESIA)
        REFERENCES SGCD_MEMBRESIAS (ID_MEMBRESIA),
    CONSTRAINT CK_SGCD_PAGO_ORIGEN CHECK (
        CASE WHEN ID_RESERVA   IS NOT NULL THEN 1 ELSE 0 END
      + CASE WHEN ID_OPERACION IS NOT NULL THEN 1 ELSE 0 END
      + CASE WHEN ID_MEMBRESIA IS NOT NULL THEN 1 ELSE 0 END = 1
    ),
    CONSTRAINT CK_SGCD_PAGO_IMPORTE CHECK (IMPORTE_PAGO > 0),
    CONSTRAINT CK_SGCD_PAGO_MEDIO
        CHECK (MEDIO_PAGO IN ('EFECTIVO', 'DEBITO', 'CREDITO', 'TRANSFERENCIA'))
);


