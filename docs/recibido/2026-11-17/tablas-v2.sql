-- SISTEMA DE GESTION DE CENTROS DEPORTIVOS
-- BASE DE DATOS ORACLE
-- MODELO RELACIONAL 3FN



-- 1. TABLA RECINTO


CREATE TABLE SGCD_RECINTOS (
    ID_RECINTO NUMBER(10),
    NOMBRE_RECINTO VARCHAR2(100),
    DIRECCION_RECINTO VARCHAR2(200),

    CONSTRAINT PK_SGCD_RECINTO
    PRIMARY KEY (ID_RECINTO)
);



-- 2. TABLA DEPORTE


CREATE TABLE SGCD_DEPORTES (
    ID_DEPORTE NUMBER(10),
    NOMBRE_DEPORTE VARCHAR2(100),

    CONSTRAINT PK_SGCD_DEPORTE
    PRIMARY KEY (ID_DEPORTE)
);



-- 3. TABLA CLIENTE


CREATE TABLE SGCD_CLIENTES (
    ID_CLIENTE NUMBER(10),
    NOMBRE_CLIENTE VARCHAR2(100),
    TELEFONO_CLIENTE VARCHAR2(20),
    CORREO_CLIENTE VARCHAR2(150),

    CONSTRAINT PK_SGCD_CLIENTE
    PRIMARY KEY (ID_CLIENTE)
);



-- 4. TABLA ADMINISTRADOR


CREATE TABLE SGCD_ADMINISTRADORES (
    ID_ADMINISTRADOR NUMBER(10),
    NOMBRE_ADMINISTRADOR VARCHAR2(100),
    USUARIO_ADMINISTRADOR VARCHAR2(50),
    CLAVE_HASH_ADMINISTRADOR VARCHAR2(255),
    PERFIL_ADMINISTRADOR VARCHAR2(20),

    CONSTRAINT PK_SGCD_ADMINISTRADOR
    PRIMARY KEY (ID_ADMINISTRADOR),

    CONSTRAINT UQ_SGCD_ADMIN_USUARIO
    UNIQUE (USUARIO_ADMINISTRADOR)
);



-- 5. TABLA PLAN_MEMBRESIA


CREATE TABLE SGCD_PLANES_MEMBRESIA (
    ID_PLAN NUMBER(10),
    NOMBRE_PLAN VARCHAR2(100),
    DURACION_DIAS_PLAN NUMBER(5),
    BENEFICIO_PLAN VARCHAR2(200),
    DESCUENTO_PORCENTAJE_PLAN NUMBER(5) DEFAULT 0,

    CONSTRAINT PK_SGCD_PLAN_MEMBRESIA
    PRIMARY KEY (ID_PLAN)
);



-- 6. TABLA ARTICULO


CREATE TABLE SGCD_ARTICULOS (
    ID_ARTICULO NUMBER(10),
    NOMBRE_ARTICULO VARCHAR2(100),
    EXISTENCIAS_VENTA_ARTICULO NUMBER(10) DEFAULT 0,
    EXISTENCIAS_ARRIENDO_ARTICULO NUMBER(10) DEFAULT 0,

    CONSTRAINT PK_SGCD_ARTICULO
    PRIMARY KEY (ID_ARTICULO)
);



-- 7. TABLA CANCHA


CREATE TABLE SGCD_CANCHAS (
    ID_CANCHA NUMBER(10),
    ID_RECINTO NUMBER(10),
    NOMBRE_CANCHA VARCHAR2(100),
    SUPERFICIE_CANCHA VARCHAR2(50),
    ESTADO_CANCHA VARCHAR2(20),

    CONSTRAINT PK_SGCD_CANCHA
    PRIMARY KEY (ID_CANCHA),

    CONSTRAINT FK_SGCD_CANCHA_RECINTO
    FOREIGN KEY (ID_RECINTO)
    REFERENCES SGCD_RECINTOS (ID_RECINTO)
);



-- 8. TABLA MODALIDAD


CREATE TABLE SGCD_MODALIDADES (
    ID_MODALIDAD NUMBER(10),
    ID_DEPORTE NUMBER(10),
    NOMBRE_MODALIDAD VARCHAR2(100),

    CONSTRAINT PK_SGCD_MODALIDAD
    PRIMARY KEY (ID_MODALIDAD),

    CONSTRAINT FK_SGCD_MODALIDAD_DEP
    FOREIGN KEY (ID_DEPORTE)
    REFERENCES SGCD_DEPORTES (ID_DEPORTE)
);



-- 9. TABLA HORARIO


CREATE TABLE SGCD_HORARIOS (
    ID_HORARIO NUMBER(10),
    ID_RECINTO NUMBER(10),
    DIA_SEMANA_HORARIO NUMBER(1),
    HORA_APERTURA_HORARIO VARCHAR2(5),
    HORA_CIERRE_HORARIO VARCHAR2(5),

    CONSTRAINT PK_SGCD_HORARIO
    PRIMARY KEY (ID_HORARIO),

    CONSTRAINT FK_SGCD_HORARIO_RECINTO
    FOREIGN KEY (ID_RECINTO)
    REFERENCES SGCD_RECINTOS (ID_RECINTO)
);



-- 10. TABLA CANCHA_MODALIDAD
-- PK COMPUESTA


CREATE TABLE SGCD_CANCHAS_MODALIDADES (
    ID_CANCHA NUMBER(10),
    ID_MODALIDAD NUMBER(10),

    CONSTRAINT PK_SGCD_CANCHA_MODALIDAD
    PRIMARY KEY (ID_CANCHA, ID_MODALIDAD),

    CONSTRAINT FK_SGCD_CM_CANCHA
    FOREIGN KEY (ID_CANCHA)
    REFERENCES SGCD_CANCHAS (ID_CANCHA),

    CONSTRAINT FK_SGCD_CM_MODALIDAD
    FOREIGN KEY (ID_MODALIDAD)
    REFERENCES SGCD_MODALIDADES (ID_MODALIDAD)
);



-- 11. TABLA TARIFA


CREATE TABLE SGCD_TARIFAS (
    ID_TARIFA NUMBER(10),
    ID_CANCHA NUMBER(10),
    ID_MODALIDAD NUMBER(10),
    DIA_SEMANA_TARIFA NUMBER(1),
    HORA_DESDE_TARIFA VARCHAR2(5),
    HORA_HASTA_TARIFA VARCHAR2(5),
    VIGENTE_DESDE_TARIFA DATE,
    VIGENTE_HASTA_TARIFA DATE,
    VALOR_HORA_TARIFA NUMBER(10),

    CONSTRAINT PK_SGCD_TARIFA
    PRIMARY KEY (ID_TARIFA),

    CONSTRAINT FK_SGCD_TARIFA_CM
    FOREIGN KEY (ID_CANCHA, ID_MODALIDAD)
    REFERENCES SGCD_CANCHAS_MODALIDADES
    (ID_CANCHA, ID_MODALIDAD)
);



-- 12. TABLA MEMBRESIA


CREATE TABLE SGCD_MEMBRESIAS (
    ID_MEMBRESIA NUMBER(10),
    ID_CLIENTE NUMBER(10),
    ID_PLAN NUMBER(10),
    FECHA_INICIO_MEMBRESIA DATE,
    FECHA_TERMINO_MEMBRESIA DATE,

    CONSTRAINT PK_SGCD_MEMBRESIA
    PRIMARY KEY (ID_MEMBRESIA),

    CONSTRAINT FK_SGCD_MEMB_CLIENTE
    FOREIGN KEY (ID_CLIENTE)
    REFERENCES SGCD_CLIENTES (ID_CLIENTE),

    CONSTRAINT FK_SGCD_MEMB_PLAN
    FOREIGN KEY (ID_PLAN)
    REFERENCES SGCD_PLANES_MEMBRESIA (ID_PLAN)
);



-- 13. TABLA MOVIMIENTO_PUNTOS


CREATE TABLE SGCD_MOVIMIENTOS_PUNTOS (
    ID_MOVIMIENTO NUMBER(10),
    ID_CLIENTE NUMBER(10),
    FECHA_MOVIMIENTO DATE,
    TIPO_MOVIMIENTO VARCHAR2(15),
    CANTIDAD_MOVIMIENTO NUMBER(10),

    CONSTRAINT PK_SGCD_MOVIMIENTO_PUNTOS
    PRIMARY KEY (ID_MOVIMIENTO),

    CONSTRAINT FK_SGCD_MOV_CLIENTE
    FOREIGN KEY (ID_CLIENTE)
    REFERENCES SGCD_CLIENTES (ID_CLIENTE)
);



-- 14. TABLA RESERVA


CREATE TABLE SGCD_RESERVAS (
    ID_RESERVA NUMBER(10),
    ID_CLIENTE NUMBER(10),
    ID_ADMINISTRADOR NUMBER(10),
    ID_CANCHA NUMBER(10),
    ID_MODALIDAD NUMBER(10),
    INICIO_RESERVA DATE,
    TERMINO_RESERVA DATE,
    IMPORTE_ACORDADO_RESERVA NUMBER(10),
    ESTADO_RESERVA VARCHAR2(20) DEFAULT 'PENDIENTE',

    CONSTRAINT PK_SGCD_RESERVA
    PRIMARY KEY (ID_RESERVA),

    CONSTRAINT FK_SGCD_RES_CLIENTE
    FOREIGN KEY (ID_CLIENTE)
    REFERENCES SGCD_CLIENTES (ID_CLIENTE),

    CONSTRAINT FK_SGCD_RES_ADMIN
    FOREIGN KEY (ID_ADMINISTRADOR)
    REFERENCES SGCD_ADMINISTRADORES (ID_ADMINISTRADOR),

    CONSTRAINT FK_SGCD_RES_CM
    FOREIGN KEY (ID_CANCHA, ID_MODALIDAD)
    REFERENCES SGCD_CANCHAS_MODALIDADES
    (ID_CANCHA, ID_MODALIDAD)
);



-- 15. TABLA OPERACION_IMPLEMENTOS


CREATE TABLE SGCD_OPERACIONES_IMPLEMENTOS (
    ID_OPERACION NUMBER(10),
    ID_CLIENTE NUMBER(10),
    TIPO_OPERACION VARCHAR2(10),
    FECHA_OPERACION DATE,
    IMPORTE_TOTAL_OPERACION NUMBER(10),

    CONSTRAINT PK_SGCD_OPER_IMPLEMENTOS
    PRIMARY KEY (ID_OPERACION),

    CONSTRAINT FK_SGCD_OPER_CLIENTE
    FOREIGN KEY (ID_CLIENTE)
    REFERENCES SGCD_CLIENTES (ID_CLIENTE)
);



-- 16. TABLA DETALLE_IMPLEMENTO
-- PK COMPUESTA


CREATE TABLE SGCD_DETALLES_IMPLEMENTOS (
    ID_OPERACION NUMBER(10),
    ID_ARTICULO NUMBER(10),
    CANTIDAD_DETALLE NUMBER(10),
    PRECIO_ACORDADO_DETALLE NUMBER(10),
    ENTREGA_DETALLE DATE,
    DEVOLUCION_PREVISTA_DETALLE DATE,
    DEVOLUCION_REAL_DETALLE DATE,

    CONSTRAINT PK_SGCD_DET_IMPLEMENTOS
    PRIMARY KEY (ID_OPERACION, ID_ARTICULO),

    CONSTRAINT FK_SGCD_DET_OPERACION
    FOREIGN KEY (ID_OPERACION)
    REFERENCES SGCD_OPERACIONES_IMPLEMENTOS (ID_OPERACION),

    CONSTRAINT FK_SGCD_DET_ARTICULO
    FOREIGN KEY (ID_ARTICULO)
    REFERENCES SGCD_ARTICULOS (ID_ARTICULO)
);



-- 17. TABLA PAGO


CREATE TABLE SGCD_PAGOS (
    ID_PAGO NUMBER(10),
    ID_RESERVA NUMBER(10),
    ID_OPERACION NUMBER(10),
    FECHA_PAGO DATE,
    IMPORTE_PAGO NUMBER(10),
    MEDIO_PAGO VARCHAR2(30),

    CONSTRAINT PK_SGCD_PAGO
    PRIMARY KEY (ID_PAGO),

    CONSTRAINT FK_SGCD_PAGO_RESERVA
    FOREIGN KEY (ID_RESERVA)
    REFERENCES SGCD_RESERVAS (ID_RESERVA),

    CONSTRAINT FK_SGCD_PAGO_OPERACION
    FOREIGN KEY (ID_OPERACION)
    REFERENCES SGCD_OPERACIONES_IMPLEMENTOS (ID_OPERACION)
);