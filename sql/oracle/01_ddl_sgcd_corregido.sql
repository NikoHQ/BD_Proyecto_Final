-- =====================================================================
-- SISTEMA DE GESTION DE CENTROS DEPORTIVOS - SGCD
-- DDL Oracle 23ai · 17 tablas · modelo 3FN
--
-- Origen: 17-11-26/3EB070B49142DEC4AE7096-tablas.sql (recibido 17-11).
-- Este script es ese mismo modelo con las correcciones C-01..C-20
-- documentadas en ANALISIS_17-11-26_vs_nuestro.md.
--
-- Cambios estructurales respecto al archivo recibido:
--   * PAGOS incorpora ID_MEMBRESIA y un CHECK XOR real (C-01, C-16).
--   * Todas las columnas descriptivas y FK son NOT NULL (C-02).
--   * Dinero en NUMBER(12,2); horas en CHAR(5) con REGEXP (C-04, C-05).
--   * Fechas-hora en TIMESTAMP; superficie en NUMBER(8,2) (C-06, C-07).
--   * UNIQUE en claves naturales + CHECK de dominio y de rango (C-08..C-11).
--   * Indices sobre FK, ON DELETE donde el hijo no vive solo (C-12, C-13).
--   * PK con GENERATED BY DEFAULT ON NULL AS IDENTITY (C-15).
--   * CANCHAS.TIPO_CANCHA: gimnasio, sala y piscina dejan de ser canchas (C-18).
--
-- Reglas que NO pueden expresarse en DDL y quedan para PL/SQL:
--   * Solapamiento de reservas (dos reservas que se cruzan en el tiempo).
--   * Vigencia de membresia contra la fecha de la reserva.
--   * Saldo de puntos del cliente.
--   * Stock real de articulos frente a MOVIMIENTO/EXISTENCIAS.
-- =====================================================================


-- 1. TABLA RECINTO
CREATE TABLE SGCD_RECINTOS (
    ID_RECINTO      NUMBER(10) GENERATED BY DEFAULT ON NULL AS IDENTITY,
    NOMBRE_RECINTO  VARCHAR2(100) NOT NULL,
    DIRECCION_RECINTO VARCHAR2(200) NOT NULL,
    COMUNA_RECINTO  VARCHAR2(80)  NOT NULL,
    TELEFONO_RECINTO VARCHAR2(20),
    ESTADO_RECINTO  VARCHAR2(10) DEFAULT 'ACTIVO' NOT NULL,
    CREADO_EN_RECINTO TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,

    CONSTRAINT PK_SGCD_RECINTOS PRIMARY KEY (ID_RECINTO),
    CONSTRAINT UQ_SGCD_RECINTO_NOMBRE UNIQUE (NOMBRE_RECINTO, COMUNA_RECINTO),
    CONSTRAINT CK_SGCD_RECINTO_ESTADO CHECK (ESTADO_RECINTO IN ('ACTIVO', 'INACTIVO'))
);


-- 2. TABLA DEPORTE
CREATE TABLE SGCD_DEPORTES (
    ID_DEPORTE      NUMBER(10) GENERATED BY DEFAULT ON NULL AS IDENTITY,
    NOMBRE_DEPORTE  VARCHAR2(100) NOT NULL,
    ESTADO_DEPORTE  VARCHAR2(10) DEFAULT 'ACTIVO' NOT NULL,

    CONSTRAINT PK_SGCD_DEPORTES PRIMARY KEY (ID_DEPORTE),
    CONSTRAINT UQ_SGCD_DEPORTE_NOMBRE UNIQUE (NOMBRE_DEPORTE),
    CONSTRAINT CK_SGCD_DEPORTE_ESTADO CHECK (ESTADO_DEPORTE IN ('ACTIVO', 'INACTIVO'))
);


-- 3. TABLA CLIENTE
CREATE TABLE SGCD_CLIENTES (
    ID_CLIENTE      NUMBER(10) GENERATED BY DEFAULT ON NULL AS IDENTITY,
    NOMBRE_CLIENTE  VARCHAR2(100) NOT NULL,
    TELEFONO_CLIENTE VARCHAR2(20),
    CORREO_CLIENTE  VARCHAR2(150),
    ESTADO_CLIENTE  VARCHAR2(10) DEFAULT 'ACTIVO' NOT NULL,
    CREADO_EN_CLIENTE TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,

    CONSTRAINT PK_SGCD_CLIENTES PRIMARY KEY (ID_CLIENTE),
    CONSTRAINT CK_SGCD_CLIENTE_ESTADO CHECK (ESTADO_CLIENTE IN ('ACTIVO', 'INACTIVO'))
);


-- 4. TABLA ADMINISTRADOR
CREATE TABLE SGCD_ADMINISTRADORES (
    ID_ADMINISTRADOR NUMBER(10) GENERATED BY DEFAULT ON NULL AS IDENTITY,
    NOMBRE_ADMINISTRADOR VARCHAR2(100) NOT NULL,
    USUARIO_ADMINISTRADOR VARCHAR2(50) NOT NULL,
    CLAVE_HASH_ADMINISTRADOR VARCHAR2(255) NOT NULL,
    PERFIL_ADMINISTRADOR VARCHAR2(20) DEFAULT 'OPERADOR' NOT NULL,
    ESTADO_ADMINISTRADOR VARCHAR2(10) DEFAULT 'ACTIVO' NOT NULL,

    CONSTRAINT PK_SGCD_ADMINISTRADORES PRIMARY KEY (ID_ADMINISTRADOR),
    CONSTRAINT UQ_SGCD_ADMIN_USUARIO UNIQUE (USUARIO_ADMINISTRADOR),
    CONSTRAINT CK_SGCD_ADMIN_PERFIL CHECK (PERFIL_ADMINISTRADOR IN ('ADMINISTRADOR', 'OPERADOR')),
    CONSTRAINT CK_SGCD_ADMIN_ESTADO CHECK (ESTADO_ADMINISTRADOR IN ('ACTIVO', 'INACTIVO'))
);


-- 5. TABLA PLAN_MEMBRESIA
CREATE TABLE SGCD_PLANES_MEMBRESIA (
    ID_PLAN         NUMBER(10) GENERATED BY DEFAULT ON NULL AS IDENTITY,
    NOMBRE_PLAN     VARCHAR2(100) NOT NULL,
    DURACION_DIAS_PLAN NUMBER(5) NOT NULL,
    BENEFICIO_PLAN  VARCHAR2(200),
    DESCUENTO_PORCENTAJE_PLAN NUMBER(5,2) DEFAULT 0 NOT NULL,
    ESTADO_PLAN     VARCHAR2(10) DEFAULT 'ACTIVO' NOT NULL,

    CONSTRAINT PK_SGCD_PLANES_MEMBRESIA PRIMARY KEY (ID_PLAN),
    CONSTRAINT UQ_SGCD_PLAN_NOMBRE UNIQUE (NOMBRE_PLAN),
    CONSTRAINT CK_SGCD_PLAN_DURACION CHECK (DURACION_DIAS_PLAN > 0),
    CONSTRAINT CK_SGCD_PLAN_DESCUENTO CHECK (DESCUENTO_PORCENTAJE_PLAN BETWEEN 0 AND 100),
    CONSTRAINT CK_SGCD_PLAN_ESTADO CHECK (ESTADO_PLAN IN ('ACTIVO', 'INACTIVO'))
);


-- 6. TABLA ARTICULO
CREATE TABLE SGCD_ARTICULOS (
    ID_ARTICULO     NUMBER(10) GENERATED BY DEFAULT ON NULL AS IDENTITY,
    NOMBRE_ARTICULO VARCHAR2(100) NOT NULL,
    EXISTENCIAS_VENTA_ARTICULO NUMBER(10) DEFAULT 0 NOT NULL,
    EXISTENCIAS_ARRIENDO_ARTICULO NUMBER(10) DEFAULT 0 NOT NULL,
    PRECIO_VENTA_ARTICULO NUMBER(12,2),
    PRECIO_ARRIENDO_ARTICULO NUMBER(12,2),
    ESTADO_ARTICULO VARCHAR2(10) DEFAULT 'ACTIVO' NOT NULL,

    CONSTRAINT PK_SGCD_ARTICULOS PRIMARY KEY (ID_ARTICULO),
    CONSTRAINT UQ_SGCD_ARTICULO_NOMBRE UNIQUE (NOMBRE_ARTICULO),
    CONSTRAINT CK_SGCD_ART_STOCK CHECK (EXISTENCIAS_VENTA_ARTICULO >= 0
                                    AND EXISTENCIAS_ARRIENDO_ARTICULO >= 0),
    CONSTRAINT CK_SGCD_ART_PRECIOS CHECK ((PRECIO_VENTA_ARTICULO IS NULL OR PRECIO_VENTA_ARTICULO >= 0)
                                      AND (PRECIO_ARRIENDO_ARTICULO IS NULL OR PRECIO_ARRIENDO_ARTICULO >= 0)),
    CONSTRAINT CK_SGCD_ART_ESTADO CHECK (ESTADO_ARTICULO IN ('ACTIVO', 'INACTIVO'))
);


-- 7. TABLA CANCHA (instalacion: cancha, gimnasio, sala o piscina)
CREATE TABLE SGCD_CANCHAS (
    ID_CANCHA       NUMBER(10) GENERATED BY DEFAULT ON NULL AS IDENTITY,
    ID_RECINTO      NUMBER(10) NOT NULL,
    NOMBRE_CANCHA   VARCHAR2(100) NOT NULL,
    TIPO_CANCHA     VARCHAR2(20) DEFAULT 'CANCHA' NOT NULL,
    SUPERFICIE_CANCHA NUMBER(8,2),
    ESTADO_CANCHA   VARCHAR2(20) DEFAULT 'DISPONIBLE' NOT NULL,

    CONSTRAINT PK_SGCD_CANCHAS PRIMARY KEY (ID_CANCHA),
    CONSTRAINT FK_SGCD_CANCHA_RECINTO FOREIGN KEY (ID_RECINTO)
        REFERENCES SGCD_RECINTOS (ID_RECINTO),
    CONSTRAINT UQ_SGCD_CANCHA_NOMBRE UNIQUE (ID_RECINTO, NOMBRE_CANCHA),
    CONSTRAINT CK_SGCD_CANCHA_TIPO CHECK (TIPO_CANCHA IN ('CANCHA', 'GIMNASIO', 'SALA', 'PISCINA')),
    CONSTRAINT CK_SGCD_CANCHA_SUPERFICIE CHECK (SUPERFICIE_CANCHA IS NULL OR SUPERFICIE_CANCHA > 0),
    CONSTRAINT CK_SGCD_CANCHA_ESTADO CHECK (ESTADO_CANCHA IN ('DISPONIBLE', 'MANTENCION', 'INACTIVA'))
);


-- 8. TABLA MODALIDAD
CREATE TABLE SGCD_MODALIDADES (
    ID_MODALIDAD    NUMBER(10) GENERATED BY DEFAULT ON NULL AS IDENTITY,
    ID_DEPORTE      NUMBER(10) NOT NULL,
    NOMBRE_MODALIDAD VARCHAR2(100) NOT NULL,
    ESTADO_MODALIDAD VARCHAR2(10) DEFAULT 'ACTIVO' NOT NULL,

    CONSTRAINT PK_SGCD_MODALIDADES PRIMARY KEY (ID_MODALIDAD),
    CONSTRAINT FK_SGCD_MODALIDAD_DEP FOREIGN KEY (ID_DEPORTE)
        REFERENCES SGCD_DEPORTES (ID_DEPORTE),
    CONSTRAINT UQ_SGCD_MODALIDAD_NOMBRE UNIQUE (ID_DEPORTE, NOMBRE_MODALIDAD),
    CONSTRAINT CK_SGCD_MODALIDAD_ESTADO CHECK (ESTADO_MODALIDAD IN ('ACTIVO', 'INACTIVO'))
);


-- 9. TABLA HORARIO
CREATE TABLE SGCD_HORARIOS (
    ID_HORARIO      NUMBER(10) GENERATED BY DEFAULT ON NULL AS IDENTITY,
    ID_RECINTO      NUMBER(10) NOT NULL,
    DIA_SEMANA_HORARIO NUMBER(1) NOT NULL,
    HORA_APERTURA_HORARIO CHAR(5) NOT NULL,
    HORA_CIERRE_HORARIO   CHAR(5) NOT NULL,

    CONSTRAINT PK_SGCD_HORARIOS PRIMARY KEY (ID_HORARIO),
    CONSTRAINT FK_SGCD_HORARIO_RECINTO FOREIGN KEY (ID_RECINTO)
        REFERENCES SGCD_RECINTOS (ID_RECINTO) ON DELETE CASCADE,
    CONSTRAINT UQ_SGCD_HORARIO_REC_DIA UNIQUE (ID_RECINTO, DIA_SEMANA_HORARIO),
    CONSTRAINT CK_SGCD_HORARIO_DIA CHECK (DIA_SEMANA_HORARIO BETWEEN 1 AND 7),
    CONSTRAINT CK_SGCD_HORARIO_APERTURA
        CHECK (REGEXP_LIKE(HORA_APERTURA_HORARIO, '^([01][0-9]|2[0-3]):[0-5][0-9]$')),
    CONSTRAINT CK_SGCD_HORARIO_CIERRE
        CHECK (REGEXP_LIKE(HORA_CIERRE_HORARIO, '^([01][0-9]|2[0-3]):[0-5][0-9]$')),
    CONSTRAINT CK_SGCD_HORARIO_RANGO CHECK (HORA_APERTURA_HORARIO < HORA_CIERRE_HORARIO)
);


-- 10. TABLA CANCHA_MODALIDAD (PK compuesta)
CREATE TABLE SGCD_CANCHAS_MODALIDADES (
    ID_CANCHA       NUMBER(10) NOT NULL,
    ID_MODALIDAD    NUMBER(10) NOT NULL,

    CONSTRAINT PK_SGCD_CANCHAS_MODALIDADES PRIMARY KEY (ID_CANCHA, ID_MODALIDAD),
    CONSTRAINT FK_SGCD_CM_CANCHA FOREIGN KEY (ID_CANCHA)
        REFERENCES SGCD_CANCHAS (ID_CANCHA) ON DELETE CASCADE,
    CONSTRAINT FK_SGCD_CM_MODALIDAD FOREIGN KEY (ID_MODALIDAD)
        REFERENCES SGCD_MODALIDADES (ID_MODALIDAD)
);


-- 11. TABLA TARIFA
CREATE TABLE SGCD_TARIFAS (
    ID_TARIFA       NUMBER(10) GENERATED BY DEFAULT ON NULL AS IDENTITY,
    ID_CANCHA       NUMBER(10) NOT NULL,
    ID_MODALIDAD    NUMBER(10) NOT NULL,
    DIA_SEMANA_TARIFA NUMBER(1) NOT NULL,
    HORA_DESDE_TARIFA CHAR(5) NOT NULL,
    HORA_HASTA_TARIFA CHAR(5) NOT NULL,
    VIGENTE_DESDE_TARIFA DATE NOT NULL,
    VIGENTE_HASTA_TARIFA DATE,
    VALOR_HORA_TARIFA NUMBER(12,2) NOT NULL,
    ESTADO_TARIFA   VARCHAR2(10) DEFAULT 'ACTIVA' NOT NULL,

    CONSTRAINT PK_SGCD_TARIFAS PRIMARY KEY (ID_TARIFA),
    CONSTRAINT FK_SGCD_TARIFA_CM FOREIGN KEY (ID_CANCHA, ID_MODALIDAD)
        REFERENCES SGCD_CANCHAS_MODALIDADES (ID_CANCHA, ID_MODALIDAD),
    CONSTRAINT UQ_SGCD_TARIFA_BANDA UNIQUE (ID_CANCHA, ID_MODALIDAD, DIA_SEMANA_TARIFA,
                                           HORA_DESDE_TARIFA, VIGENTE_DESDE_TARIFA),
    CONSTRAINT CK_SGCD_TARIFA_DIA CHECK (DIA_SEMANA_TARIFA BETWEEN 1 AND 7),
    CONSTRAINT CK_SGCD_TARIFA_DESDE
        CHECK (REGEXP_LIKE(HORA_DESDE_TARIFA, '^([01][0-9]|2[0-3]):[0-5][0-9]$')),
    CONSTRAINT CK_SGCD_TARIFA_HASTA
        CHECK (REGEXP_LIKE(HORA_HASTA_TARIFA, '^([01][0-9]|2[0-3]):[0-5][0-9]$')),
    CONSTRAINT CK_SGCD_TARIFA_HORAS CHECK (HORA_DESDE_TARIFA < HORA_HASTA_TARIFA),
    CONSTRAINT CK_SGCD_TARIFA_VIGENCIA
        CHECK (VIGENTE_HASTA_TARIFA IS NULL OR VIGENTE_HASTA_TARIFA >= VIGENTE_DESDE_TARIFA),
    CONSTRAINT CK_SGCD_TARIFA_VALOR CHECK (VALOR_HORA_TARIFA > 0),
    CONSTRAINT CK_SGCD_TARIFA_ESTADO CHECK (ESTADO_TARIFA IN ('ACTIVA', 'INACTIVA'))
);


-- 12. TABLA MEMBRESIA
