-- =====================================================================
-- MANTENEDORES DE HORARIO - horario del recinto, bloques y administradores
-- Requiere: 10_ddl_sgcd_19.sql, 11_catalogos_sgcd_19.sql y 12a_pkg_auth.sql
--
-- Codigo de Ignacio (23-11-26/mi_parte_nuevo), con los mismos cambios de la
-- unidad 3: mensajes sin tildes y sin lineas en blanco dentro de cada sentencia.
-- Aqui ademas se renombraron tres columnas al modelo de 19 tablas:
--   DIA_SEMANA_HORARIO    -> DIA_SEMANA
--   HORA_APERTURA_HORARIO -> HORA_APERTURA
--   HORA_CIERRE_HORARIO   -> HORA_CIERRE
--
-- El bloque es de una hora exacta y tiene que caber en la ventana del horario.
-- El alta de administrador vincula una cuenta existente con rol ADMINISTRADOR;
-- la cuenta la crea SGCD_PKG_AUTH.crear_usuario.
--
-- Codigos: -20820 horario inexistente, -20821 formato de hora, -20822 duracion
-- distinta de una hora, -20823 bloque fuera de la ventana, -20824 bloque
-- solapado, -20825 bloque inexistente, -20840 dia fuera de 1..7,
-- -20841 horario repetido, -20842 bloques fuera del nuevo horario,
-- -20843 horario inexistente, -20844 horario con bloques.
-- Administradores usa -20860..-20864, el mismo rango que canchas.
-- =====================================================================


SET DEFINE OFF


-- ---------------------------------------------------------------------
-- HORARIO DEL RECINTO
-- ---------------------------------------------------------------------
CREATE OR REPLACE PROCEDURE SGCD_CREAR_HORARIO (
    ID_RECINTO_P NUMBER,
    DIA_P NUMBER,
    APERTURA_P VARCHAR2,
    CIERRE_P VARCHAR2,
    ID_HORARIO_P OUT NUMBER
)
IS
BEGIN
    IF DIA_P IS NULL OR DIA_P < 1 OR DIA_P > 7 OR DIA_P <> TRUNC(DIA_P) THEN
        RAISE_APPLICATION_ERROR(-20840, 'Ingrese un dia entero entre 1 y 7');
    END IF;
    INSERT INTO SGCD_HORARIOS (
        ID_RECINTO, DIA_SEMANA, HORA_APERTURA, HORA_CIERRE
    ) VALUES (
        ID_RECINTO_P, DIA_P, APERTURA_P, CIERRE_P
    ) RETURNING ID_HORARIO INTO ID_HORARIO_P;
EXCEPTION
    WHEN DUP_VAL_ON_INDEX THEN
        RAISE_APPLICATION_ERROR(-20841, 'Ya existe un horario para ese dia y recinto');
END;
/


CREATE OR REPLACE PROCEDURE SGCD_LISTAR_HORARIOS (
    ID_RECINTO_P NUMBER,
    HORARIOS_P OUT SYS_REFCURSOR
)
IS
BEGIN
    OPEN HORARIOS_P FOR
        SELECT ID_HORARIO, DIA_SEMANA, HORA_APERTURA, HORA_CIERRE
        FROM SGCD_HORARIOS
        WHERE ID_RECINTO = ID_RECINTO_P
        ORDER BY DIA_SEMANA;
END;
/


CREATE OR REPLACE PROCEDURE SGCD_ACTUALIZAR_HORARIO (
    ID_HORARIO_P NUMBER,
    APERTURA_P VARCHAR2,
    CIERRE_P VARCHAR2
)
IS
    ID_HORARIO_V NUMBER;
    BLOQUES_FUERA_V NUMBER;
BEGIN
    -- El mantenedor de bloques tambien bloquea esta fila antes de guardar.
    SELECT ID_HORARIO INTO ID_HORARIO_V FROM SGCD_HORARIOS
    WHERE ID_HORARIO = ID_HORARIO_P
    FOR UPDATE;
    SELECT COUNT(*) INTO BLOQUES_FUERA_V FROM SGCD_BLOQUES_HORARIOS
    WHERE ID_HORARIO = ID_HORARIO_V
      AND (HORA_INICIO < APERTURA_P OR HORA_TERMINO > CIERRE_P);
    IF BLOQUES_FUERA_V > 0 THEN
        RAISE_APPLICATION_ERROR(-20842, 'Hay bloques fuera del nuevo horario');
    END IF;
    UPDATE SGCD_HORARIOS
    SET HORA_APERTURA = APERTURA_P,
        HORA_CIERRE = CIERRE_P
    WHERE ID_HORARIO = ID_HORARIO_V;
EXCEPTION
    WHEN NO_DATA_FOUND THEN
        RAISE_APPLICATION_ERROR(-20843, 'El horario no existe');
END;
/


CREATE OR REPLACE PROCEDURE SGCD_BORRAR_HORARIO (
    ID_HORARIO_P NUMBER
)
IS
    ID_HORARIO_V NUMBER;
    BLOQUES_V NUMBER;
BEGIN
    SELECT ID_HORARIO INTO ID_HORARIO_V
    FROM SGCD_HORARIOS
    WHERE ID_HORARIO = ID_HORARIO_P
    FOR UPDATE;
    SELECT COUNT(*) INTO BLOQUES_V
    FROM SGCD_BLOQUES_HORARIOS
    WHERE ID_HORARIO = ID_HORARIO_V;
    IF BLOQUES_V > 0 THEN
        RAISE_APPLICATION_ERROR(-20844, 'Quite los bloques antes de borrar el horario');
    END IF;
    DELETE FROM SGCD_HORARIOS WHERE ID_HORARIO = ID_HORARIO_V;
EXCEPTION
    WHEN NO_DATA_FOUND THEN
        RAISE_APPLICATION_ERROR(-20843, 'El horario no existe');
END;
/


-- ---------------------------------------------------------------------
-- BLOQUES DE LA PLANTILLA SEMANAL
-- ---------------------------------------------------------------------
CREATE OR REPLACE PROCEDURE SGCD_VALIDAR_BLOQUE_HORARIO (
    ID_HORARIO_P NUMBER,
    HORA_INICIO_P VARCHAR2,
    HORA_TERMINO_P VARCHAR2,
    ID_BLOQUE_P NUMBER
)
IS
    APERTURA_V SGCD_HORARIOS.HORA_APERTURA%TYPE;
    CIERRE_V SGCD_HORARIOS.HORA_CIERRE%TYPE;
    COINCIDENCIAS_V NUMBER;
BEGIN
    IF HORA_INICIO_P IS NULL OR HORA_TERMINO_P IS NULL
       OR NOT REGEXP_LIKE(HORA_INICIO_P, '^([01][0-9]|2[0-3]):[0-5][0-9]$')
       OR NOT REGEXP_LIKE(HORA_TERMINO_P, '^([01][0-9]|2[0-3]):[0-5][0-9]$') THEN
        RAISE_APPLICATION_ERROR(-20821, 'Ingrese las horas en formato HH:MI');
    END IF;
    IF (TO_NUMBER(SUBSTR(HORA_TERMINO_P, 1, 2)) -
        TO_NUMBER(SUBSTR(HORA_INICIO_P, 1, 2))) * 60 +
        TO_NUMBER(SUBSTR(HORA_TERMINO_P, 4, 2)) -
        TO_NUMBER(SUBSTR(HORA_INICIO_P, 4, 2)) <> 60 THEN
        RAISE_APPLICATION_ERROR(-20822, 'El bloque debe durar una hora');
    END IF;
    -- Se bloquea el horario para que dos altas simultaneas no se solapen.
    SELECT HORA_APERTURA, HORA_CIERRE
    INTO APERTURA_V, CIERRE_V FROM SGCD_HORARIOS
    WHERE ID_HORARIO = ID_HORARIO_P
    FOR UPDATE;
    IF HORA_INICIO_P < APERTURA_V OR HORA_TERMINO_P > CIERRE_V THEN
        RAISE_APPLICATION_ERROR(-20823, 'El bloque queda fuera del horario del recinto');
    END IF;
    SELECT COUNT(*) INTO COINCIDENCIAS_V FROM SGCD_BLOQUES_HORARIOS
    WHERE ID_HORARIO = ID_HORARIO_P
      AND (ID_BLOQUE_P IS NULL OR ID_BLOQUE_HORARIO <> ID_BLOQUE_P)
      AND HORA_INICIO < HORA_TERMINO_P
      AND HORA_TERMINO > HORA_INICIO_P;
    IF COINCIDENCIAS_V > 0 THEN
        RAISE_APPLICATION_ERROR(-20824, 'El bloque se solapa con otro del mismo horario');
    END IF;
EXCEPTION
    WHEN NO_DATA_FOUND THEN
        RAISE_APPLICATION_ERROR(-20820, 'El horario no existe');
END;
/


CREATE OR REPLACE PROCEDURE SGCD_CREAR_BLOQUE_HORARIO (
    ID_HORARIO_P NUMBER,
    HORA_INICIO_P VARCHAR2,
    HORA_TERMINO_P VARCHAR2,
    ID_BLOQUE_P OUT NUMBER
)
IS
BEGIN
    SGCD_VALIDAR_BLOQUE_HORARIO(ID_HORARIO_P, HORA_INICIO_P, HORA_TERMINO_P, NULL);
    INSERT INTO SGCD_BLOQUES_HORARIOS (ID_HORARIO, HORA_INICIO, HORA_TERMINO)
    VALUES (ID_HORARIO_P, HORA_INICIO_P, HORA_TERMINO_P)
    RETURNING ID_BLOQUE_HORARIO INTO ID_BLOQUE_P;
END;
/


CREATE OR REPLACE PROCEDURE SGCD_LISTAR_BLOQUES_HORARIOS (
    ID_HORARIO_P NUMBER,
    BLOQUES_P OUT SYS_REFCURSOR
) IS
BEGIN
    OPEN BLOQUES_P FOR
        SELECT ID_BLOQUE_HORARIO, HORA_INICIO, HORA_TERMINO
        FROM SGCD_BLOQUES_HORARIOS
        WHERE ID_HORARIO = ID_HORARIO_P
        ORDER BY HORA_INICIO, ID_BLOQUE_HORARIO;
END;
/


CREATE OR REPLACE PROCEDURE SGCD_ACTUALIZAR_BLOQUE_HORARIO (
    ID_BLOQUE_P NUMBER,
    HORA_INICIO_P VARCHAR2,
    HORA_TERMINO_P VARCHAR2
) IS
    ID_HORARIO_V SGCD_BLOQUES_HORARIOS.ID_HORARIO%TYPE;
BEGIN
    SELECT ID_HORARIO INTO ID_HORARIO_V FROM SGCD_BLOQUES_HORARIOS
    WHERE ID_BLOQUE_HORARIO = ID_BLOQUE_P;
    SGCD_VALIDAR_BLOQUE_HORARIO(ID_HORARIO_V, HORA_INICIO_P, HORA_TERMINO_P, ID_BLOQUE_P);
    UPDATE SGCD_BLOQUES_HORARIOS
    SET HORA_INICIO = HORA_INICIO_P, HORA_TERMINO = HORA_TERMINO_P
    WHERE ID_BLOQUE_HORARIO = ID_BLOQUE_P AND ID_HORARIO = ID_HORARIO_V;
    IF SQL%ROWCOUNT = 0 THEN
        RAISE_APPLICATION_ERROR(-20825, 'El bloque no existe');
    END IF;
EXCEPTION
    WHEN NO_DATA_FOUND THEN
        RAISE_APPLICATION_ERROR(-20825, 'El bloque no existe');
END;
/


CREATE OR REPLACE PROCEDURE SGCD_BORRAR_BLOQUE_HORARIO (
    ID_BLOQUE_P NUMBER
)
IS
BEGIN
    DELETE FROM SGCD_BLOQUES_HORARIOS
    WHERE ID_BLOQUE_HORARIO = ID_BLOQUE_P;
    IF SQL%ROWCOUNT = 0 THEN
        RAISE_APPLICATION_ERROR(-20825, 'El bloque no existe');
    END IF;
END;
/


-- ---------------------------------------------------------------------
-- ADMINISTRADORES: vinculan una cuenta existente con rol ADMINISTRADOR
-- ---------------------------------------------------------------------
CREATE OR REPLACE PROCEDURE SGCD_CREAR_ADMINISTRADOR (
    ID_USUARIO_P SGCD_ADMINISTRADORES.ID_USUARIO%TYPE,
    NOMBRE_ADMINISTRADOR_P SGCD_ADMINISTRADORES.NOMBRE_ADMINISTRADOR%TYPE,
    ESTADO_ADMINISTRADOR_P SGCD_ADMINISTRADORES.ESTADO_ADMINISTRADOR%TYPE,
    ID_ADMINISTRADOR_P OUT SGCD_ADMINISTRADORES.ID_ADMINISTRADOR%TYPE
)
IS
    ROL_V SGCD_USUARIOS.ROL%TYPE;
BEGIN
    IF TRIM(NOMBRE_ADMINISTRADOR_P) IS NULL OR ESTADO_ADMINISTRADOR_P IS NULL
       OR ESTADO_ADMINISTRADOR_P NOT IN ('ACTIVO', 'INACTIVO') THEN
        RAISE_APPLICATION_ERROR(-20860, 'Revise el nombre y el estado');
    END IF;
    SELECT ROL INTO ROL_V FROM SGCD_USUARIOS
    WHERE ID_USUARIO = ID_USUARIO_P FOR UPDATE;
    IF ROL_V IS NULL OR ROL_V <> 'ADMINISTRADOR' THEN
        RAISE_APPLICATION_ERROR(-20861, 'La cuenta debe tener rol de administrador');
    END IF;
    INSERT INTO SGCD_ADMINISTRADORES (ID_USUARIO, NOMBRE_ADMINISTRADOR, ESTADO_ADMINISTRADOR)
    VALUES (ID_USUARIO_P, TRIM(NOMBRE_ADMINISTRADOR_P), ESTADO_ADMINISTRADOR_P)
    RETURNING ID_ADMINISTRADOR INTO ID_ADMINISTRADOR_P;
EXCEPTION
    WHEN DUP_VAL_ON_INDEX THEN
        RAISE_APPLICATION_ERROR(-20863, 'El registro ya existe');
    WHEN NO_DATA_FOUND THEN
        RAISE_APPLICATION_ERROR(-20861, 'La cuenta no existe');
END;
/


CREATE OR REPLACE PROCEDURE SGCD_LISTAR_ADMINISTRADORES (
    RESULTADO_P OUT SYS_REFCURSOR
) IS
BEGIN
    OPEN RESULTADO_P FOR
        SELECT a.ID_ADMINISTRADOR, a.ID_USUARIO, a.NOMBRE_ADMINISTRADOR,
               a.ESTADO_ADMINISTRADOR, u.LOGIN
        FROM SGCD_ADMINISTRADORES a
        JOIN SGCD_USUARIOS u ON u.ID_USUARIO = a.ID_USUARIO
        ORDER BY a.NOMBRE_ADMINISTRADOR, a.ID_ADMINISTRADOR;
END;
/


CREATE OR REPLACE PROCEDURE SGCD_ACTUALIZAR_ADMINISTRADOR (
    ID_ADMINISTRADOR_P SGCD_ADMINISTRADORES.ID_ADMINISTRADOR%TYPE,
    NOMBRE_ADMINISTRADOR_P SGCD_ADMINISTRADORES.NOMBRE_ADMINISTRADOR%TYPE,
    ESTADO_ADMINISTRADOR_P SGCD_ADMINISTRADORES.ESTADO_ADMINISTRADOR%TYPE
)
IS
BEGIN
    IF TRIM(NOMBRE_ADMINISTRADOR_P) IS NULL OR ESTADO_ADMINISTRADOR_P IS NULL
       OR ESTADO_ADMINISTRADOR_P NOT IN ('ACTIVO', 'INACTIVO') THEN
        RAISE_APPLICATION_ERROR(-20860, 'Revise el nombre y el estado');
    END IF;
    UPDATE SGCD_ADMINISTRADORES
    SET NOMBRE_ADMINISTRADOR = TRIM(NOMBRE_ADMINISTRADOR_P),
        ESTADO_ADMINISTRADOR = ESTADO_ADMINISTRADOR_P
    WHERE ID_ADMINISTRADOR = ID_ADMINISTRADOR_P;
    IF SQL%ROWCOUNT = 0 THEN
        RAISE_APPLICATION_ERROR(-20862, 'El registro no existe');
    END IF;
EXCEPTION
    WHEN DUP_VAL_ON_INDEX THEN
        RAISE_APPLICATION_ERROR(-20863, 'El registro ya existe');
END;
/


CREATE OR REPLACE PROCEDURE SGCD_BORRAR_ADMINISTRADOR (
    ID_ADMINISTRADOR_P SGCD_ADMINISTRADORES.ID_ADMINISTRADOR%TYPE
)
IS
BEGIN
    DELETE FROM SGCD_ADMINISTRADORES WHERE ID_ADMINISTRADOR = ID_ADMINISTRADOR_P;
    IF SQL%ROWCOUNT = 0 THEN
        RAISE_APPLICATION_ERROR(-20862, 'El registro no existe');
    END IF;
EXCEPTION
    WHEN OTHERS THEN
        IF SQLCODE = -2292 THEN
            RAISE_APPLICATION_ERROR(-20864, 'El registro esta en uso');
        END IF;
        RAISE;
END;
/
