-- ---------------------------------------------------------------------
-- RECINTOS
-- ---------------------------------------------------------------------
CREATE OR REPLACE PROCEDURE SGCD_CREAR_RECINTO (
    P_NOMBRE SGCD_RECINTOS.NOMBRE_RECINTO%TYPE,
    P_DIRECCION SGCD_RECINTOS.DIRECCION_RECINTO%TYPE,
    P_ESTADO SGCD_RECINTOS.ESTADO_RECINTO%TYPE,
    P_ID OUT SGCD_RECINTOS.ID_RECINTO%TYPE
)
IS
BEGIN
    IF TRIM(P_NOMBRE) IS NULL OR TRIM(P_DIRECCION) IS NULL THEN
        RAISE_APPLICATION_ERROR(-20870, 'Ingrese nombre y direccion');
    END IF;
    INSERT INTO SGCD_RECINTOS (NOMBRE_RECINTO, DIRECCION_RECINTO, ESTADO_RECINTO)
    VALUES (TRIM(P_NOMBRE), TRIM(P_DIRECCION), P_ESTADO)
    RETURNING ID_RECINTO INTO P_ID;
EXCEPTION
    WHEN DUP_VAL_ON_INDEX THEN
        RAISE_APPLICATION_ERROR(-20871, 'Ya existe un recinto con ese nombre');
END;
/

CREATE OR REPLACE PROCEDURE SGCD_ACTUALIZAR_RECINTO (
    P_ID SGCD_RECINTOS.ID_RECINTO%TYPE,
    P_NOMBRE SGCD_RECINTOS.NOMBRE_RECINTO%TYPE,
    P_DIRECCION SGCD_RECINTOS.DIRECCION_RECINTO%TYPE,
    P_ESTADO SGCD_RECINTOS.ESTADO_RECINTO%TYPE
)
IS
BEGIN
    IF TRIM(P_NOMBRE) IS NULL OR TRIM(P_DIRECCION) IS NULL THEN
        RAISE_APPLICATION_ERROR(-20870, 'Ingrese nombre y direccion');
    END IF;
    UPDATE SGCD_RECINTOS
    SET NOMBRE_RECINTO = TRIM(P_NOMBRE), DIRECCION_RECINTO = TRIM(P_DIRECCION), ESTADO_RECINTO = P_ESTADO
    WHERE ID_RECINTO = P_ID;
    IF SQL%ROWCOUNT = 0 THEN
        RAISE_APPLICATION_ERROR(-20872, 'El recinto no existe');
    END IF;
EXCEPTION
    WHEN DUP_VAL_ON_INDEX THEN
        RAISE_APPLICATION_ERROR(-20871, 'Ya existe un recinto con ese nombre');
END;
/

CREATE OR REPLACE PROCEDURE SGCD_BORRAR_RECINTO (
    P_ID SGCD_RECINTOS.ID_RECINTO%TYPE
)
IS
    E_EN_USO EXCEPTION;
    PRAGMA EXCEPTION_INIT(E_EN_USO, -2292);
BEGIN
    DELETE FROM SGCD_RECINTOS WHERE ID_RECINTO = P_ID;
    IF SQL%ROWCOUNT = 0 THEN
        RAISE_APPLICATION_ERROR(-20872, 'El recinto no existe');
    END IF;
EXCEPTION
    WHEN E_EN_USO THEN
        RAISE_APPLICATION_ERROR(-20873, 'El recinto tiene canchas u horarios asociados');
END;
/
