-- =====================================================================
-- MANTENEDORES DE CATALOGO - deporte, modalidad, cancha y cancha-modalidad
-- Requiere: 10_ddl_sgcd_19.sql y 11_catalogos_sgcd_19.sql
--
-- Codigo de Ignacio (23-11-26/mi_parte_nuevo). Se conservan sus procedimientos
-- sueltos, sus codigos -208xx y su logica. Solo se cambio:
--   * los mensajes quedaron sin tildes, para que un SQL*Plus sin locale no los
--     guarde como caracteres de reemplazo en el codigo compilado;
--   * se quitaron las lineas en blanco dentro de cada sentencia, porque
--     SQL*Plus con SQLBLANKLINES OFF corta la sentencia en la linea vacia.
--
-- El ID de alta lo devuelve RETURNING sobre la secuencia: la aplicacion nunca
-- lo envia. Ningun procedimiento hace COMMIT.
--
-- Codigos: -20830 nombre obligatorio, -20831 cantidad entera, -20832 no existe,
-- -20833 nombre repetido, -20834 estado invalido, -20835 registro en uso,
-- -20850 par cancha-modalidad repetido, -20851 par cancha-modalidad inexistente,
-- -20860 datos de cancha invalidos, -20862 cancha no existe, -20863 cancha
-- repetida, -20864 cancha en uso.
--
-- Nota: si el padre no existe (por ejemplo una modalidad con ID_DEPORTE
-- inexistente), el FK responde ORA-02291. El API debe traducirlo; no se
-- modifico el procedimiento de Ignacio para eso.
-- =====================================================================


SET DEFINE OFF


-- ---------------------------------------------------------------------
-- DEPORTES
-- ---------------------------------------------------------------------
CREATE OR REPLACE PROCEDURE SGCD_CREAR_DEPORTE (
    NOMBRE_DEPORTE_P SGCD_DEPORTES.NOMBRE_DEPORTE%TYPE,
    ID_DEPORTE_P OUT SGCD_DEPORTES.ID_DEPORTE%TYPE
)
IS
BEGIN
    IF TRIM(NOMBRE_DEPORTE_P) IS NULL THEN
        RAISE_APPLICATION_ERROR(-20830, 'Ingrese un nombre');
    END IF;
    INSERT INTO SGCD_DEPORTES (NOMBRE_DEPORTE, ESTADO_DEPORTE)
    VALUES (TRIM(NOMBRE_DEPORTE_P), 'ACTIVO')
    RETURNING ID_DEPORTE INTO ID_DEPORTE_P;
EXCEPTION
    WHEN DUP_VAL_ON_INDEX THEN
        RAISE_APPLICATION_ERROR(-20833, 'Ya existe un registro con ese nombre');
END;
/


CREATE OR REPLACE PROCEDURE SGCD_LISTAR_DEPORTES (
    RESULTADO_P OUT SYS_REFCURSOR
)
IS
BEGIN
    OPEN RESULTADO_P FOR
        SELECT ID_DEPORTE, NOMBRE_DEPORTE, ESTADO_DEPORTE
        FROM SGCD_DEPORTES
        ORDER BY NOMBRE_DEPORTE, ID_DEPORTE;
END;
/


CREATE OR REPLACE PROCEDURE SGCD_ACTUALIZAR_DEPORTE (
    ID_DEPORTE_P SGCD_DEPORTES.ID_DEPORTE%TYPE,
    NOMBRE_DEPORTE_P SGCD_DEPORTES.NOMBRE_DEPORTE%TYPE,
    ESTADO_DEPORTE_P SGCD_DEPORTES.ESTADO_DEPORTE%TYPE
)
IS
BEGIN
    IF TRIM(NOMBRE_DEPORTE_P) IS NULL THEN
        RAISE_APPLICATION_ERROR(-20830, 'Ingrese un nombre');
    END IF;
    IF ESTADO_DEPORTE_P IS NULL OR ESTADO_DEPORTE_P NOT IN ('ACTIVO', 'INACTIVO') THEN
        RAISE_APPLICATION_ERROR(-20834, 'El estado debe ser ACTIVO o INACTIVO');
    END IF;
    UPDATE SGCD_DEPORTES
    SET NOMBRE_DEPORTE = TRIM(NOMBRE_DEPORTE_P),
        ESTADO_DEPORTE = ESTADO_DEPORTE_P
    WHERE ID_DEPORTE = ID_DEPORTE_P;
    IF SQL%ROWCOUNT = 0 THEN
        RAISE_APPLICATION_ERROR(-20832, 'El registro no existe');
    END IF;
EXCEPTION
    WHEN DUP_VAL_ON_INDEX THEN
        RAISE_APPLICATION_ERROR(-20833, 'Ya existe un registro con ese nombre');
END;
/


CREATE OR REPLACE PROCEDURE SGCD_BORRAR_DEPORTE (
    ID_DEPORTE_P SGCD_DEPORTES.ID_DEPORTE%TYPE
)
IS
BEGIN
    DELETE FROM SGCD_DEPORTES WHERE ID_DEPORTE = ID_DEPORTE_P;
    IF SQL%ROWCOUNT = 0 THEN
        RAISE_APPLICATION_ERROR(-20832, 'El registro no existe');
    END IF;
EXCEPTION
    WHEN OTHERS THEN
        IF SQLCODE = -2292 THEN
            RAISE_APPLICATION_ERROR(-20835, 'El registro esta en uso. Puede desactivarlo');
        END IF;
        RAISE;
END;
/


