-- ---------------------------------------------------------------------
-- 6. Bloques de una hora: uno por cada hora de la ventana de apertura
-- ---------------------------------------------------------------------
INSERT INTO SGCD_BLOQUES_HORARIOS (ID_HORARIO, HORA_INICIO, HORA_TERMINO)
SELECT H.ID_HORARIO,
       TO_CHAR(TO_DATE(H.HORA_APERTURA, 'HH24:MI') + (N.N - 1) / 24, 'HH24:MI'),
       TO_CHAR(TO_DATE(H.HORA_APERTURA, 'HH24:MI') + N.N / 24, 'HH24:MI')
FROM   SGCD_HORARIOS H
CROSS  JOIN (SELECT LEVEL AS N FROM DUAL CONNECT BY LEVEL <= 24) N
WHERE  N.N <= (TO_DATE(H.HORA_CIERRE, 'HH24:MI') - TO_DATE(H.HORA_APERTURA, 'HH24:MI')) * 24
ORDER  BY H.ID_HORARIO, N.N;


