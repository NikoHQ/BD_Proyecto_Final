-- ---------------------------------------------------------------------
-- 9. Reposicionar cada secuencia en MAX+1 de su tabla
-- ---------------------------------------------------------------------
DECLARE
    V_SIGUIENTE NUMBER;
BEGIN
    FOR P IN (
        SELECT 'SGCD_SEQ_RECINTOS' AS SEC, 'SGCD_RECINTOS' AS TAB, 'ID_RECINTO' AS COL FROM DUAL
        UNION ALL SELECT 'SGCD_SEQ_DEPORTES', 'SGCD_DEPORTES', 'ID_DEPORTE' FROM DUAL
        UNION ALL SELECT 'SGCD_SEQ_USUARIOS', 'SGCD_USUARIOS', 'ID_USUARIO' FROM DUAL
        UNION ALL SELECT 'SGCD_SEQ_HORARIOS', 'SGCD_HORARIOS', 'ID_HORARIO' FROM DUAL
        UNION ALL SELECT 'SGCD_SEQ_CANCHAS', 'SGCD_CANCHAS', 'ID_CANCHA' FROM DUAL
        UNION ALL SELECT 'SGCD_SEQ_MODALIDADES', 'SGCD_MODALIDADES', 'ID_MODALIDAD' FROM DUAL
        UNION ALL SELECT 'SGCD_SEQ_CLIENTES', 'SGCD_CLIENTES', 'ID_CLIENTE' FROM DUAL
        UNION ALL SELECT 'SGCD_SEQ_ADMINISTRADORES', 'SGCD_ADMINISTRADORES', 'ID_ADMINISTRADOR' FROM DUAL
        UNION ALL SELECT 'SGCD_SEQ_BLOQUES_HORARIOS', 'SGCD_BLOQUES_HORARIOS', 'ID_BLOQUE_HORARIO' FROM DUAL
        UNION ALL SELECT 'SGCD_SEQ_TORNEOS', 'SGCD_TORNEOS', 'ID_TORNEO' FROM DUAL
        UNION ALL SELECT 'SGCD_SEQ_TARIFAS', 'SGCD_TARIFAS', 'ID_TARIFA' FROM DUAL
        UNION ALL SELECT 'SGCD_SEQ_JUGADORES', 'SGCD_JUGADORES', 'ID_JUGADOR' FROM DUAL
        UNION ALL SELECT 'SGCD_SEQ_INSCRIPCIONES_TORNEO', 'SGCD_INSCRIPCIONES_TORNEO', 'ID_INSCRIPCION' FROM DUAL
        UNION ALL SELECT 'SGCD_SEQ_RESERVAS', 'SGCD_RESERVAS', 'ID_RESERVA' FROM DUAL
        UNION ALL SELECT 'SGCD_SEQ_PAGOS', 'SGCD_PAGOS', 'ID_PAGO' FROM DUAL
        UNION ALL SELECT 'SGCD_SEQ_AUDITORIA_CLIENTES', 'SGCD_AUDITORIA_CLIENTES', 'ID_AUDITORIA' FROM DUAL
    ) LOOP
        EXECUTE IMMEDIATE 'SELECT NVL(MAX(' || P.COL || '), 0) + 1 FROM ' || P.TAB INTO V_SIGUIENTE;
        EXECUTE IMMEDIATE 'ALTER SEQUENCE ' || P.SEC || ' RESTART START WITH ' || V_SIGUIENTE;
    END LOOP;
END;
