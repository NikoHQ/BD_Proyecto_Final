CREATE OR REPLACE PROCEDURE SGCD_ACTUALIZAR_TARIFA (
    ID_TARIFA_P SGCD_TARIFAS.ID_TARIFA%TYPE,
    DIA_P SGCD_TARIFAS.DIA_SEMANA%TYPE,
    HORA_DESDE_P SGCD_TARIFAS.HORA_DESDE%TYPE,
    HORA_HASTA_P SGCD_TARIFAS.HORA_HASTA%TYPE,
    VIGENTE_DESDE_P SGCD_TARIFAS.VIGENTE_DESDE%TYPE,
    VIGENTE_HASTA_P SGCD_TARIFAS.VIGENTE_HASTA%TYPE,
    VALOR_HORA_P SGCD_TARIFAS.VALOR_HORA%TYPE
)
IS
    ID_CANCHA_V SGCD_TARIFAS.ID_CANCHA%TYPE;
    ID_MODALIDAD_V SGCD_TARIFAS.ID_MODALIDAD%TYPE;
    INICIO_ANTERIOR_V DATE;
    ESTADO_ANTERIOR_V SGCD_TARIFAS.ESTADO_TARIFA%TYPE;
    HORA_DESDE_V VARCHAR2(5);
    HORA_HASTA_V VARCHAR2(5);
    VIGENTE_DESDE_V DATE;
    VIGENTE_HASTA_V DATE;
    CANCHA_ENCONTRADA_V NUMBER;
    CANTIDAD_V NUMBER;
BEGIN
    IF ID_TARIFA_P IS NULL
       OR ID_TARIFA_P <= 0
       OR ID_TARIFA_P <> TRUNC(ID_TARIFA_P) THEN
        RAISE_APPLICATION_ERROR(-20801, 'EL ID DE LA TARIFA NO ES VALIDO');
    END IF;
    IF DIA_P IS NULL OR DIA_P < 1 OR DIA_P > 7 OR DIA_P <> TRUNC(DIA_P) THEN
        RAISE_APPLICATION_ERROR(-20804, 'EL DIA DEBE ESTAR ENTRE UNO Y SIETE');
    END IF;
    HORA_DESDE_V := TRIM(HORA_DESDE_P);
    HORA_HASTA_V := TRIM(HORA_HASTA_P);
    IF HORA_DESDE_V IS NULL
       OR HORA_HASTA_V IS NULL
       OR NOT REGEXP_LIKE(HORA_DESDE_V, '^([01][0-9]|2[0-3]):[0-5][0-9]$')
       OR NOT REGEXP_LIKE(HORA_HASTA_V, '^([01][0-9]|2[0-3]):[0-5][0-9]$')
       OR HORA_DESDE_V >= HORA_HASTA_V THEN
        RAISE_APPLICATION_ERROR(-20805, 'LA BANDA HORARIA NO ES VALIDA');
    END IF;
    IF VIGENTE_DESDE_P IS NULL
       OR (VIGENTE_HASTA_P IS NOT NULL
           AND TRUNC(VIGENTE_HASTA_P) < TRUNC(VIGENTE_DESDE_P)) THEN
        RAISE_APPLICATION_ERROR(-20806, 'LA VIGENCIA NO ES VALIDA');
    END IF;
    IF VALOR_HORA_P IS NULL OR VALOR_HORA_P <= 0 THEN
        RAISE_APPLICATION_ERROR(-20807, 'EL VALOR POR HORA DEBE SER MAYOR QUE CERO');
    END IF;
    VIGENTE_DESDE_V := TRUNC(VIGENTE_DESDE_P);
    IF VIGENTE_HASTA_P IS NULL THEN
        VIGENTE_HASTA_V := NULL;
    ELSE
        VIGENTE_HASTA_V := TRUNC(VIGENTE_HASTA_P) + 1 - 1/86400;
    END IF;
    BEGIN
        SELECT ID_CANCHA, ID_MODALIDAD
        INTO ID_CANCHA_V, ID_MODALIDAD_V
        FROM SGCD_TARIFAS
        WHERE ID_TARIFA = ID_TARIFA_P;
    EXCEPTION
        WHEN NO_DATA_FOUND THEN
            RAISE_APPLICATION_ERROR(-20802, 'LA TARIFA NO EXISTE');
    END;
    SELECT ID_CANCHA INTO CANCHA_ENCONTRADA_V FROM SGCD_CANCHAS_MODALIDADES
    WHERE ID_CANCHA = ID_CANCHA_V
      AND ID_MODALIDAD = ID_MODALIDAD_V
    FOR UPDATE;
    BEGIN
        SELECT VIGENTE_DESDE, ESTADO_TARIFA
        INTO INICIO_ANTERIOR_V, ESTADO_ANTERIOR_V
        FROM SGCD_TARIFAS
        WHERE ID_TARIFA = ID_TARIFA_P
        FOR UPDATE;
    EXCEPTION
        WHEN NO_DATA_FOUND THEN
            RAISE_APPLICATION_ERROR(-20802, 'LA TARIFA NO EXISTE');
    END;
    IF INICIO_ANTERIOR_V <= TRUNC(SYSDATE)
       OR VIGENTE_DESDE_V <= TRUNC(SYSDATE) THEN
        RAISE_APPLICATION_ERROR(-20810, 'UNA TARIFA INICIADA NO SE PUEDE MODIFICAR');
    END IF;
    IF ESTADO_ANTERIOR_V = 'ACTIVA' THEN
        SELECT COUNT(*) INTO CANTIDAD_V FROM SGCD_TARIFAS
        WHERE ID_CANCHA = ID_CANCHA_V
          AND ID_MODALIDAD = ID_MODALIDAD_V
          AND DIA_SEMANA = DIA_P
          AND ESTADO_TARIFA = 'ACTIVA'
          AND VIGENTE_DESDE = VIGENTE_DESDE_V
          AND HORA_DESDE < HORA_HASTA_V
          AND HORA_HASTA > HORA_DESDE_V
          AND ID_TARIFA <> ID_TARIFA_P;
        IF CANTIDAD_V > 0 THEN
            RAISE_APPLICATION_ERROR(-20808, 'EXISTE UNA BANDA AMBIGUA PARA LA MISMA VIGENCIA');
        END IF;
    END IF;
    UPDATE SGCD_TARIFAS
    SET DIA_SEMANA = DIA_P,
        HORA_DESDE = HORA_DESDE_V,
        HORA_HASTA = HORA_HASTA_V,
        VIGENTE_DESDE = VIGENTE_DESDE_V,
        VIGENTE_HASTA = VIGENTE_HASTA_V,
        VALOR_HORA = VALOR_HORA_P
    WHERE ID_TARIFA = ID_TARIFA_P;
EXCEPTION
    WHEN DUP_VAL_ON_INDEX THEN
        RAISE_APPLICATION_ERROR(-20808, 'YA EXISTE UNA TARIFA PARA ESA BANDA Y VIGENCIA');
END;
