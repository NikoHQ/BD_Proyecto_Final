CREATE OR REPLACE PROCEDURE SGCD_CAMBIAR_ESTADO_TARIFA (
    ID_TARIFA_P SGCD_TARIFAS.ID_TARIFA%TYPE,
    ESTADO_P SGCD_TARIFAS.ESTADO_TARIFA%TYPE
)
IS
    ESTADO_V SGCD_TARIFAS.ESTADO_TARIFA%TYPE;
    ID_ENCONTRADO_V SGCD_TARIFAS.ID_TARIFA%TYPE;
    ID_CANCHA_V SGCD_TARIFAS.ID_CANCHA%TYPE;
    ID_MODALIDAD_V SGCD_TARIFAS.ID_MODALIDAD%TYPE;
    DIA_V SGCD_TARIFAS.DIA_SEMANA%TYPE;
    HORA_DESDE_V SGCD_TARIFAS.HORA_DESDE%TYPE;
    HORA_HASTA_V SGCD_TARIFAS.HORA_HASTA%TYPE;
    VIGENTE_DESDE_V SGCD_TARIFAS.VIGENTE_DESDE%TYPE;
    CANCHA_ENCONTRADA_V NUMBER;
    CANTIDAD_V NUMBER;
BEGIN
    IF ID_TARIFA_P IS NULL
       OR ID_TARIFA_P <= 0
       OR ID_TARIFA_P <> TRUNC(ID_TARIFA_P) THEN
        RAISE_APPLICATION_ERROR(-20801, 'EL ID DE LA TARIFA NO ES VALIDO');
    END IF;
    ESTADO_V := UPPER(TRIM(ESTADO_P));
    IF ESTADO_V IS NULL OR ESTADO_V NOT IN ('ACTIVA', 'INACTIVA') THEN
        RAISE_APPLICATION_ERROR(-20809, 'EL ESTADO DEBE SER ACTIVA O INACTIVA');
    END IF;
    BEGIN
        SELECT ID_CANCHA, ID_MODALIDAD
        INTO ID_CANCHA_V, ID_MODALIDAD_V
        FROM SGCD_TARIFAS
        WHERE ID_TARIFA = ID_TARIFA_P;
    EXCEPTION
        WHEN NO_DATA_FOUND THEN
            RAISE_APPLICATION_ERROR(-20802, 'LA TARIFA NO EXISTE');
    END;
    SELECT ID_CANCHA INTO CANCHA_ENCONTRADA_V FROM SGCD_CANCHAS_MODALIDADES
    WHERE ID_CANCHA = ID_CANCHA_V
      AND ID_MODALIDAD = ID_MODALIDAD_V
    FOR UPDATE;
    BEGIN
        SELECT ID_TARIFA,
               ID_CANCHA,
               ID_MODALIDAD,
               DIA_SEMANA,
               HORA_DESDE,
               HORA_HASTA,
               VIGENTE_DESDE
        INTO ID_ENCONTRADO_V,
             ID_CANCHA_V,
             ID_MODALIDAD_V,
             DIA_V,
             HORA_DESDE_V,
             HORA_HASTA_V,
             VIGENTE_DESDE_V
        FROM SGCD_TARIFAS
        WHERE ID_TARIFA = ID_TARIFA_P
        FOR UPDATE;
    EXCEPTION
        WHEN NO_DATA_FOUND THEN
            RAISE_APPLICATION_ERROR(-20802, 'LA TARIFA NO EXISTE');
    END;
    IF ESTADO_V = 'ACTIVA' THEN
        SELECT COUNT(*) INTO CANTIDAD_V FROM SGCD_TARIFAS
        WHERE ID_CANCHA = ID_CANCHA_V
          AND ID_MODALIDAD = ID_MODALIDAD_V
          AND DIA_SEMANA = DIA_V
          AND ESTADO_TARIFA = 'ACTIVA'
          AND VIGENTE_DESDE = VIGENTE_DESDE_V
          AND HORA_DESDE < HORA_HASTA_V
          AND HORA_HASTA > HORA_DESDE_V
          AND ID_TARIFA <> ID_TARIFA_P;
        IF CANTIDAD_V > 0 THEN
            RAISE_APPLICATION_ERROR(-20808, 'EXISTE UNA BANDA AMBIGUA PARA LA MISMA VIGENCIA');
        END IF;
    END IF;
    UPDATE SGCD_TARIFAS
    SET ESTADO_TARIFA = ESTADO_V
    WHERE ID_TARIFA = ID_TARIFA_P;
END;
