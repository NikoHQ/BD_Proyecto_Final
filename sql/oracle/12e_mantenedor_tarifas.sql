CREATE OR REPLACE PROCEDURE SGCD_BORRAR_TARIFA (
    ID_TARIFA_P SGCD_TARIFAS.ID_TARIFA%TYPE
)
IS
    INICIO_V DATE;
BEGIN
    IF ID_TARIFA_P IS NULL
       OR ID_TARIFA_P <= 0
       OR ID_TARIFA_P <> TRUNC(ID_TARIFA_P) THEN
        RAISE_APPLICATION_ERROR(-20801, 'EL ID DE LA TARIFA NO ES VALIDO');
    END IF;
    BEGIN
        SELECT VIGENTE_DESDE INTO INICIO_V FROM SGCD_TARIFAS
        WHERE ID_TARIFA = ID_TARIFA_P
        FOR UPDATE;
    EXCEPTION
        WHEN NO_DATA_FOUND THEN
            RAISE_APPLICATION_ERROR(-20802, 'LA TARIFA NO EXISTE');
    END;
    IF INICIO_V <= TRUNC(SYSDATE) THEN
        RAISE_APPLICATION_ERROR(-20811, 'UNA TARIFA INICIADA NO SE PUEDE BORRAR');
    END IF;
    DELETE FROM SGCD_TARIFAS
    WHERE ID_TARIFA = ID_TARIFA_P;
END;
