CREATE OR REPLACE PROCEDURE SGCD_LISTAR_TARIFAS (
    ID_CANCHA_P SGCD_TARIFAS.ID_CANCHA%TYPE,
    ID_MODALIDAD_P SGCD_TARIFAS.ID_MODALIDAD%TYPE,
    ESTADO_P SGCD_TARIFAS.ESTADO_TARIFA%TYPE,
    CURSOR_P OUT SYS_REFCURSOR
)
IS
    ESTADO_V SGCD_TARIFAS.ESTADO_TARIFA%TYPE;
BEGIN
    ESTADO_V := UPPER(TRIM(ESTADO_P));
    IF ESTADO_V IS NOT NULL AND ESTADO_V NOT IN ('ACTIVA', 'INACTIVA') THEN
        RAISE_APPLICATION_ERROR(-20812, 'EL FILTRO DE ESTADO NO ES VALIDO');
    END IF;
    IF (ID_CANCHA_P IS NOT NULL
        AND (ID_CANCHA_P <= 0 OR ID_CANCHA_P <> TRUNC(ID_CANCHA_P)))
       OR (ID_MODALIDAD_P IS NOT NULL
        AND (ID_MODALIDAD_P <= 0 OR ID_MODALIDAD_P <> TRUNC(ID_MODALIDAD_P))) THEN
        RAISE_APPLICATION_ERROR(-20803, 'LOS FILTROS DE CANCHA O MODALIDAD NO SON VALIDOS');
    END IF;
    OPEN CURSOR_P FOR
        SELECT ID_TARIFA,
               ID_CANCHA,
               ID_MODALIDAD,
               DIA_SEMANA,
               HORA_DESDE,
               HORA_HASTA,
               VIGENTE_DESDE,
               VIGENTE_HASTA,
               VALOR_HORA,
               ESTADO_TARIFA
        FROM SGCD_TARIFAS
        WHERE (ID_CANCHA_P IS NULL OR ID_CANCHA = ID_CANCHA_P)
          AND (ID_MODALIDAD_P IS NULL OR ID_MODALIDAD = ID_MODALIDAD_P)
          AND (ESTADO_V IS NULL OR ESTADO_TARIFA = ESTADO_V)
        ORDER BY ID_CANCHA,
                 ID_MODALIDAD,
                 DIA_SEMANA,
                 VIGENTE_DESDE DESC,
                 HORA_DESDE;
END;
