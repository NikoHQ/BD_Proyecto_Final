-- Rango de jugadores por equipo. Repetible sobre un esquema SGCD19 existente.
SET DEFINE OFF

DECLARE
    v_columnas NUMBER;
BEGIN
    SELECT COUNT(*) INTO v_columnas FROM USER_TAB_COLUMNS
    WHERE TABLE_NAME = 'SGCD_MODALIDADES' AND COLUMN_NAME = 'MIN_JUGADORES_POR_EQUIPO';
    IF v_columnas = 0 THEN
        EXECUTE IMMEDIATE 'ALTER TABLE SGCD_MODALIDADES ADD (MIN_JUGADORES_POR_EQUIPO NUMBER(2) DEFAULT 1 NOT NULL)';
        EXECUTE IMMEDIATE 'ALTER TABLE SGCD_MODALIDADES ADD CONSTRAINT CK_SGCD_MODALIDAD_MIN_MAX CHECK (MIN_JUGADORES_POR_EQUIPO BETWEEN 1 AND MAX_JUGADORES_POR_EQUIPO)';
    END IF;
    SELECT COUNT(*) INTO v_columnas FROM USER_TAB_COLUMNS
    WHERE TABLE_NAME = 'SGCD_TORNEOS' AND COLUMN_NAME = 'MIN_JUGADORES_POR_EQUIPO';
    IF v_columnas = 0 THEN
        EXECUTE IMMEDIATE 'ALTER TABLE SGCD_TORNEOS ADD (MIN_JUGADORES_POR_EQUIPO NUMBER(2) DEFAULT 1 NOT NULL)';
        EXECUTE IMMEDIATE 'ALTER TABLE SGCD_TORNEOS ADD CONSTRAINT CK_SGCD_TORNEO_MIN_MAX CHECK (MIN_JUGADORES_POR_EQUIPO BETWEEN 1 AND MAX_JUGADORES_POR_EQUIPO)';
    END IF;
END;
/

UPDATE SGCD_MODALIDADES
SET MIN_JUGADORES_POR_EQUIPO = CASE
    WHEN NOMBRE_MODALIDAD = 'Fútbol 6' THEN 6
    WHEN NOMBRE_MODALIDAD = 'Pádel dobles' THEN 2
    WHEN NOMBRE_MODALIDAD = 'Tenis' THEN 1
    ELSE LEAST(MIN_JUGADORES_POR_EQUIPO, MAX_JUGADORES_POR_EQUIPO)
END;

UPDATE SGCD_TORNEOS t
SET MIN_JUGADORES_POR_EQUIPO = (
    SELECT m.MIN_JUGADORES_POR_EQUIPO FROM SGCD_MODALIDADES m WHERE m.ID_MODALIDAD = t.ID_MODALIDAD
);
COMMIT;
