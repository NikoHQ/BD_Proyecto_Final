-- ---------------------------------------------------------------------
-- 12. SGCD_TORNEOS - competencia por modalidad. El rango se copia de la
--     modalidad al crear y se puede ajustar por torneo.
-- ---------------------------------------------------------------------
CREATE TABLE SGCD_TORNEOS (
    ID_TORNEO                 NUMBER(10),
    ID_MODALIDAD              NUMBER(10) NOT NULL,
    NOMBRE_TORNEO             VARCHAR2(100) NOT NULL,
    FECHA_INICIO              DATE NOT NULL,
    FECHA_TERMINO             DATE NOT NULL,
    CUPOS_TORNEO              NUMBER(3) NOT NULL,
    MIN_JUGADORES_POR_EQUIPO  NUMBER(2) DEFAULT 1 NOT NULL,
    MAX_JUGADORES_POR_EQUIPO  NUMBER(2) NOT NULL,
    ESTADO_TORNEO             VARCHAR2(15) DEFAULT 'PLANIFICADO' NOT NULL,
    CONSTRAINT PK_SGCD_TORNEOS PRIMARY KEY (ID_TORNEO),
    CONSTRAINT FK_SGCD_TORNEO_MODALIDAD FOREIGN KEY (ID_MODALIDAD)
        REFERENCES SGCD_MODALIDADES (ID_MODALIDAD),
    CONSTRAINT CK_SGCD_TORNEO_FECHAS CHECK (FECHA_TERMINO >= FECHA_INICIO),
    CONSTRAINT CK_SGCD_TORNEO_CUPOS CHECK (CUPOS_TORNEO BETWEEN 1 AND 128),
    CONSTRAINT CK_SGCD_TORNEO_JUGADORES CHECK (MIN_JUGADORES_POR_EQUIPO BETWEEN 1 AND MAX_JUGADORES_POR_EQUIPO
                                                AND MAX_JUGADORES_POR_EQUIPO <= 50),
    CONSTRAINT CK_SGCD_TORNEO_ESTADO CHECK (
        ESTADO_TORNEO IN ('PLANIFICADO', 'EN_CURSO', 'FINALIZADO', 'CANCELADO')
    )
);


-- ---------------------------------------------------------------------
-- 13. SGCD_TARIFAS - valor por hora de una cancha y modalidad, por dia y
--    franja, con vigencia. El par cancha-modalidad debe existir
-- ---------------------------------------------------------------------
CREATE TABLE SGCD_TARIFAS (
    ID_TARIFA     NUMBER(10),
    ID_CANCHA     NUMBER(10) NOT NULL,
    ID_MODALIDAD  NUMBER(10) NOT NULL,
    DIA_SEMANA    NUMBER(1) NOT NULL,
    HORA_DESDE    CHAR(5) NOT NULL,
    HORA_HASTA    CHAR(5) NOT NULL,
    VIGENTE_DESDE DATE NOT NULL,
    VIGENTE_HASTA DATE,
    VALOR_HORA    NUMBER(12,2) NOT NULL,
    ESTADO_TARIFA VARCHAR2(10) DEFAULT 'ACTIVA' NOT NULL,
    CONSTRAINT PK_SGCD_TARIFAS PRIMARY KEY (ID_TARIFA),
    CONSTRAINT FK_SGCD_TARIFA_CM FOREIGN KEY (ID_CANCHA, ID_MODALIDAD)
        REFERENCES SGCD_CANCHAS_MODALIDADES (ID_CANCHA, ID_MODALIDAD),
    CONSTRAINT UQ_SGCD_TARIFA_BANDA UNIQUE (ID_CANCHA, ID_MODALIDAD, DIA_SEMANA,
                                            HORA_DESDE, VIGENTE_DESDE),
    CONSTRAINT CK_SGCD_TARIFA_DIA CHECK (DIA_SEMANA BETWEEN 1 AND 7),
    CONSTRAINT CK_SGCD_TARIFA_DESDE
        CHECK (REGEXP_LIKE(HORA_DESDE, '^([01][0-9]|2[0-3]):[0-5][0-9]$')),
    CONSTRAINT CK_SGCD_TARIFA_HASTA
        CHECK (REGEXP_LIKE(HORA_HASTA, '^([01][0-9]|2[0-3]):[0-5][0-9]$')),
    CONSTRAINT CK_SGCD_TARIFA_HORAS CHECK (HORA_DESDE < HORA_HASTA),
    CONSTRAINT CK_SGCD_TARIFA_VIGENCIA
        CHECK (VIGENTE_HASTA IS NULL OR VIGENTE_HASTA >= VIGENTE_DESDE),
    CONSTRAINT CK_SGCD_TARIFA_VALOR CHECK (VALOR_HORA > 0),
    CONSTRAINT CK_SGCD_TARIFA_ESTADO CHECK (ESTADO_TARIFA IN ('ACTIVA', 'INACTIVA'))
);


