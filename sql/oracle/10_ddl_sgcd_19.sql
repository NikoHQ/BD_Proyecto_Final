-- =====================================================================
-- AUDITORIA DE LA FICHA DEL CLIENTE
--
-- VALORES_ANTERIORES y VALORES_NUEVOS guardan solo los campos que cambiaron,
-- como un objeto JSON plano:  {"nombre":"Ana Perez","correo":"ana@nuevo.cl"}
-- El campo nulo se escribe como null. Al borrar, NUEVOS queda nulo y
-- ANTERIORES lleva el retrato completo de la ficha.
-- Quien hizo el cambio llega en CLIENT_IDENTIFIER: la API PHP ya publica el
-- ID del administrador de la sesion con DBMS_SESSION.SET_IDENTIFIER.
-- =====================================================================

CREATE OR REPLACE FUNCTION SGCD_JSON_TEXTO (P_TEXTO VARCHAR2) RETURN VARCHAR2 IS
BEGIN
    IF P_TEXTO IS NULL THEN
        RETURN 'null';
    END IF;
    RETURN '"' || REPLACE(REPLACE(P_TEXTO, '\', '\\'), '"', '\"') || '"';
END;
/

CREATE OR REPLACE TRIGGER TRG_SGCD_CLIENTES_AU
AFTER UPDATE ON SGCD_CLIENTES
FOR EACH ROW
DECLARE
    V_ANT    VARCHAR2(4000);
    V_NUE    VARCHAR2(4000);
    V_ADMIN  NUMBER(10);
    V_CAMBIO BOOLEAN := FALSE;

    PROCEDURE AGREGAR (P_CLAVE VARCHAR2, P_VIEJO VARCHAR2, P_NUEVO VARCHAR2) IS
    BEGIN
        IF (P_VIEJO IS NULL AND P_NUEVO IS NULL) OR P_VIEJO = P_NUEVO THEN
            RETURN;
        END IF;
        V_CAMBIO := TRUE;
        V_ANT := V_ANT || CASE WHEN V_ANT IS NULL THEN '' ELSE ',' END
                 || '"' || P_CLAVE || '":' || SGCD_JSON_TEXTO(P_VIEJO);
        V_NUE := V_NUE || CASE WHEN V_NUE IS NULL THEN '' ELSE ',' END
                 || '"' || P_CLAVE || '":' || SGCD_JSON_TEXTO(P_NUEVO);
    END AGREGAR;
BEGIN
    AGREGAR('nombre',   :OLD.NOMBRE_CLIENTE,   :NEW.NOMBRE_CLIENTE);
    AGREGAR('telefono', :OLD.TELEFONO_CLIENTE, :NEW.TELEFONO_CLIENTE);
    AGREGAR('correo',   :OLD.CORREO_CLIENTE,   :NEW.CORREO_CLIENTE);
    AGREGAR('estado',   :OLD.ESTADO_CLIENTE,   :NEW.ESTADO_CLIENTE);
    IF NOT V_CAMBIO THEN
        RETURN;
    END IF;
    IF REGEXP_LIKE(NVL(SYS_CONTEXT('USERENV', 'CLIENT_IDENTIFIER'), 'x'), '^[0-9]{1,10}$') THEN
        V_ADMIN := TO_NUMBER(SYS_CONTEXT('USERENV', 'CLIENT_IDENTIFIER'));
    END IF;
    INSERT INTO SGCD_AUDITORIA_CLIENTES (
        ID_CLIENTE, ID_ADMINISTRADOR, ACCION, FECHA_EVENTO,
        VALORES_ANTERIORES, VALORES_NUEVOS)
    VALUES (
        :OLD.ID_CLIENTE, V_ADMIN, 'UPDATE', SYSTIMESTAMP,
        '{' || V_ANT || '}', '{' || V_NUE || '}');
END;
/

CREATE OR REPLACE TRIGGER TRG_SGCD_CLIENTES_AD
AFTER DELETE ON SGCD_CLIENTES
FOR EACH ROW
DECLARE
    V_ANT   VARCHAR2(4000);
    V_ADMIN NUMBER(10);
BEGIN
    V_ANT := '{' ||
        '"nombre":'   || SGCD_JSON_TEXTO(:OLD.NOMBRE_CLIENTE)   || ',' ||
        '"telefono":' || SGCD_JSON_TEXTO(:OLD.TELEFONO_CLIENTE) || ',' ||
        '"correo":'   || SGCD_JSON_TEXTO(:OLD.CORREO_CLIENTE)   || ',' ||
        '"estado":'   || SGCD_JSON_TEXTO(:OLD.ESTADO_CLIENTE)   || '}';
    IF REGEXP_LIKE(NVL(SYS_CONTEXT('USERENV', 'CLIENT_IDENTIFIER'), 'x'), '^[0-9]{1,10}$') THEN
        V_ADMIN := TO_NUMBER(SYS_CONTEXT('USERENV', 'CLIENT_IDENTIFIER'));
    END IF;
    INSERT INTO SGCD_AUDITORIA_CLIENTES (
        ID_CLIENTE, ID_ADMINISTRADOR, ACCION, FECHA_EVENTO,
        VALORES_ANTERIORES, VALORES_NUEVOS)
    VALUES (
        :OLD.ID_CLIENTE, V_ADMIN, 'DELETE', SYSTIMESTAMP, V_ANT, NULL);
END;
/


