-- =====================================================================
-- SISTEMA DE GESTION DE CENTROS DEPORTIVOS - SGCD
-- DDL Oracle 26ai Free - MODELO OBJETIVO DE 19 TABLAS
--
-- Fuente del modelo: UML oficial del equipo (03 Tercera forma normal),
-- docs/modelo/uml-equipo-19/UML_objetivo.mdj, y el DDL de Pablo
-- (23-11-26/tablas.sql). Este archivo agrega lo que ese DDL no traia:
-- NOT NULL, DEFAULT, CHECK, FK, indices, secuencias y triggers.
--
-- Orden de ejecucion en una base vacia:
--   10_ddl_sgcd_19.sql -> 11_catalogos_sgcd_19.sql -> 12_paquetes_sgcd_19.sql
--
-- Este script es autocontenido y re-ejecutable: borra las tablas SGCD_* y las
-- secuencias SGCD_SEQ_* del esquema actual (datos incluidos) antes de crearlas.
-- No toca otros esquemas.
--
-- Decisiones aplicadas (2026-11-23):
--   * 19 tablas. Membresias, puntos, implementos y operador salen del alcance.
--   * Un solo recinto; seis canchas de futbol 6 y una grande compuesta por
--     las canchas 1, 2 y 3 mediante SGCD_CANCHAS_COMPONENTES.
--   * SGCD_USUARIOS reemplaza a SGCD_CREDENCIALES. ROL solo ADMINISTRADOR o
--     CLIENTE; CLIENTE y ADMINISTRADOR apuntan a su cuenta con ID_USUARIO.
--   * TARIFA conserva ID_MODALIDAD, como el UML.
--   * PAGO es unico por reserva (UQ sobre ID_RESERVA).
--   * AUDITORIA_CLIENTE guarda los valores anteriores y nuevos como JSON
--     (ver el trigger TRG_SGCD_CLIENTES_AU al final del archivo).
--   * Las llaves las genera Oracle con SGCD_SEQ_* + trigger BEFORE INSERT.
--
-- Reglas de escritura: sin lineas en blanco dentro de cada sentencia, porque
-- SQL*Plus con SQLBLANKLINES OFF corta la sentencia en la linea vacia.
-- =====================================================================


SET DEFINE OFF


-- ---------------------------------------------------------------------
-- 0. Limpieza: borra cualquier tabla SGCD_* y secuencia SGCD_SEQ_* previa
-- ---------------------------------------------------------------------
DECLARE
    V_OWNER VARCHAR2(30) := SYS_CONTEXT('USERENV', 'CURRENT_SCHEMA');
BEGIN
    FOR T IN (SELECT TABLE_NAME FROM ALL_TABLES
              WHERE OWNER = V_OWNER AND TABLE_NAME LIKE 'SGCD\_%' ESCAPE '\') LOOP
        EXECUTE IMMEDIATE 'DROP TABLE ' || V_OWNER || '.' || T.TABLE_NAME || ' CASCADE CONSTRAINTS';
    END LOOP;
    FOR S IN (SELECT SEQUENCE_NAME FROM ALL_SEQUENCES
              WHERE SEQUENCE_OWNER = V_OWNER AND SEQUENCE_NAME LIKE 'SGCD\_SEQ\_%' ESCAPE '\') LOOP
        EXECUTE IMMEDIATE 'DROP SEQUENCE ' || V_OWNER || '.' || S.SEQUENCE_NAME;
    END LOOP;
END;
/


-- ---------------------------------------------------------------------
-- 1. SGCD_RECINTOS - el establecimiento. El modelo objetivo usa uno solo
-- ---------------------------------------------------------------------
CREATE TABLE SGCD_RECINTOS (
    ID_RECINTO        NUMBER(10),
    NOMBRE_RECINTO    VARCHAR2(100) NOT NULL,
    DIRECCION_RECINTO VARCHAR2(150) NOT NULL,
    ESTADO_RECINTO    VARCHAR2(10) DEFAULT 'ACTIVO' NOT NULL,
    CONSTRAINT PK_SGCD_RECINTOS PRIMARY KEY (ID_RECINTO),
    CONSTRAINT UQ_SGCD_RECINTO_NOMBRE UNIQUE (NOMBRE_RECINTO),
    CONSTRAINT CK_SGCD_RECINTO_ESTADO CHECK (ESTADO_RECINTO IN ('ACTIVO', 'INACTIVO'))
);


-- ---------------------------------------------------------------------
-- 2. SGCD_DEPORTES - futbol, tenis y padel
-- ---------------------------------------------------------------------
CREATE TABLE SGCD_DEPORTES (
    ID_DEPORTE     NUMBER(10),
    NOMBRE_DEPORTE VARCHAR2(50) NOT NULL,
    ESTADO_DEPORTE VARCHAR2(10) DEFAULT 'ACTIVO' NOT NULL,
    CONSTRAINT PK_SGCD_DEPORTES PRIMARY KEY (ID_DEPORTE),
    CONSTRAINT UQ_SGCD_DEPORTE_NOMBRE UNIQUE (NOMBRE_DEPORTE),
    CONSTRAINT CK_SGCD_DEPORTE_ESTADO CHECK (ESTADO_DEPORTE IN ('ACTIVO', 'INACTIVO'))
);


-- ---------------------------------------------------------------------
-- 3. SGCD_USUARIOS - el acceso. ROL define el portal: administracion o cliente
-- ---------------------------------------------------------------------
CREATE TABLE SGCD_USUARIOS (
    ID_USUARIO     NUMBER(10),
    LOGIN          VARCHAR2(50) NOT NULL,
    CLAVE_HASH     VARCHAR2(255) NOT NULL,
    ROL            VARCHAR2(20) NOT NULL,
    ESTADO_USUARIO VARCHAR2(10) DEFAULT 'ACTIVO' NOT NULL,
    CONSTRAINT PK_SGCD_USUARIOS PRIMARY KEY (ID_USUARIO),
    CONSTRAINT UQ_SGCD_USUARIO_LOGIN UNIQUE (LOGIN),
    CONSTRAINT CK_SGCD_USUARIO_LOGIN CHECK (
        LOGIN = LOWER(LOGIN)
        AND REGEXP_LIKE(LOGIN, '^[a-z0-9._-]{3,50}$')
    ),
    CONSTRAINT CK_SGCD_USUARIO_ROL CHECK (ROL IN ('ADMINISTRADOR', 'CLIENTE')),
    CONSTRAINT CK_SGCD_USUARIO_ESTADO CHECK (ESTADO_USUARIO IN ('ACTIVO', 'INACTIVO'))
);


-- ---------------------------------------------------------------------
-- 4. SGCD_HORARIOS - apertura y cierre por dia. Sin fila = cerrado
-- ---------------------------------------------------------------------
CREATE TABLE SGCD_HORARIOS (
    ID_HORARIO    NUMBER(10),
    ID_RECINTO    NUMBER(10) NOT NULL,
    DIA_SEMANA    NUMBER(1) NOT NULL,
    HORA_APERTURA CHAR(5) NOT NULL,
    HORA_CIERRE   CHAR(5) NOT NULL,
    CONSTRAINT PK_SGCD_HORARIOS PRIMARY KEY (ID_HORARIO),
    CONSTRAINT FK_SGCD_HORARIO_RECINTO FOREIGN KEY (ID_RECINTO)
        REFERENCES SGCD_RECINTOS (ID_RECINTO),
    CONSTRAINT UQ_SGCD_HORARIO_RECINTO_DIA UNIQUE (ID_RECINTO, DIA_SEMANA),
    CONSTRAINT CK_SGCD_HORARIO_DIA CHECK (DIA_SEMANA BETWEEN 1 AND 7),
    CONSTRAINT CK_SGCD_HORARIO_APERTURA
        CHECK (REGEXP_LIKE(HORA_APERTURA, '^([01][0-9]|2[0-3]):[0-5][0-9]$')),
    CONSTRAINT CK_SGCD_HORARIO_CIERRE
        CHECK (REGEXP_LIKE(HORA_CIERRE, '^([01][0-9]|2[0-3]):[0-5][0-9]$')),
    CONSTRAINT CK_SGCD_HORARIO_RANGO CHECK (HORA_APERTURA < HORA_CIERRE)
);


-- ---------------------------------------------------------------------
-- 5. SGCD_CANCHAS - las canchas fisicas del recinto, incluida la grande
