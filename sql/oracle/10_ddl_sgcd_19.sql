    CONSTRAINT PK_SGCD_MODALIDADES PRIMARY KEY (ID_MODALIDAD),
    CONSTRAINT FK_SGCD_MODALIDAD_DEPORTE FOREIGN KEY (ID_DEPORTE)
        REFERENCES SGCD_DEPORTES (ID_DEPORTE),
    CONSTRAINT UQ_SGCD_MODALIDAD_NOMBRE UNIQUE (ID_DEPORTE, NOMBRE_MODALIDAD),
    CONSTRAINT CK_SGCD_MODALIDAD_JUGADORES CHECK (MIN_JUGADORES_POR_EQUIPO BETWEEN 1 AND MAX_JUGADORES_POR_EQUIPO
                                                   AND MAX_JUGADORES_POR_EQUIPO <= 50),
    CONSTRAINT CK_SGCD_MODALIDAD_ESTADO CHECK (ESTADO_MODALIDAD IN ('ACTIVO', 'INACTIVO'))
);


-- ---------------------------------------------------------------------
-- 7. SGCD_CLIENTES - la ficha. ID_USUARIO es opcional: el cliente presencial
--    existe sin cuenta. El RUT identifica; no autentica
-- ---------------------------------------------------------------------
CREATE TABLE SGCD_CLIENTES (
    ID_CLIENTE       NUMBER(10),
    ID_USUARIO       NUMBER(10),
    RUT_CLIENTE      NUMBER(8) NOT NULL,
    DV_CLIENTE       CHAR(1) NOT NULL,
    NOMBRE_CLIENTE   VARCHAR2(100) NOT NULL,
    CORREO_CLIENTE   VARCHAR2(150),
    TELEFONO_CLIENTE VARCHAR2(20),
    ESTADO_CLIENTE   VARCHAR2(10) DEFAULT 'ACTIVO' NOT NULL,
    CONSTRAINT PK_SGCD_CLIENTES PRIMARY KEY (ID_CLIENTE),
    CONSTRAINT FK_SGCD_CLIENTE_USUARIO FOREIGN KEY (ID_USUARIO)
        REFERENCES SGCD_USUARIOS (ID_USUARIO),
    CONSTRAINT UQ_SGCD_CLIENTE_USUARIO UNIQUE (ID_USUARIO),
    CONSTRAINT UQ_SGCD_CLIENTE_RUT UNIQUE (RUT_CLIENTE, DV_CLIENTE),
    CONSTRAINT UQ_SGCD_CLIENTE_CORREO UNIQUE (CORREO_CLIENTE),
    CONSTRAINT CK_SGCD_CLIENTE_RUT CHECK (RUT_CLIENTE BETWEEN 1 AND 99999999),
    CONSTRAINT CK_SGCD_CLIENTE_DV CHECK (REGEXP_LIKE(DV_CLIENTE, '^[0-9K]$')),
    CONSTRAINT CK_SGCD_CLIENTE_CORREO CHECK (
        CORREO_CLIENTE IS NULL
        OR (CORREO_CLIENTE = LOWER(CORREO_CLIENTE)
            AND REGEXP_LIKE(CORREO_CLIENTE, '^[^@[:space:]]+@[^@[:space:]]+\.[[:alpha:]]{2,}$'))
    ),
    CONSTRAINT CK_SGCD_CLIENTE_ESTADO CHECK (ESTADO_CLIENTE IN ('ACTIVO', 'INACTIVO'))
);


-- ---------------------------------------------------------------------
-- 8. SGCD_ADMINISTRADORES - ficha del personal. La cuenta es obligatoria
