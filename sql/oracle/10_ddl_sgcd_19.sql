);


-- ---------------------------------------------------------------------
-- 6. SGCD_MODALIDADES - depende del deporte. El rango incluye al capitan.
-- ---------------------------------------------------------------------
CREATE TABLE SGCD_MODALIDADES (
    ID_MODALIDAD              NUMBER(10),
    ID_DEPORTE                NUMBER(10) NOT NULL,
    NOMBRE_MODALIDAD          VARCHAR2(80) NOT NULL,
