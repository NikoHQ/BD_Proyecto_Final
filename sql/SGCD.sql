WHENEVER OSERROR EXIT FAILURE ROLLBACK
WHENEVER SQLERROR EXIT FAILURE ROLLBACK
SET DEFINE OFF
SET SQLBLANKLINES ON
SET SERVEROUTPUT ON

DECLARE
    v_objetos NUMBER;
BEGIN
    SELECT COUNT(*) INTO v_objetos
    FROM USER_OBJECTS
    WHERE OBJECT_NAME LIKE 'SGCD%' OR OBJECT_NAME LIKE 'TRG_SGCD%';
    IF SYS_CONTEXT('USERENV', 'SESSION_USER') IN ('SYS', 'SYSTEM')
       OR SYS_CONTEXT('USERENV', 'SESSION_USER') <> SYS_CONTEXT('USERENV', 'CURRENT_SCHEMA')
       OR v_objetos > 0 THEN
        RAISE_APPLICATION_ERROR(-20999, 'Ejecute el script en un esquema propio sin objetos SGCD');
    END IF;
END;
/

-- 01. Modelo físico, secuencias y triggers

CREATE TABLE SGCD_RECINTOS (
    ID_RECINTO        NUMBER(10),
    NOMBRE_RECINTO    VARCHAR2(100) NOT NULL,
    DIRECCION_RECINTO VARCHAR2(150) NOT NULL,
    ESTADO_RECINTO    VARCHAR2(10) DEFAULT 'ACTIVO' NOT NULL,
    CONSTRAINT PK_SGCD_RECINTOS PRIMARY KEY (ID_RECINTO),
    CONSTRAINT UQ_SGCD_RECINTO_NOMBRE UNIQUE (NOMBRE_RECINTO),
    CONSTRAINT CK_SGCD_RECINTO_ESTADO CHECK (ESTADO_RECINTO IN ('ACTIVO', 'INACTIVO'))
);

CREATE TABLE SGCD_DEPORTES (
    ID_DEPORTE     NUMBER(10),
    NOMBRE_DEPORTE VARCHAR2(50) NOT NULL,
    ESTADO_DEPORTE VARCHAR2(10) DEFAULT 'ACTIVO' NOT NULL,
    CONSTRAINT PK_SGCD_DEPORTES PRIMARY KEY (ID_DEPORTE),
    CONSTRAINT UQ_SGCD_DEPORTE_NOMBRE UNIQUE (NOMBRE_DEPORTE),
    CONSTRAINT CK_SGCD_DEPORTE_ESTADO CHECK (ESTADO_DEPORTE IN ('ACTIVO', 'INACTIVO'))
);

CREATE TABLE SGCD_USUARIOS (
    ID_USUARIO     NUMBER(10),
    LOGIN          VARCHAR2(50) NOT NULL,
    CLAVE_HASH     VARCHAR2(255) NOT NULL,
    ROL            VARCHAR2(20) NOT NULL,
    ESTADO_USUARIO VARCHAR2(10) DEFAULT 'ACTIVO' NOT NULL,
    CONSTRAINT PK_SGCD_USUARIOS PRIMARY KEY (ID_USUARIO),
    CONSTRAINT UQ_SGCD_USUARIO_LOGIN UNIQUE (LOGIN),
    CONSTRAINT CK_SGCD_USUARIO_LOGIN CHECK (
        LOGIN = LOWER(LOGIN)
        AND REGEXP_LIKE(LOGIN, '^[a-z0-9._-]{3,50}$')
    ),
    CONSTRAINT CK_SGCD_USUARIO_ROL CHECK (ROL IN ('ADMINISTRADOR', 'CLIENTE')),
    CONSTRAINT CK_SGCD_USUARIO_ESTADO CHECK (ESTADO_USUARIO IN ('ACTIVO', 'INACTIVO'))
);

CREATE TABLE SGCD_HORARIOS (
    ID_HORARIO    NUMBER(10),
    ID_RECINTO    NUMBER(10) NOT NULL,
    DIA_SEMANA    NUMBER(1) NOT NULL,
    HORA_APERTURA CHAR(5) NOT NULL,
    HORA_CIERRE   CHAR(5) NOT NULL,
    CONSTRAINT PK_SGCD_HORARIOS PRIMARY KEY (ID_HORARIO),
    CONSTRAINT FK_SGCD_HORARIO_RECINTO FOREIGN KEY (ID_RECINTO)
        REFERENCES SGCD_RECINTOS (ID_RECINTO),
    CONSTRAINT UQ_SGCD_HORARIO_RECINTO_DIA UNIQUE (ID_RECINTO, DIA_SEMANA),
    CONSTRAINT CK_SGCD_HORARIO_DIA CHECK (DIA_SEMANA BETWEEN 1 AND 7),
    CONSTRAINT CK_SGCD_HORARIO_APERTURA
        CHECK (REGEXP_LIKE(HORA_APERTURA, '^([01][0-9]|2[0-3]):[0-5][0-9]$')),
    CONSTRAINT CK_SGCD_HORARIO_CIERRE
        CHECK (REGEXP_LIKE(HORA_CIERRE, '^([01][0-9]|2[0-3]):[0-5][0-9]$')),
    CONSTRAINT CK_SGCD_HORARIO_RANGO CHECK (HORA_APERTURA < HORA_CIERRE)
);

CREATE TABLE SGCD_CANCHAS (
    ID_CANCHA     NUMBER(10),
    ID_RECINTO    NUMBER(10) NOT NULL,
    NOMBRE_CANCHA VARCHAR2(100) NOT NULL,
    TIPO_CANCHA   VARCHAR2(20) NOT NULL,
    ESTADO_CANCHA VARCHAR2(15) DEFAULT 'DISPONIBLE' NOT NULL,
    CONSTRAINT PK_SGCD_CANCHAS PRIMARY KEY (ID_CANCHA),
    CONSTRAINT FK_SGCD_CANCHA_RECINTO FOREIGN KEY (ID_RECINTO)
        REFERENCES SGCD_RECINTOS (ID_RECINTO),
    CONSTRAINT UQ_SGCD_CANCHA_NOMBRE UNIQUE (ID_RECINTO, NOMBRE_CANCHA),
    CONSTRAINT CK_SGCD_CANCHA_ESTADO CHECK (ESTADO_CANCHA IN ('DISPONIBLE', 'MANTENCION', 'INACTIVA'))
);

CREATE TABLE SGCD_MODALIDADES (
    ID_MODALIDAD              NUMBER(10),
    ID_DEPORTE                NUMBER(10) NOT NULL,
    NOMBRE_MODALIDAD          VARCHAR2(80) NOT NULL,
    MIN_JUGADORES_POR_EQUIPO  NUMBER(2) DEFAULT 1 NOT NULL,
    MAX_JUGADORES_POR_EQUIPO  NUMBER(2) NOT NULL,
    ESTADO_MODALIDAD          VARCHAR2(10) DEFAULT 'ACTIVO' NOT NULL,
    CONSTRAINT PK_SGCD_MODALIDADES PRIMARY KEY (ID_MODALIDAD),
    CONSTRAINT FK_SGCD_MODALIDAD_DEPORTE FOREIGN KEY (ID_DEPORTE)
        REFERENCES SGCD_DEPORTES (ID_DEPORTE),
    CONSTRAINT UQ_SGCD_MODALIDAD_NOMBRE UNIQUE (ID_DEPORTE, NOMBRE_MODALIDAD),
    CONSTRAINT CK_SGCD_MODALIDAD_JUGADORES CHECK (MIN_JUGADORES_POR_EQUIPO BETWEEN 1 AND MAX_JUGADORES_POR_EQUIPO
                                                   AND MAX_JUGADORES_POR_EQUIPO <= 50),
    CONSTRAINT CK_SGCD_MODALIDAD_ESTADO CHECK (ESTADO_MODALIDAD IN ('ACTIVO', 'INACTIVO'))
);

CREATE TABLE SGCD_CLIENTES (
    ID_CLIENTE       NUMBER(10),
    ID_USUARIO       NUMBER(10),
    RUT_CLIENTE      NUMBER(8) NOT NULL,
    DV_CLIENTE       CHAR(1) NOT NULL,
    NOMBRE_CLIENTE   VARCHAR2(100) NOT NULL,
    CORREO_CLIENTE   VARCHAR2(150),
    TELEFONO_CLIENTE VARCHAR2(20),
    ESTADO_CLIENTE   VARCHAR2(10) DEFAULT 'ACTIVO' NOT NULL,
    CONSTRAINT PK_SGCD_CLIENTES PRIMARY KEY (ID_CLIENTE),
    CONSTRAINT FK_SGCD_CLIENTE_USUARIO FOREIGN KEY (ID_USUARIO)
        REFERENCES SGCD_USUARIOS (ID_USUARIO),
    CONSTRAINT UQ_SGCD_CLIENTE_USUARIO UNIQUE (ID_USUARIO),
    CONSTRAINT UQ_SGCD_CLIENTE_RUT UNIQUE (RUT_CLIENTE, DV_CLIENTE),
    CONSTRAINT UQ_SGCD_CLIENTE_CORREO UNIQUE (CORREO_CLIENTE),
    CONSTRAINT CK_SGCD_CLIENTE_RUT CHECK (RUT_CLIENTE BETWEEN 1 AND 99999999),
    CONSTRAINT CK_SGCD_CLIENTE_DV CHECK (REGEXP_LIKE(DV_CLIENTE, '^[0-9K]$')),
    CONSTRAINT CK_SGCD_CLIENTE_CORREO CHECK (
        CORREO_CLIENTE IS NULL
        OR (CORREO_CLIENTE = LOWER(CORREO_CLIENTE)
            AND REGEXP_LIKE(CORREO_CLIENTE, '^[^@[:space:]]+@[^@[:space:]]+\.[[:alpha:]]{2,}$'))
    ),
    CONSTRAINT CK_SGCD_CLIENTE_ESTADO CHECK (ESTADO_CLIENTE IN ('ACTIVO', 'INACTIVO'))
);

CREATE TABLE SGCD_ADMINISTRADORES (
