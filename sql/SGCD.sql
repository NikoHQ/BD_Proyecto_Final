CREATE TABLE SGCD_RESERVAS (
    ID_RESERVA       NUMBER(10),
    ID_CLIENTE       NUMBER(10),
    ID_ADMINISTRADOR NUMBER(10),
    ID_CANCHA        NUMBER(10) NOT NULL,
    ID_MODALIDAD     NUMBER(10) NOT NULL,
    ID_TORNEO        NUMBER(10),
    INICIO_RESERVA   DATE NOT NULL,
    TERMINO_RESERVA  DATE NOT NULL,
    IMPORTE_ACORDADO NUMBER(12,2) NOT NULL,
    ORIGEN_RESERVA   VARCHAR2(10) DEFAULT 'MOSTRADOR' NOT NULL,
    ESTADO_RESERVA   VARCHAR2(15) DEFAULT 'PENDIENTE' NOT NULL,
    CONSTRAINT PK_SGCD_RESERVAS PRIMARY KEY (ID_RESERVA),
    CONSTRAINT FK_SGCD_RESERVA_CLIENTE FOREIGN KEY (ID_CLIENTE)
        REFERENCES SGCD_CLIENTES (ID_CLIENTE),
    CONSTRAINT FK_SGCD_RESERVA_ADMINISTRADOR FOREIGN KEY (ID_ADMINISTRADOR)
        REFERENCES SGCD_ADMINISTRADORES (ID_ADMINISTRADOR),
    CONSTRAINT FK_SGCD_RESERVA_CM FOREIGN KEY (ID_CANCHA, ID_MODALIDAD)
        REFERENCES SGCD_CANCHAS_MODALIDADES (ID_CANCHA, ID_MODALIDAD),
    CONSTRAINT FK_SGCD_RESERVA_TORNEO FOREIGN KEY (ID_TORNEO)
        REFERENCES SGCD_TORNEOS (ID_TORNEO),
    CONSTRAINT CK_SGCD_RESERVA_FECHAS CHECK (TERMINO_RESERVA > INICIO_RESERVA),
    CONSTRAINT CK_SGCD_RESERVA_IMPORTE CHECK (IMPORTE_ACORDADO >= 0),
    CONSTRAINT CK_SGCD_RESERVA_ORIGEN CHECK (ORIGEN_RESERVA IN ('MOSTRADOR', 'WEB', 'TORNEO')),
    CONSTRAINT CK_SGCD_RESERVA_ESTADO CHECK (
        ESTADO_RESERVA IN ('PENDIENTE', 'CONFIRMADA', 'COMPLETADA', 'CANCELADA')
    ),
    CONSTRAINT CK_SGCD_RESERVA_DUENO CHECK (ID_CLIENTE IS NOT NULL OR ID_TORNEO IS NOT NULL),
    CONSTRAINT CK_SGCD_RESERVA_TORNEO_ORIGEN CHECK (
        ORIGEN_RESERVA <> 'TORNEO' OR ID_TORNEO IS NOT NULL
    )
);

