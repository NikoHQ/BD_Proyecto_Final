-- Divide una tarifa futura en la misma transaccion y conserva su estado.
CREATE OR REPLACE PROCEDURE SGCD_DIVIDIR_TARIFA (
    P_ID SGCD_TARIFAS.ID_TARIFA%TYPE,
    P_HORA SGCD_TARIFAS.HORA_HASTA%TYPE,
    P_VALOR SGCD_TARIFAS.VALOR_HORA%TYPE,
    P_NUEVA OUT SGCD_TARIFAS.ID_TARIFA%TYPE
)
IS
    V_TARIFA SGCD_TARIFAS%ROWTYPE;
    V_CANCHA SGCD_TARIFAS.ID_CANCHA%TYPE;
    V_MODALIDAD SGCD_TARIFAS.ID_MODALIDAD%TYPE;
BEGIN
    SELECT ID_CANCHA, ID_MODALIDAD INTO V_CANCHA, V_MODALIDAD
    FROM SGCD_TARIFAS WHERE ID_TARIFA = P_ID;
    -- Mismo orden de bloqueo que SGCD_ACTUALIZAR_TARIFA.
    SELECT ID_CANCHA INTO V_CANCHA
    FROM SGCD_CANCHAS_MODALIDADES
    WHERE ID_CANCHA = V_CANCHA AND ID_MODALIDAD = V_MODALIDAD
    FOR UPDATE;
    SELECT * INTO V_TARIFA FROM SGCD_TARIFAS WHERE ID_TARIFA = P_ID FOR UPDATE;
    IF V_TARIFA.ESTADO_TARIFA <> 'ACTIVA' THEN
        RAISE_APPLICATION_ERROR(-20809, 'Active la tarifa antes de dividirla');
    END IF;
    IF P_HORA IS NULL OR P_HORA <= V_TARIFA.HORA_DESDE OR P_HORA >= V_TARIFA.HORA_HASTA THEN
        RAISE_APPLICATION_ERROR(-20805, 'La hora de corte debe estar dentro de la banda');
    END IF;
    SGCD_ACTUALIZAR_TARIFA(P_ID, V_TARIFA.DIA_SEMANA, V_TARIFA.HORA_DESDE, P_HORA,
        V_TARIFA.VIGENTE_DESDE, V_TARIFA.VIGENTE_HASTA, V_TARIFA.VALOR_HORA);
    SGCD_CREAR_TARIFA(V_TARIFA.ID_CANCHA, V_TARIFA.ID_MODALIDAD, V_TARIFA.DIA_SEMANA,
        P_HORA, V_TARIFA.HORA_HASTA, V_TARIFA.VIGENTE_DESDE, V_TARIFA.VIGENTE_HASTA, P_VALOR, P_NUEVA);
EXCEPTION
    WHEN NO_DATA_FOUND THEN
        RAISE_APPLICATION_ERROR(-20802, 'La tarifa no existe');
END;
